def cluster_part(budget: Budget) -> dict[str, Any]:
    """Propagate epistemic uncertainty to the success of a nine-engine cluster.

    Args:
        budget: Sample sizes.

    Returns:
        The reliability distribution.

    References:
        [EQ-AERO-REL-011], [REF-MOSLEH-ETAL-1998], [REF-NASA-PRA-2011].

    """
    headline("(e) engine cluster: mission reliability distribution")
    prior = heritage_prior(99, 1, weight=0.5)
    outage = Beta(prior.beta, prior.alpha)
    print(
        f"heritage prior on engine reliability: Beta({prior.alpha:.1f}, "
        f"{prior.beta:.1f}); "
        f"outage law Beta({outage.alpha:.1f}, {outage.beta:.1f}) mean "
        f"{float(outage.mean):.4f}"
    )
    uncertainty = ClusterUncertainty(9, 8, outage, Beta(2.0, 18.0), Beta(3.0, 7.0))
    plug = EngineClusterModel(9, 8, float(outage.mean), 0.1, 0.3).success_probability()
    distribution = cluster_reliability_distribution(
        uncertainty,
        samples=budget.cluster_samples,
        sobol_samples=budget.cluster_sobol,
        seed=SEED,
    )
    exact_mean, exact_variance = cluster_reliability_moments(uncertainty)
    low, high = distribution.interval
    print(
        f"cluster success (9 engines, 8 required): plug-in at the means={plug:.5f}; "
        f"exact mean={exact_mean:.5f} sd={math.sqrt(exact_variance):.5f}"
    )
    print(
        f"  Monte Carlo ({budget.cluster_samples}): mean={distribution.mean:.5f} "
        f"sd={distribution.standard_deviation:.5f} {distribution.level:.0%} interval "
        f"[{low:.5f}, {high:.5f}]"
    )
    for name, first, total in zip(
        distribution.input_names,
        distribution.sobol_first or (),
        distribution.sobol_total or (),
        strict=True,
    ):
        print(f"  Sobol {name:20s} S1={first:.3f} ST={total:.3f}")
    print(f"  ranking: {distribution.ranking}")
    return {
        "distribution": distribution,
        "plug": plug,
        "exact": (exact_mean, exact_variance),
    }


