"""Rocket-propulsion uncertainty laboratory: five synthetic cases, one seed.

Run with ``PYTHONPATH=src python examples/rocket_propulsion_uq_lab.py``. The
lab applies the library's propagation, sensitivity, rare-event, Bayesian
calibration, model-selection and surrogate tools to the physical models of
``probstat.aerospace``: (a) a liquid engine (dispersion of vacuum specific
impulse and thrust, Sobol ranking, probability of missing an impulse
requirement by FORM, subset simulation and Monte Carlo), (b) a solid motor
(impulse dispersion, probability that the peak chamber pressure exceeds the
case burst pressure, FORM sensitivities of the burst margin), (c) Bayesian
calibration of the burn-rate law from synthetic static-fire pressures by
transitional MCMC with posterior predictive peak pressure and Bayesian model
class selection, (d) thermoacoustic instability (Monte Carlo against a
Gaussian-process surrogate with Bastos-O'Hagan validation and GP-based Sobol
indices), and (e) the success probability of an engine cluster under
epistemic uncertainty. Every number is printed; with Matplotlib installed
three figures are written to ``examples/generated/``.

EVERY CASE IS SYNTHETIC. The propellant table, motor, chamber, test data and
failure probabilities are invented demonstration values; none is data from a
real engine, motor or vehicle, and the models are textbook idealizations.

Definitions:
    ``Isp_vac``: vacuum specific impulse ``F_vac / (mdot g0)`` of an ideal
        frozen-flow nozzle with combustion and divergence corrections, in s.
    requirement: the vacuum specific impulse must be at least
        ``ISP_REQUIREMENT`` seconds; failure is ``Isp_vac <= requirement``.
    MEOP: the maximum chamber pressure of one motor burn, in Pa; the burst
        margin is ``p_burst - MEOP`` and a case burst is a margin ``<= 0``.
    Vieille law: ``r = a exp(sigma_p (T - T_ref)) (p / p_ref)^n``; the model
        class "Vieille" fixes ``sigma_p = 0`` and "Vieille + T" estimates it.
    ``beta``: FORM reliability index, ``P_f ~ Phi(-beta)``; ``d beta / d theta``
        is its derivative with respect to a distribution parameter.
    growth rate: ``Im(omega)`` of the first thermoacoustic mode in 1/s; the
        chamber is unstable when it is positive.
    cluster reliability: probability that at least ``k`` of ``n`` engines work
        and no catastrophic outage occurs, with beta-factor common cause.

Assumptions:
    - Inputs are independent with the stated engineering spreads; the
      spreads are assumptions, not measurements.
    - The engine and motor models are quasi-steady ideal-gas relations
      (no heat loss, no igniter transient in the quasi-steady mode, no
      erosive burning, no real-gas chemistry); the thermoacoustic model is a
      linear n-tau duct mode; none is validated against hardware.
    - FORM assumes one dominant design point and a smooth limit state; the
      engine and motor limit states are close to that, which the comparison
      with simulation checks but does not prove.
    - The calibration noise is lognormal with a known 1.5 % scale and the
      static-fire data are generated by the same Vieille model, so the
      posterior is calibrated by construction (no model-form error).
    - The GP Sobol indices refer to standard-normal coordinates restricted to
      the box ``|z| <= 3`` with uniform weight, a different input law from the
      normal one; the true-model Sobol ranking under the normal law is printed
      beside them.
    - Engine outcomes are Bernoulli per mission, one parameter draw is shared
      by all engines (state-of-knowledge dependence).

Equations:
    EQ-AERO-LRE-010: liquid-engine probabilistic model.
    EQ-AERO-SRM-002: quasi-steady equilibrium chamber pressure.
    EQ-AERO-SRM-007: solid-motor simulation and its probabilistic model.
    EQ-AERO-CI-006: thermoacoustic probabilistic model.
    EQ-AERO-CI-007: instability probability by Monte Carlo, PCE and FORM.
    EQ-AERO-REL-011: distribution of cluster reliability.
    EQ-SENS-FIRST-001: first-order Sobol indices.
    EQ-SENS-TOTAL-001: total-effect Sobol indices.
    EQ-REL-PF-001: failure probability.
    EQ-REL-FORM-001: FORM design point and reliability index.
    EQ-REL-SUBSET-001: subset simulation.
    EQ-REL-RSENS-001: envelope derivative of the reliability index.
    EQ-INF-TMCMC-003: log evidence of transitional MCMC.
    EQ-INF-TMCMC-005: posterior model probabilities.
    EQ-SUR-GPB-003: standardized emulator errors.
    EQ-SUR-GPB-004: Mahalanobis distance of the emulator.
    EQ-SUR-GPB-006: Sobol indices over GP sample paths.

Diagnostics:
    - Reliability methods on one limit state are compared with a crude Monte
      Carlo count whose standard error is printed.
    - Subset simulation prints its coefficient of variation and convergence;
      FORM prints convergence.
    - TMCMC prints the number of stages, the stop reason and the log
      evidence; the posterior mean is compared with the generating value.
    - Two GP emulators (60 and 100 training runs) are validated on held-out
      runs (Mahalanobis distance, coverage, flags) before the probability and
      indices are used; a flag saying the Mahalanobis distance is too small
      marks a conservative emulator, not a wrong one, and every flag is
      printed.
    - The model-class selection is repeated on data that cannot distinguish
      the classes, where the evidence ratio must be close to one.
    - The cluster distribution is checked against exact moments.

Cost and error:
    - Model runs are printed per stage. Engine: 2048 propagation runs, a
      Sobol design of ``512 (d + 2)``, then FORM, subset simulation (1000
      per level) and 10 000 Monte Carlo runs.
    - Motor: 4 000 propagation runs, subset simulation with 500 samples per
      level (a few thousand runs), 6 000 crude Monte Carlo runs for the
      reference, and a handful of runs for FORM and its parameter
      derivatives.
    - Calibration: 1 000 TMCMC particles per model class and data set.
    - Instability: 5 000 true-model runs, 100 (and 60) emulator training
      runs, 30 validation runs.
    - Monte Carlo errors are binomial standard errors; GP and TMCMC errors
      are those of one seed and are not averaged over seeds.

References:
    REF-SUTTON-BIBLARZ-2017: ideal-rocket performance and internal ballistics.
    REF-MELCHERS-BECK-2018: FORM and reliability methods.
    REF-AU-BECK-2001: subset simulation.
    REF-SALTELLI-2010: Sobol index estimators.
    REF-HOHENBICHLER-RACKWITZ-1986: FORM sensitivities.
    REF-CHING-CHEN-2007: transitional MCMC.
    REF-BECK-YUEN-2004: Bayesian model class selection.
    REF-MAGRI-JUNIPER-2013: thermoacoustic sensitivity analysis.
    REF-BASTOS-OHAGAN-2009: emulator diagnostics.
    REF-OAKLEY-OHAGAN-2004: emulator-based sensitivity analysis.
    REF-MOSLEH-ETAL-1998: common-cause failure modeling.
    REF-NASA-PRA-2011: probabilistic risk assessment procedures.
    REF-MATPLOTLIB: figures.

"""

