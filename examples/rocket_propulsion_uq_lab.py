def instability_part(budget: Budget) -> dict[str, Any]:
    """Estimate the instability probability by Monte Carlo and by a GP emulator.

    The emulator is trained in standard-normal coordinates ``z`` of the five
    uncertain parameters; its validation, its probability and its Sobol
    posterior are reported.

    Args:
        budget: Sample sizes.

    Returns:
        Probabilities, validations and Sobol indices.

    References:
        [EQ-AERO-CI-006], [EQ-AERO-CI-007], [EQ-SUR-GPB-004], [EQ-SUR-GPB-006].

    """
    headline("(d) thermoacoustic instability: Monte Carlo vs GP emulator")
    model = thermoacoustic_model(CHAMBER)
    names = model.inputs.names
    mean = model.inputs.means()
    sd = model.inputs.standard_deviations()

    def to_z(x: tuple[float, ...]) -> tuple[float, ...]:
        """Return standard-normal coordinates of a physical input.

        References:
            [EQ-AERO-CI-006].

        """
        return tuple((v - m) / s for v, m, s in zip(x, mean, sd, strict=True))

    points = model.inputs.sample(budget.instability_mc, seed=SEED)
    growth = model.evaluate_many(points)["growth_rate"]
    unstable = [g > 0.0 for g in growth]
    p_mc = sum(unstable) / len(unstable)
    se = math.sqrt(p_mc * (1.0 - p_mc) / len(unstable))
    print(
        f"true model: mean growth={statistics.fmean(growth):.3f} /s "
        f"sd={statistics.stdev(growth):.3f} P(unstable)={p_mc:.4f} se={se:.4f} "
        f"(n={len(growth)})"
    )
    library = instability_probability(
        model, mc_samples=min(budget.instability_mc, 2000), pce_degree=3, seed=SEED
    )
    print(
        f"library routes: MC={library.monte_carlo_probability:.4f} "
        f"PCE={library.surrogate_probability:.4f} (loo error "
        f"{library.surrogate_error:.2e}, "
        f"{library.surrogate_evaluations} runs) FORM={library.form_probability:.4f} "
        f"(beta={library.form_beta:.3f}, converged={library.form_converged})"
    )
    held = model.inputs.sample_design(
        latin_hypercube(budget.gp_validation, 5, seed=SEED + 3)
    )
    held_growth = model.evaluate_many(held)["growth_rate"]
    held_z = [to_z(x) for x in held]
    emulators = []
    for size in budget.gp_training:
        design = model.inputs.sample_design(latin_hypercube(size, 5, seed=SEED + 1))
        train_growth = model.evaluate_many(design)["growth_rate"]
        started = time.perf_counter()
        with warnings.catch_warnings(record=True) as caught:
            warnings.simplefilter("always")
            gp = fit_gaussian_process(
                [to_z(x) for x in design], train_growth, seed=SEED + 2, restarts=1
            )
        check = validate_gp_emulator(gp, held_z, held_growth)
        rmse = math.sqrt(
            statistics.fmean(
                (gp.predict(z) - y) ** 2
                for z, y in zip(held_z, held_growth, strict=True)
            )
        )
        print(
            f"GP with {size} runs: held-out rmse={rmse:.4f} /s "
            f"Mahalanobis={check.mahalanobis:.1f} (expected "
            f"{check.mahalanobis_expected:.0f}) "
            f"coverage={check.coverage:.3f} passed={check.passed} "
            f"conditioning warnings {len(caught)} "
            f"fit+validate {time.perf_counter() - started:.1f} s"
        )
        for flag in check.flags:
            print(f"    flag: {flag}")
        emulators.append((size, gp, check))
    size, gp, check = emulators[-1]
    p_gp = sum(1 for x in points if gp.predict(to_z(x)) > 0.0) / len(points)
    disagree = sum(
        1
        for x, u in zip(points, unstable, strict=True)
        if (gp.predict(to_z(x)) > 0.0) != u
    )
    print(
        f"GP({size}) P(unstable)={p_gp:.4f} on the same {len(points)} draws; "
        f"{disagree} draws classified differently from the true model"
    )
    sobol = gp_sobol_posterior(
        gp,
        (-3.0,) * 5,
        (3.0,) * 5,
        base_samples=budget.gp_base,
        paths=budget.gp_paths,
        seed=SEED + 5,
        max_points=600,
    )
    print(
        f"GP Sobol of the growth rate (uniform on |z|<=3; {sobol.evaluation_points} "
        f"points/path, {budget.gp_paths} paths):"
    )
    for index, name in enumerate(names):
        low, high = sobol.first_order_interval[index]
        print(
            f"  {name:15s} S1={sobol.first_order_mean[index]:.3f} [{low:.3f}, "
            f"{high:.3f}] "
            f"ST={sobol.total_mean[index]:.3f}"
        )
    study = UQStudy(model, seed=SEED)
    true_sobol = study.sensitivity("growth_rate", 256, bootstrap=0)
    print(f"true-model Sobol ranking under the normal law: {true_sobol.ranking()}")
    return {
        "names": names,
        "sobol": sobol,
        "p_mc": p_mc,
        "p_gp": p_gp,
        "emulators": [(s, c.passed) for s, _, c in emulators],
    }


