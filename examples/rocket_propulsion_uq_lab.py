def motor_from_inputs(values: dict[str, float]) -> SolidMotorParameters:
    """Return the motor of one realization of the model inputs.

    Args:
        values: Named input values of ``solid_motor_model``.

    Returns:
        Motor data with the realized propellant, throat and erosion.

    References:
        [EQ-AERO-SRM-007].

    """
    throat = values["d_throat"]
    return replace(
        MOTOR,
        burn_rate_coefficient=values["a0"],
        pressure_exponent=values["n"],
        characteristic_velocity=values["c_star"],
        propellant_density=values["rho_p"],
        temperature_sensitivity=values["sigma_p"],
        grain_temperature=values["T_grain"],
        throat_diameter=throat,
        erosion_rate=values["erosion_rate"],
        expansion_ratio=MOTOR.exit_area / (0.25 * math.pi * throat * throat),
    )


def burst_margin_form(budget: Budget) -> dict[str, Any]:
    """Return FORM and its parameter derivatives for a three-input burst margin.

    The margin ``p_burst - MEOP`` is a function of three independent normal
    inputs (burn-rate coefficient, characteristic velocity, burst pressure)
    with the other motor data fixed; ``theta`` collects their means and
    standard deviations.

    Args:
        budget: Sample sizes (unused; FORM costs a handful of runs).

    Returns:
        The FORM sensitivity result with parameter names and elasticities.

    References:
        [EQ-REL-RSENS-001], [EQ-AERO-SRM-007], [REF-HOHENBICHLER-RACKWITZ-1986].

    """
    del budget

    def margin(x: tuple[float, ...]) -> float:
        """Return ``p_burst - MEOP`` for ``(a0, c_star, p_burst)``.

        References:
            [EQ-AERO-SRM-007].

        """
        motor = replace(MOTOR, burn_rate_coefficient=x[0], characteristic_velocity=x[1])
        return x[2] - simulate_solid_motor(GRAIN, motor, steps=40).meop

    means = (MOTOR.burn_rate_coefficient, MOTOR.characteristic_velocity, BURST_MEDIAN)
    spreads = (0.04 * means[0], 0.01 * means[1], 0.05 * means[2])
    theta = means + spreads
    problem = normal_input_limit_state(margin, 3)
    result = form_sensitivities(problem, theta, 3)
    names = normal_parameter_names(3)
    labels = ("a0", "c_star", "p_burst")
    full = [f"mu({labels[i]})" for i in range(3)] + [
        f"sd({labels[i]})" for i in range(3)
    ]
    elasticity = tuple(t * d for t, d in zip(theta, result.dbeta, strict=True))
    print(
        f"FORM of the three-input margin: beta={result.beta:.3f} "
        f"P={result.probability:.3e} converged={result.converged} "
        f"runs={result.evaluations} ({names})"
    )
    for label, value, scaled in zip(full, result.dbeta, elasticity, strict=True):
        print(
            f"  d beta / d {label:11s} = {value: .4e}  elasticity theta*dbeta = "
            f"{scaled: .3f}"
        )
    print(f"  importance alpha = {tuple(round(a, 3) for a in result.alpha)}")
    return {"result": result, "elasticity": elasticity, "labels": full}


def motor_part(budget: Budget) -> dict[str, Any]:
    """Disperse the motor and estimate its burst probability by subset simulation.

    Args:
        budget: Sample sizes.

    Returns:
        Quantities for the figure and the probability comparison.

    References:
        [EQ-AERO-SRM-007], [EQ-REL-SUBSET-001], [REF-AU-BECK-2001].

    """
    headline("(b) solid motor: impulse dispersion, burst probability, FORM")
    nominal = simulate_solid_motor(GRAIN, MOTOR, steps=60)
    print(
        f"nominal burn: MEOP={nominal.meop / 1e6:.3f} MPa "
        f"burn_time={nominal.burn_time:.3f} s impulse={nominal.total_impulse:.1f} N s "
        f"Isp={nominal.specific_impulse:.1f} s"
    )
    model = solid_motor_model(GRAIN, MOTOR, BURST_MEDIAN, steps=40)
    points = model.inputs.sample(budget.motor_runs, seed=SEED)
    out = model.evaluate_many(points)
    for name, unit, scale in (
        ("meop", "MPa", 1e-6),
        ("total_impulse", "kN s", 1e-3),
        ("burn_time", "s", 1.0),
    ):
        values = out[name]
        print(
            f"{name}: mean={statistics.fmean(values) * scale:.4f} {unit} "
            f"sd={statistics.stdev(values) * scale:.4f} (n={budget.motor_runs})"
        )
    impulse = out["total_impulse"]
    print(
        f"impulse coefficient of variation "
        f"{statistics.stdev(impulse) / statistics.fmean(impulse):.4f}"
    )
    limit = ModelLimitState(model, "burst_margin", 0.0, failure="below")
    started = time.perf_counter()
    subset = subset_simulation(limit, samples_per_level=budget.motor_subset, seed=SEED)
    elapsed_subset = time.perf_counter() - started
    started = time.perf_counter()
    crude = model_monte_carlo(limit, budget.motor_mc, seed=SEED + 1)
    elapsed_crude = time.perf_counter() - started
    print(f"P(MEOP >= p_burst), median burst {BURST_MEDIAN / 1e6:.2f} MPa:")
    print(
        f"  subset  P={subset.probability:.3e} "
        f"cov={subset.coefficient_of_variation:.3f} "
        f"runs={subset.evaluations} converged={subset.converged} "
        f"({elapsed_subset:.1f} s)"
    )
    print(
        f"  crude   P={crude.probability:.3e} se={crude.standard_error:.2e} "
        f"runs={crude.evaluations} ({elapsed_crude:.1f} s)"
    )
    sensitivities = burst_margin_form(budget)
    generator = model.inputs.sample(budget.traces, seed=SEED + 2)
    traces = []
    for point in generator:
        realized = dict(zip(model.inputs.names, point, strict=True))
        result = simulate_solid_motor(GRAIN, motor_from_inputs(realized), steps=60)
        traces.append((result.times, result.pressures, result.burn_time))
    return {
        "outputs": out,
        "subset": subset,
        "crude": crude,
        "traces": traces,
        "form": sensitivities,
    }


