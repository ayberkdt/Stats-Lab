def motor_figure(motor: dict[str, Any]) -> str:
    """Draw the pressure-time band of the dispersed motor against the burst median.

    Args:
        motor: Result of :func:`motor_part`.

    Returns:
        The file name written.

    References:
        [EQ-AERO-SRM-007], [REF-MATPLOTLIB]. No equation is evaluated.

    """
    from probstat.visualization import theme

    traces = motor["traces"]
    horizon = min(trace[2] for trace in traces)
    grid = [horizon * i / 60 for i in range(61)]

    def at(trace: tuple[Any, Any, float], time_value: float) -> float:
        """Interpolate one pressure trace linearly.

        References:
            [EQ-AERO-SRM-007].

        """
        times, pressures, _ = trace
        for k in range(1, len(times)):
            if times[k] >= time_value:
                w = (time_value - times[k - 1]) / (times[k] - times[k - 1])
                return float(pressures[k - 1] + w * (pressures[k] - pressures[k - 1]))
        return float(pressures[-1])

    lows, mids, highs = [], [], []
    for t in grid:
        column = sorted(at(trace, t) / 1e6 for trace in traces)
        lows.append(column[int(0.05 * len(column))])
        mids.append(column[len(column) // 2])
        highs.append(column[min(len(column) - 1, int(0.95 * len(column)))])
    axes = theme.new_axes(figsize=(7.2, 4.4))
    colour = theme.role_colour("model")
    theme.band(axes, grid, lows, highs, color=colour)
    theme.line(axes, grid, mids, color=colour)
    theme.reference_line(
        axes, y=BURST_MEDIAN / 1e6, entity="threshold", label="median burst"
    )
    axes.set_xlim(0.0, horizon)
    theme.axis_labels(axes, "Time since ignition (s)", "Chamber pressure (MPa)")
    peak = motor["outputs"]["meop"]
    theme.title_block(
        axes,
        f"Mean peak pressure {statistics.fmean(peak) / 1e6:.2f} MPa, "
        f"burst probability {motor['subset'].probability:.1e}",
        f"Synthetic BATES motor, 5-95 % band of {len(traces)} draws; subset simulation",
    )
    return save(axes.figure, "rocket-propulsion-motor-pressure.png")


