def static_fire_tests(ambient_only: bool) -> list[tuple[float, float]]:
    """Return the ``(grain temperature, throat diameter)`` of the static fires.

    Args:
        ambient_only: Whether all nine tests are at the reference temperature
            (repeated throats) instead of three temperatures.

    Returns:
        Nine test conditions.

    References:
        [EQ-AERO-SRM-002].

    """
    throats = (0.022, 0.024, 0.026)
    if ambient_only:
        return [(REFERENCE_K, d) for _ in range(3) for d in throats]
    return [(t, d) for t in (258.15, 293.15, HOT_GRAIN_K) for d in throats]


def plateau_pressure(
    a: float, n: float, sigma: float, temperature: float, throat: float
) -> float:
    """Return the initial equilibrium chamber pressure of one static fire.

    Args:
        a: Burn-rate coefficient at the reference pressure and temperature.
        n: Pressure exponent.
        sigma: Temperature sensitivity in 1/K.
        temperature: Grain temperature in K.
        throat: Throat diameter in m.

    Returns:
        Pressure in Pa from the quasi-steady balance.

    References:
        [EQ-AERO-SRM-002], [REF-SUTTON-BIBLARZ-2017].

    """
    klemmung = GRAIN.burning_area(0.0) / (0.25 * math.pi * throat * throat)
    coefficient = a * math.exp(sigma * (temperature - REFERENCE_K))
    return equilibrium_pressure(
        coefficient,
        n,
        MOTOR.characteristic_velocity,
        MOTOR.propellant_density,
        klemmung,
        reference_pressure=MOTOR.reference_pressure,
    )


def synthetic_data(tests: list[tuple[float, float]], seed: int) -> list[float]:
    """Generate static-fire pressures from the generating law with noise.

    Args:
        tests: Test conditions.
        seed: Seed of the lognormal noise.

    Returns:
        One plateau pressure in Pa per test.

    References:
        [EQ-AERO-SRM-002].

    """
    generator = resolve_stream(seed).generator()
    return [
        plateau_pressure(TRUTH["a"], TRUTH["n"], TRUTH["sigma"], t, d)
        * math.exp(generator.gauss(0.0, NOISE_SCALE))
        for t, d in tests
    ]


def log_prior(x: tuple[float, ...], with_sigma: bool) -> float:
    """Return the unnormalized log prior of ``(log a0, n[, sigma_p])``.

    Args:
        x: Parameter vector.
        with_sigma: Whether the vector holds ``sigma_p``.

    Returns:
        Log density up to a constant; ``-inf`` outside the support.

    References:
        [EQ-INF-TMCMC-003].

    """
    if not 0.0 < x[1] < 0.95:
        return -math.inf
    value = -0.5 * ((x[0] - PRIOR_A[0]) / PRIOR_A[1]) ** 2
    value -= 0.5 * ((x[1] - PRIOR_N[0]) / PRIOR_N[1]) ** 2
    if with_sigma:
        if x[2] < 0.0:
            return -math.inf
        value -= 0.5 * ((x[2] - PRIOR_SIGMA[0]) / PRIOR_SIGMA[1]) ** 2
    return value


def log_likelihood(
    x: tuple[float, ...],
    with_sigma: bool,
    tests: list[tuple[float, float]],
    data: list[float],
) -> float:
    """Return the normalized log likelihood of the plateau pressures.

    The data are lognormal about the model pressure with scale ``NOISE_SCALE``;
    the density of the pressure (not of its logarithm) is used so that
    evidences of classes are comparable.

    Args:
        x: Parameter vector.
        with_sigma: Whether the vector holds ``sigma_p``.
        tests: Test conditions.
        data: Observed pressures in Pa.

    Returns:
        ``log L``.

    References:
        [EQ-INF-TMCMC-003], [EQ-AERO-SRM-002].

    """
    a, n = math.exp(x[0]), x[1]
    sigma = x[2] if with_sigma else 0.0
    constant = -math.log(NOISE_SCALE) - 0.5 * math.log(2.0 * math.pi)
    total = 0.0
    for (t, d), p in zip(tests, data, strict=True):
        z = (math.log(p) - math.log(plateau_pressure(a, n, sigma, t, d))) / NOISE_SCALE
        total += -0.5 * z * z + constant - math.log(p)
    return total


def calibrate(
    with_sigma: bool,
    tests: list[tuple[float, float]],
    data: list[float],
    budget: Budget,
) -> TMCMCResult:
    """Run TMCMC for one model class on one data set.

    Args:
        with_sigma: Whether the temperature sensitivity is estimated.
        tests: Test conditions.
        data: Observed pressures.
        budget: Sample sizes.

    Returns:
        The TMCMC result (samples and log evidence).

    References:
        [EQ-INF-TMCMC-003], [REF-CHING-CHEN-2007].

    """

    def sampler(generator: Any) -> tuple[float, ...]:
        """Draw one prior sample inside the support.

        References:
            [EQ-INF-TMCMC-003].

        """
        while True:
            x = [generator.gauss(*PRIOR_A), generator.gauss(*PRIOR_N)]
            if with_sigma:
                x.append(generator.gauss(*PRIOR_SIGMA))
            if log_prior(tuple(x), with_sigma) > -math.inf:
                return tuple(x)

    return transitional_mcmc(
        sampler,
        lambda x: log_prior(x, with_sigma),
        lambda x: log_likelihood(x, with_sigma, tests, data),
        particles=budget.particles,
        seed=SEED,
    )


def calibration_part(budget: Budget) -> dict[str, Any]:
    """Calibrate the burn-rate law, predict the hot peak pressure, select a class.

    Args:
        budget: Sample sizes.

    Returns:
        Results per data set and the predictive peak pressures.

    References:
        [EQ-INF-TMCMC-003], [EQ-INF-TMCMC-005], [REF-BECK-YUEN-2004].

    """
    headline("(c) calibration of the burn-rate law by TMCMC")
    print(
        f"generating law (synthetic): a0={TRUTH['a']:.4e} m/s n={TRUTH['n']} "
        f"sigma_p={TRUTH['sigma']:.2e} /K; noise scale {NOISE_SCALE}"
    )
    results: dict[str, dict[str, TMCMCResult]] = {}
    for label, ambient in (("all temperatures", False), ("ambient only", True)):
        tests = static_fire_tests(ambient)
        data = synthetic_data(tests, SEED + 3)
        print(
            f"data set '{label}': pressures (MPa) = {[round(p / 1e6, 3) for p in data]}"
        )
        runs: dict[str, TMCMCResult] = {}
        for name, with_sigma in CLASSES:
            started = time.perf_counter()
            result = calibrate(with_sigma, tests, data, budget)
            runs[name] = result
            samples = result.particles
            parts = [
                f"a0={statistics.fmean(math.exp(s[0]) for s in samples):.4e}",
                f"n={statistics.fmean(s[1] for s in samples):.4f}"
                f"+-{statistics.stdev(s[1] for s in samples):.4f}",
            ]
            if with_sigma:
                parts.append(
                    f"sigma_p={statistics.fmean(s[2] for s in samples):.3e}"
                    f"+-{statistics.stdev(s[2] for s in samples):.2e}"
                )
            print(
                f"  {name:12s} stages={len(result.exponents) - 1} "
                f"stop={result.stop_reason} "
                f"logZ={result.log_evidence:.3f} runs={result.evaluations} "
                f"({time.perf_counter() - started:.1f} s) " + " ".join(parts)
            )
        selection = model_class_selection(runs)
        for name, evidence, posterior in zip(
            selection.names,
            selection.log_evidences,
            selection.posterior_probabilities,
            strict=True,
        ):
            print(
                f"  model class {name:12s} log evidence={evidence:.3f} "
                f"P(M|D)={posterior:.4g}"
            )
        results[label] = runs
    full = results["all temperatures"]["Vieille + T"]
    generator = resolve_stream(SEED + 4).generator()
    peaks = []
    for index in range(budget.predictive):
        sample = full.particles[generator.randrange(len(full.particles))]
        motor = replace(
            MOTOR,
            burn_rate_coefficient=math.exp(sample[0]),
            pressure_exponent=sample[1],
            temperature_sensitivity=sample[2],
            grain_temperature=HOT_GRAIN_K,
        )
        peaks.append(simulate_solid_motor(GRAIN, motor, steps=40).meop)
        del index
    peaks.sort()
    count = len(peaks)
    print(
        f"posterior predictive MEOP at {HOT_GRAIN_K} K (nominal throat, erosion): "
        f"mean={statistics.fmean(peaks) / 1e6:.3f} MPa "
        f"sd={statistics.stdev(peaks) / 1e6:.3f} "
        f"q05={peaks[int(0.05 * count)] / 1e6:.3f} "
        f"q95={peaks[min(count - 1, int(0.95 * count))] / 1e6:.3f} "
        f"(n={count}); median burst {BURST_MEDIAN / 1e6:.2f} MPa"
    )
    return {"results": results, "peaks": peaks}


