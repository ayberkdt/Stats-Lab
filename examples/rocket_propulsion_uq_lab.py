def engine_model() -> Any:
    """Return the synthetic liquid-engine model with six uncertain inputs.

    Chamber pressure and throat diameter are normal, the mixture ratio and
    combustion efficiency are truncated normal, the expansion ratio is
    normal, the nozzle exhausts to vacuum and the cone half-angle is fixed at
    15 degrees.

    Returns:
        A probabilistic model with the engine quantities of interest.

    References:
        [EQ-AERO-LRE-010], [REF-SUTTON-BIBLARZ-2017].

    """
    return liquid_engine_model(
        chamber_pressure=Normal(7.0e6, 0.2e6),
        mixture_ratio=TruncatedNormal(2.6, 0.08, lower=2.0, upper=3.2),
        combustion_efficiency=TruncatedNormal(0.975, 0.008, lower=0.9, upper=1.0),
        throat_diameter=Normal(0.200, 0.0008),
        expansion_ratio=Normal(45.0, 0.5),
        ambient_pressure=0.0,
        divergence_half_angle=0.2618,
    )


def engine_part(budget: Budget) -> dict[str, Any]:
    """Disperse, rank and test the engine against its impulse requirement.

    Args:
        budget: Sample sizes.

    Returns:
        Samples, indices and the method comparison, for the figure.

    References:
        [EQ-AERO-LRE-010], [EQ-SENS-TOTAL-001], [EQ-REL-FORM-001],
        [EQ-REL-SUBSET-001], [REF-MELCHERS-BECK-2018].

    """
    headline("(a) liquid engine: dispersion, Sobol ranking, requirement")
    model = engine_model()
    study = UQStudy(model, seed=SEED)
    forward = study.propagate(budget.engine_runs)
    for name, unit, scale in (
        ("vacuum_specific_impulse", "s", 1.0),
        ("thrust", "kN", 1.0e-3),
    ):
        result = forward[name]
        print(
            f"{name}: mean={result.mean * scale:.3f} {unit} "
            f"sd={result.standard_deviation * scale:.3f} "
            f"q01={result.quantile(0.01) * scale:.3f} "
            f"q99={result.quantile(0.99) * scale:.3f} (n={budget.engine_runs})"
        )
    sobol = study.sensitivity("vacuum_specific_impulse", budget.engine_sobol)
    for index, name in enumerate(sobol.input_names):
        first, total = sobol.first_order[index], sobol.total_effect[index]
        print(
            f"  Sobol Isp_vac {name:22s} S1={first.estimate:.3f} "
            f"ST={total.estimate:.3f}"
        )
    print(f"  ranking Isp_vac: {sobol.ranking()}")
    thrust = study.sensitivity("thrust", budget.engine_sobol)
    print(f"  ranking thrust : {thrust.ranking()}")
    comparison = study.reliability(
        "vacuum_specific_impulse",
        ISP_REQUIREMENT,
        failure="below",
        methods=("form", "subset", "mc"),
        monte_carlo_samples=budget.engine_mc,
    )
    print(f"P(Isp_vac <= {ISP_REQUIREMENT:g} s):")
    for row in comparison.rows:
        cov = (
            "-"
            if row.coefficient_of_variation is None
            else f"{row.coefficient_of_variation:.3f}"
        )
        print(
            f"  {row.method:7s} P={row.probability:.3e} beta={row.beta:.3f} "
            f"runs={row.evaluations} cov={cov}"
        )
    mc = comparison.row("MC")
    se = math.sqrt(mc.probability * (1.0 - mc.probability) / budget.engine_mc)
    print(
        f"  crude Monte Carlo standard error {se:.2e}; total runs "
        f"{study.total_evaluations}"
    )
    return {"forward": forward, "sobol": sobol, "comparison": comparison}


