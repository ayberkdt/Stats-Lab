    def test_pelt_equals_exhaustive_enumeration(self) -> None:
        """On n = 10 every subset of change points is enumerated."""
        data = [0.1, -0.3, 0.2, 2.9, 3.4, 3.1, 2.8, -1.0, -1.2, -0.7]
        beta = 2.0

        def rss(segment: list[float]) -> float:
            """Return the residual sum of squares of a segment.

            References:
                [EQ-TS-CP-003], [REF-KILLICK-2012].

            """
            mean = sum(segment) / len(segment)
            return sum((x - mean) ** 2 for x in segment)

        best_value, best_points = math.inf, ()
        for count in range(10):
            for points in itertools.combinations(range(1, 10), count):
                edges = (0, *points, 10)
                value = (
                    sum(rss(data[a:b]) for a, b in itertools.pairwise(edges))
                    + beta * count
                )
                if value < best_value - 1e-12:
                    best_value, best_points = value, points
        result = pelt(data, model="mean", penalty=beta, variance=1.0)
        self.assertEqual(result.changepoints, best_points)
        self.assertAlmostEqual(result.objective, best_value, places=12)

    def test_pelt_recovers_mean_and_variance_changes(self) -> None:
        """Clear changes are found within two observations; pruning saves work."""
        generator = random.Random(2012)
        data = [generator.gauss(0, 1) for _ in range(300)]
        data += [generator.gauss(3, 1) for _ in range(300)]
        data += [generator.gauss(3, 3) for _ in range(300)]
        result = pelt(data, model="meanvar", penalty="mbic")
        self.assertEqual(len(result.changepoints), 2)
        for got, true in zip(result.changepoints, (300, 600), strict=True):
            self.assertLessEqual(abs(got - true), 2)
        self.assertLess(result.cost_evaluations, 900 * 901 // 2 // 2)
        self.assertAlmostEqual(result.penalty, 4 * math.log(900), places=12)
        self.assertAlmostEqual(result.segments[2].variance, 9.0, delta=1.5)
        means = pelt(data[:600], model="mean", penalty="bic")
        self.assertEqual(len(means.changepoints), 1)
        self.assertAlmostEqual(means.penalty, 2 * math.log(600), places=12)

