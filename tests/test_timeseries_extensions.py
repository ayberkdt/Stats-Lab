    def test_kpss_size_by_simulation(self) -> None:
        """On white noise the 5% level test rejects at 5% within 3 SE (300 runs)."""
        runs = 300
        threshold = kpss_critical_values("c")[0.05]
        rejections = 0
        for seed in range(runs):
            generator = random.Random(9000 + seed)
            series = [generator.gauss(0, 1) for _ in range(250)]
            data_mean = sum(series) / 250
            residuals = [v - data_mean for v in series]
            lags = int(4 * (250 / 100) ** 0.25)
            variance = newey_west_variance(residuals, lags)
            partial, total = 0.0, 0.0
            for e in residuals:
                partial += e
                total += partial * partial
            rejections += total / (250**2 * variance) > threshold
        rate = rejections / runs
        self.assertLess(abs(rate - 0.05), 3 * math.sqrt(0.05 * 0.95 / runs))

    def test_newey_west_zero_lag_is_variance(self) -> None:
        """With l = 0 the long-run variance is the mean square."""
        values = [1.0, -2.0, 0.5, 0.5]
        self.assertAlmostEqual(newey_west_variance(values, 0), 5.5 / 4, places=15)
        weight = 0.5
        lag1 = (1.0 * -2.0 + -2.0 * 0.5 + 0.5 * 0.5) / 4
        self.assertAlmostEqual(
            newey_west_variance(values, 1), 5.5 / 4 + 2 * weight * lag1, places=15
        )


