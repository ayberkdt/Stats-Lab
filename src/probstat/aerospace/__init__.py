"""Aerospace engineering models with uncertainty: propulsion and launch risk.

Engineering-level physical models of rocket propulsion with explicit units,
assumptions and validity ranges, built so that the library's propagation,
sensitivity, reliability, calibration and design tools apply to them
directly. The models are textbook-level idealizations (ideal-rocket theory,
quasi-steady internal ballistics, linear thermoacoustics); they are not
validated against any specific engine, and their cases are synthetic.

``liquid_engine``
    ideal-rocket performance (``c*``, ``CF``, ``Isp``), the area-Mach
    relation, nozzle divergence, the Summerfield separation flag,
    mixture-ratio tables and the turbine-pump power balance;
``solid_motor``
    zero-dimensional internal ballistics with the Vieille burn rate and
    tubular, end-burning and BATES grains;
``combustion_instability``
    linear ``n``-``tau`` thermoacoustic modes, the Rayleigh index and
    eigenvalue sensitivities;
``ascent``
    planar ascent through the 1976 standard atmosphere, staging, orbit
    insertion and dispersion analysis;
``entry``
    planar atmospheric entry, Allen-Eggers checks, Sutton-Graves heating,
    heat-shield sizing and entry corridors;
``nozzle_cooling``
    Bartz gas-side heat transfer, the wall resistance network and
    regenerative coolant heating along the nozzle;
``debris_risk``
    micrometeoroid and debris penetration risk with parameterized
    ballistic limits, epistemic factors and Bayesian flux updating;
``shell_buckling``
    classical buckling, the SP-8007 knockdown, Koiter's imperfection law and
    a probabilistic knockdown for thin-walled cylinders;
``health_monitoring``
    a digital twin of chamber pressure with joint efficiency estimation,
    CUSUM and GLR fault detection and remaining-useful-life prognostics;
``turbopump``
    net positive suction head, suction specific speed, the pump operating
    point and the probability of cavitation;
``entry_reconstruction``
    post-flight reconstruction of the density profile and ballistic
    coefficient from entry measurements;
``orbital_decay``
    orbital lifetime under drag with a synthetic solar cycle and disposal
    compliance;
``wind_loads``
    dynamic pressure and q-alpha loads through a synthetic wind field;
``attitude_estimation``
    gyro and star-tracker attitude filtering, steady-state accuracy, Allan
    variance and the pointing error budget;
``power_budget``
    eclipse geometry, array and battery degradation and the end-of-life
    energy balance;
``reentry_casualty``
    fragment demise, casualty area and casualty expectation for an
    uncontrolled reentry;
``engine_reliability``
    demonstration test planning, heritage priors, reliability growth,
    engine clusters with common cause and launch event trees;
``conjunction``
    the probability of collision on the encounter plane.

Main entry points:
    ``liquid_engine_model``, ``solid_motor_model``,
        ``thermoacoustic_model``, ``ascent_model``, ``entry_model``,
        ``nozzle_cooling_model``, ``mmod_risk_model``,
        ``shell_buckling_model``, ``turbopump_cavitation_model``,
        ``orbital_lifetime_model``, ``wind_loads_model``:
        ``ProbabilisticModel``
        builders for the library's propagation, sensitivity and
        reliability tools.
    ``ideal_rocket_performance``, ``simulate_solid_motor``,
        ``thermoacoustic_modes``, ``simulate_ascent``: deterministic
        solvers at one point.
    ``instability_probability``, ``dispersion_intervals``,
        ``dispersion_budget``: uncertainty summaries of one model.
    ``demonstration_plan``, ``bayesian_demonstration_size``,
        ``vehicle_reliability_distribution``: reliability planning.
    ``collision_probability``, ``dilution_analysis``,
        ``pc_under_scale_uncertainty``: conjunction assessment.

Assumptions:
    Ideal-gas, frozen-composition and quasi-steady physics; a spherical,
    non-rotating Earth for the ascent; independent uncertain inputs unless
    a model states otherwise; Gaussian position errors on the encounter
    plane. Each module states its validity range; inputs outside it (an
    O/F outside the mixture table, a drag table out of range) fail the run
    instead of extrapolating.

Common pitfalls:
    - Treating a synthetic demonstration vehicle as a real one: the
      numbers illustrate the method, not an engine.
    - Quoting a subset-simulation probability without its coefficient of
      variation; at a few hundred samples per level it is about 0.5.
    - Trusting FORM where the failure boundary is curved or the unstable
      region is not connected: compare with SORM or Monte Carlo.
    - Using the demonstration ballistic-limit coefficients or flux of
      ``debris_risk`` for a real design: they are synthetic; take published
      coefficient sets and an environment model from their sources.
    - Reading a dilution-region collision probability as safe: a small
      probability can mean the covariance is too large to say anything.

Experimental (added in 0.28).

Guide: docs/foundations/aerospace-propulsion-uq.md

References:
    [REF-SUTTON-BIBLARZ-2017].

"""

