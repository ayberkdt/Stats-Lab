"""Finite measure theory: sigma-algebras, measures, integrals, and densities.

This module is the measure-theoretic bridge of the probability layer. A
:class:`FiniteMeasurableSpace` carries an explicit sigma-algebra on a finite
set, which is no longer forced to be the full power set: it is the
sigma-algebra generated by a collection of subsets and is represented by its
atoms, the cells of the generated partition. A :class:`FiniteMeasure` assigns
a non-negative mass to every atom, so countable additivity holds by
construction. On top of these two objects the module evaluates

* measurability of events, maps, and real functions;
* pushforward (image) measures;
* the Lebesgue integral, first for simple functions and then for every
  measurable function;
* product measures and the Fubini-Tonelli equality of iterated integrals;
* absolute continuity, Radon-Nikodym derivatives, and their chain rule;
* conditional expectation given a sub-sigma-algebra, with the tower property
  and the rule that a known factor can be taken out;
* the total-variation distance; and
* completeness of a statistic for a finite parametric family.

Arithmetic is exact with :class:`fractions.Fraction` whenever every input is
an ``int`` or a ``Fraction``. A ``float`` input is accepted; any result that
depends on it is a ``float`` and comparisons then use an explicit tolerance.

Outcome sets are compared by value: two spaces on the same outcomes with
different sigma-algebras describe the same experiment observed at different
resolutions, which is exactly the relation a sub-sigma-algebra expresses.
"""

from __future__ import annotations

import math
from collections.abc import Callable, Hashable, Iterable, Iterator, Mapping, Sequence
from dataclasses import dataclass, field
from fractions import Fraction
from numbers import Rational, Real
from types import MappingProxyType
from typing import Generic, TypeVar

from .finite import FiniteEvent, FiniteProbabilityMeasure

OutcomeT = TypeVar("OutcomeT", bound=Hashable)
TargetT = TypeVar("TargetT", bound=Hashable)
OtherT = TypeVar("OtherT", bound=Hashable)

Scalar = Fraction | float
"""A stored number: exact ``Fraction`` or ``float``."""

NumberLike = int | float | Fraction
"""An accepted numeric input."""

EventLike = Iterable[OutcomeT] | FiniteEvent[OutcomeT]
"""An event given as outcomes or as a :class:`FiniteEvent`."""

_TOLERANCE = 1e-12
_ZERO = Fraction(0)
_ONE = Fraction(1)


def _scalar(value: object, *, name: str) -> Scalar:
    """Convert a real input to an exact ``Fraction`` or a finite ``float``.

    Args:
        value: Candidate number. Booleans are rejected.
        name: Argument name used in error messages.

    Returns:
        ``Fraction`` for integers and rationals, ``float`` otherwise.

    Raises:
        TypeError: If ``value`` is not a real number.
        ValueError: If ``value`` is a non-finite float.

    References:
        [REF-BILLINGSLEY-1995, Section 10]. No equation is evaluated.

    """
    if isinstance(value, bool) or not isinstance(value, Real):
        raise TypeError(f"{name} must be a real number")
    if isinstance(value, Fraction):
        return value
    if isinstance(value, int):
        return Fraction(value)
    if isinstance(value, Rational):
        return Fraction(int(value.numerator), int(value.denominator))
    converted = float(value)
    if not math.isfinite(converted):
        raise ValueError(f"{name} must be finite")
    return converted


def _sum(values: Iterable[Scalar]) -> Scalar:
    """Add numbers exactly when all are fractions, otherwise with ``fsum``.

    Args:
        values: Numbers to add.

    Returns:
        Exact ``Fraction`` sum, or a correctly rounded ``float`` sum.

    References:
        [EQ-MEAS-002], [REF-BILLINGSLEY-1995, Section 10].

    """
    materialized = tuple(values)
    exact = [value for value in materialized if isinstance(value, Fraction)]
    if len(exact) == len(materialized):
        total = _ZERO
        for value in exact:
            total += value
        return total
    return math.fsum(float(value) for value in materialized)


def _equal(first: Scalar, second: Scalar, tolerance: float) -> bool:
    """Compare two numbers exactly, or within ``tolerance`` for floats.

    Args:
        first: First number.
        second: Second number.
        tolerance: Absolute and relative tolerance used for floats.

    Returns:
        Whether the numbers agree.

    References:
        [REF-BILLINGSLEY-1995, Section 10]. No equation is evaluated.

    """
    if isinstance(first, Fraction) and isinstance(second, Fraction):
        return first == second
    return math.isclose(
        float(first), float(second), rel_tol=tolerance, abs_tol=tolerance
    )


def _is_zero(value: Scalar) -> bool:
    """Return whether a stored number is exactly zero.

    Args:
        value: Stored number.

    Returns:
        ``True`` for an exact or floating zero.

    References:
        [EQ-MEAS-006], [REF-BILLINGSLEY-1995, Section 32].

    """
    return value == 0


def _check_tolerance(tolerance: object) -> float:
    """Validate a non-negative finite comparison tolerance.

    Args:
        tolerance: Candidate tolerance.

    Returns:
        The tolerance as a float.

    Raises:
        TypeError: If ``tolerance`` is not real.
        ValueError: If ``tolerance`` is negative or not finite.

    References:
        [REF-BILLINGSLEY-1995, Section 10]. No equation is evaluated.

    """
    if isinstance(tolerance, bool) or not isinstance(tolerance, Real):
        raise TypeError("tolerance must be a real number")
    checked = float(tolerance)
    if not math.isfinite(checked) or checked < 0.0:
        raise ValueError("tolerance must be finite and non-negative")
    return checked


def _members(event: object, *, name: str) -> frozenset[Hashable]:
    """Materialize an event given as outcomes or as a ``FiniteEvent``.

    Args:
        event: Iterable of hashable outcomes or a ``FiniteEvent``.
        name: Argument name used in error messages.

    Returns:
        The event's members.

    Raises:
        TypeError: If ``event`` is a string, is not iterable, or contains an
            unhashable member.

    References:
        [REF-BILLINGSLEY-1995, Section 2]. No equation is evaluated.

    """
    if isinstance(event, FiniteEvent):
        return frozenset(event.members)
    if isinstance(event, str | bytes) or not isinstance(event, Iterable):
        raise TypeError(f"{name} must be an iterable of outcomes")
    try:
        return frozenset(event)
    except TypeError as error:
        raise TypeError(f"{name} members must be hashable") from error


def _ordered_outcomes(outcomes: Iterable[OutcomeT]) -> tuple[OutcomeT, ...]:
    """Validate a non-empty sequence of distinct hashable outcomes.

    Args:
        outcomes: Candidate outcomes; a ``FiniteSampleSpace`` is accepted.

    Returns:
        Outcomes in input order.

    Raises:
        TypeError: If an outcome is unhashable or ``outcomes`` is a string.
        ValueError: If no outcome is given or an outcome repeats.

    References:
        [REF-BILLINGSLEY-1995, Section 2]. No equation is evaluated.

    """
    if isinstance(outcomes, str | bytes):
        raise TypeError("outcomes must be an iterable of outcomes, not a string")
    ordered: list[OutcomeT] = []
    seen: set[OutcomeT] = set()
    for index, outcome in enumerate(outcomes):
        try:
            repeated = outcome in seen
        except TypeError as error:
            raise TypeError(f"outcomes[{index}] must be hashable") from error
        if repeated:
            raise ValueError(f"outcomes[{index}] repeats an earlier outcome")
        seen.add(outcome)
        ordered.append(outcome)
    if not ordered:
        raise ValueError("a measurable space needs at least one outcome")
    return tuple(ordered)


def _values(
    function: Callable[[OutcomeT], object] | Mapping[OutcomeT, object],
    outcomes: Sequence[OutcomeT],
    *,
    name: str,
) -> dict[OutcomeT, object]:
    """Evaluate a callable or read a complete mapping on every outcome.

    Args:
        function: Callable on outcomes, or a mapping with exactly the
            outcomes as keys.
        outcomes: Outcomes on which to evaluate.
        name: Argument name used in error messages.

    Returns:
        Outcome-to-value dictionary in outcome order.

    Raises:
        TypeError: If ``function`` is neither callable nor a mapping.
        ValueError: If a mapping's keys differ from the outcomes.

    References:
        [REF-BILLINGSLEY-1995, Section 13]. No equation is evaluated.

    """
    if isinstance(function, Mapping):
        keys = frozenset(function)
        if keys != frozenset(outcomes):
            raise ValueError(f"{name} keys must equal the outcomes")
        return {outcome: function[outcome] for outcome in outcomes}
    if not callable(function):
        raise TypeError(f"{name} must be callable or a mapping")
    return {outcome: function(outcome) for outcome in outcomes}


def _real_values(
    function: Callable[[OutcomeT], NumberLike] | Mapping[OutcomeT, NumberLike],
    outcomes: Sequence[OutcomeT],
    *,
    name: str,
) -> dict[OutcomeT, Scalar]:
    """Evaluate a real-valued function on every outcome.

    Args:
        function: Callable or complete mapping with real values.
        outcomes: Outcomes on which to evaluate.
        name: Argument name used in error messages.

    Returns:
        Outcome-to-number dictionary.

    Raises:
        TypeError: If a value is not real.
        ValueError: If a value is not finite or a mapping is incomplete.

    References:
        [REF-BILLINGSLEY-1995, Section 13]. No equation is evaluated.

    """
    raw = _values(function, outcomes, name=name)
    return {
        outcome: _scalar(value, name=f"{name}({outcome!r})")
        for outcome, value in raw.items()
    }


def is_sigma_algebra(
    outcomes: Iterable[OutcomeT], collection: Iterable[EventLike[OutcomeT]]
) -> bool:
    """Return whether a collection of subsets is a sigma-algebra.

    On a finite set countable unions reduce to finite unions, so the check is
    that the collection contains the whole set and is closed under complement
    and pairwise union ([EQ-MEAS-001]).

    Args:
        outcomes: The underlying finite set.
        collection: Candidate family of subsets.

    Returns:
        ``True`` exactly when the family is a sigma-algebra.

    Raises:
        TypeError: If an item is not an iterable of hashable outcomes.
        ValueError: If an item contains an outcome outside the set.

    Equation:
        [EQ-MEAS-001].

    References:
        [REF-BILLINGSLEY-1995, Section 2], [REF-DURRETT-2019, Section 1.1].

    """
    universe = frozenset(_ordered_outcomes(outcomes))
    sets: set[frozenset[Hashable]] = set()
    for index, item in enumerate(collection):
        members = _members(item, name=f"collection[{index}]")
        if not members <= universe:
            raise ValueError(f"collection[{index}] has outcomes outside the set")
        sets.add(members)
    if universe not in sets:
        return False
    for members in sets:
        if universe - members not in sets:
            return False
    return all(first | second in sets for first in sets for second in sets)


@dataclass(frozen=True, slots=True, init=False, eq=False)
class FiniteMeasurableSpace(Generic[OutcomeT]):
    """A finite set with the sigma-algebra generated by chosen subsets.

    The generated sigma-algebra is described by its atoms: two outcomes share
    an atom exactly when every generator contains both or neither. Every
    event is a union of atoms, so with ``k`` atoms there are ``2^k`` events
    ([EQ-MEAS-001]). Without generators the sigma-algebra is the power set,
    the convention of :class:`~probstat.probability.FiniteSampleSpace`.

    Args:
        outcomes: Distinct hashable outcomes; a ``FiniteSampleSpace`` works.
        generators: Optional subsets (iterables of outcomes or
            ``FiniteEvent`` objects) generating the sigma-algebra.

    Raises:
        TypeError: If an outcome or generator member is unhashable.
        ValueError: If no outcome is given, an outcome repeats, or a
            generator has an outcome outside the set.

    Equation:
        [EQ-MEAS-001].

    References:
        [REF-BILLINGSLEY-1995, Section 2], [REF-DURRETT-2019, Section 1.1].

    """

    _outcomes: tuple[OutcomeT, ...]
    _atoms: tuple[frozenset[OutcomeT], ...]
    _atom_index: Mapping[OutcomeT, int] = field(repr=False)

    def __init__(
        self,
        outcomes: Iterable[OutcomeT],
        generators: Iterable[EventLike[OutcomeT]] | None = None,
    ) -> None:
        """Generate the sigma-algebra and store its atoms.

        Args:
            outcomes: Distinct hashable outcomes.
            generators: Optional generating subsets; ``None`` gives the
                power set.

        Raises:
            TypeError: If an outcome or generator member is unhashable.
            ValueError: If the outcomes or generators are invalid.

        Equation:
            [EQ-MEAS-001].

        References:
            [REF-BILLINGSLEY-1995, Section 2].

        """
        ordered = _ordered_outcomes(outcomes)
        universe = frozenset(ordered)
        if generators is None:
            cells: list[list[OutcomeT]] = [[outcome] for outcome in ordered]
        else:
            generating: list[frozenset[Hashable]] = []
            for index, generator in enumerate(generators):
                members = _members(generator, name=f"generators[{index}]")
                if not members <= universe:
                    raise ValueError(
                        f"generators[{index}] has outcomes outside the set"
                    )
                generating.append(members)
            groups: dict[tuple[bool, ...], list[OutcomeT]] = {}
            for outcome in ordered:
                signature = tuple(outcome in members for members in generating)
                groups.setdefault(signature, []).append(outcome)
            cells = list(groups.values())
        self._store(ordered, cells)

    def _store(
        self, ordered: tuple[OutcomeT, ...], cells: Sequence[Sequence[OutcomeT]]
    ) -> None:
        """Freeze the outcomes, the atoms, and the outcome-to-atom index.

        Args:
            ordered: Validated outcomes in display order.
            cells: Partition of the outcomes into atoms.

        References:
            [REF-BILLINGSLEY-1995, Section 2]. No equation is evaluated.

        """
        atoms = tuple(frozenset(cell) for cell in cells)
        index = {
            outcome: number for number, atom in enumerate(atoms) for outcome in atom
        }
        object.__setattr__(self, "_outcomes", ordered)
        object.__setattr__(self, "_atoms", atoms)
        object.__setattr__(self, "_atom_index", MappingProxyType(index))

    @classmethod
    def power_set(cls, outcomes: Iterable[OutcomeT]) -> FiniteMeasurableSpace[OutcomeT]:
        """Return the space whose sigma-algebra is every subset.

        Args:
            outcomes: Distinct hashable outcomes.

        Returns:
            The power-set measurable space, with one atom per outcome.

        Equation:
            [EQ-MEAS-001].

        References:
            [REF-BILLINGSLEY-1995, Section 2].

        """
        return cls(outcomes)

    @classmethod
    def trivial(cls, outcomes: Iterable[OutcomeT]) -> FiniteMeasurableSpace[OutcomeT]:
        """Return the space with the trivial sigma-algebra ``{empty, Omega}``.

        Args:
            outcomes: Distinct hashable outcomes.

        Returns:
            A measurable space with a single atom.

        Equation:
            [EQ-MEAS-001].

        References:
            [REF-BILLINGSLEY-1995, Section 2].

        """
        return cls(outcomes, ())

    @classmethod
    def from_partition(
        cls,
        outcomes: Iterable[OutcomeT],
        cells: Iterable[EventLike[OutcomeT]],
    ) -> FiniteMeasurableSpace[OutcomeT]:
        """Return the sigma-algebra whose atoms are the given partition cells.

        Args:
            outcomes: Distinct hashable outcomes.
            cells: Non-empty, pairwise-disjoint subsets covering the set.

        Returns:
            The measurable space with exactly these atoms.

        Raises:
            ValueError: If a cell is empty, cells overlap, or they do not
                cover the set.

        Equation:
            [EQ-MEAS-001].

        References:
            [REF-BILLINGSLEY-1995, Section 2].

        """
        ordered = _ordered_outcomes(outcomes)
        universe = frozenset(ordered)
        covered: set[Hashable] = set()
        materialized: list[frozenset[OutcomeT]] = []
        for index, cell in enumerate(cells):
            members = _members(cell, name=f"cells[{index}]")
            if not members:
                raise ValueError(f"cells[{index}] is empty")
            if not members <= universe:
                raise ValueError(f"cells[{index}] has outcomes outside the set")
            if covered & members:
                raise ValueError(f"cells[{index}] overlaps an earlier cell")
            covered.update(members)
            materialized.append(frozenset(o for o in ordered if o in members))
        if covered != universe:
            raise ValueError("cells do not cover the set")
        return cls(ordered, materialized)

    @classmethod
    def generated_by_map(
        cls,
        outcomes: Iterable[OutcomeT],
        mapping: Callable[[OutcomeT], Hashable] | Mapping[OutcomeT, Hashable],
    ) -> FiniteMeasurableSpace[OutcomeT]:
        """Return ``sigma(X)``, the sigma-algebra generated by a map ``X``.

        Its atoms are the non-empty level sets ``X^-1({x})``.

        Args:
            outcomes: Distinct hashable outcomes.
            mapping: Callable or complete mapping with hashable values.

        Returns:
            The smallest sigma-algebra making ``mapping`` measurable into its
            power-set codomain.

        Raises:
            TypeError: If a value is unhashable.
            ValueError: If a mapping's keys differ from the outcomes.

        Equation:
            [EQ-MEAS-001], [EQ-MEAS-003].

        References:
            [REF-BILLINGSLEY-1995, Section 13], [REF-DURRETT-2019, Section 1.3].

        """
        ordered = _ordered_outcomes(outcomes)
        values = _values(mapping, ordered, name="mapping")
        levels: dict[Hashable, list[OutcomeT]] = {}
        for outcome, value in values.items():
            try:
                levels.setdefault(value, []).append(outcome)
            except TypeError as error:
                raise TypeError(f"mapping({outcome!r}) must be hashable") from error
        space = cls.__new__(cls)
        space._store(ordered, list(levels.values()))
        return space

    def __eq__(self, other: object) -> bool:
        """Return whether two spaces have equal outcomes and equal atoms.

        Args:
            other: Object to compare.

        Returns:
            ``True`` when the outcome sets and sigma-algebras coincide.

        References:
            [REF-BILLINGSLEY-1995, Section 2]. No equation is evaluated.

        """
        if not isinstance(other, FiniteMeasurableSpace):
            return NotImplemented
        return frozenset(self._outcomes) == frozenset(other._outcomes) and frozenset(
            self._atoms
        ) == frozenset(other._atoms)

    def __hash__(self) -> int:
        """Hash consistently with structural equality.

        Returns:
            Hash of the outcome set and the atom set.

        References:
            [REF-PYTHON-DATAMODEL]. No equation is evaluated.

        """
        value: int = hash((frozenset(self._outcomes), frozenset(self._atoms)))
        return value

    @property
    def outcomes(self) -> tuple[OutcomeT, ...]:
        """Return the outcomes in input order.

        References:
            [REF-BILLINGSLEY-1995, Section 2]. No equation is evaluated.

        """
        return self._outcomes

    @property
    def atoms(self) -> tuple[frozenset[OutcomeT], ...]:
        """Return the atoms (cells of the generated partition) in order.

        References:
            [EQ-MEAS-001], [REF-BILLINGSLEY-1995, Section 2].

        """
        return self._atoms

    @property
    def event_count(self) -> int:
        """Return the number of events, ``2^k`` for ``k`` atoms.

        References:
            [EQ-MEAS-001], [REF-BILLINGSLEY-1995, Section 2].

        """
        return 1 << len(self._atoms)

    def atom_of(self, outcome: OutcomeT) -> frozenset[OutcomeT]:
        """Return the atom containing ``outcome``.

        Args:
            outcome: An outcome of the space.

        Returns:
            The smallest event containing ``outcome``.

        Raises:
            ValueError: If ``outcome`` is not in the space.

        References:
            [EQ-MEAS-001], [REF-BILLINGSLEY-1995, Section 2].

        """
        try:
            return self._atoms[self._atom_index[outcome]]
        except (KeyError, TypeError) as error:
            raise ValueError(f"{outcome!r} is not an outcome of the space") from error

    def _subset(self, event: object, *, name: str) -> frozenset[OutcomeT]:
        """Validate that ``event`` is a subset of the outcomes.

        Args:
            event: Candidate event.
            name: Argument name used in error messages.

        Returns:
            The event's members.

        Raises:
            TypeError: If ``event`` is not an iterable of hashable outcomes.
            ValueError: If ``event`` has an outcome outside the space.

        References:
            [REF-BILLINGSLEY-1995, Section 2]. No equation is evaluated.

        """
        members = _members(event, name=name)
        outside = members - frozenset(self._outcomes)
        if outside:
            raise ValueError(f"{name} has outcomes outside the space: {outside!r}")
        return frozenset(member for member in self._outcomes if member in members)

    def is_measurable(self, event: EventLike[OutcomeT]) -> bool:
        """Return whether ``event`` belongs to the sigma-algebra.

        A subset is measurable exactly when it is a union of atoms, that is,
        every atom lies inside it or outside it.

        Args:
            event: Subset of the outcomes.

        Returns:
            Whether the subset is an event of this space.

        Raises:
            TypeError: If ``event`` is not an iterable of hashable outcomes.
            ValueError: If ``event`` has an outcome outside the space.

        Equation:
            [EQ-MEAS-001].

        References:
            [REF-BILLINGSLEY-1995, Section 2].

        """
        members = self._subset(event, name="event")
        return all(atom <= members or atom.isdisjoint(members) for atom in self._atoms)

    def _require_measurable(self, event: object, *, name: str) -> frozenset[OutcomeT]:
        """Return the members of ``event`` or reject a non-measurable subset.

        Args:
            event: Candidate event.
            name: Argument name used in error messages.

        Returns:
            The event's members.

        Raises:
            ValueError: If ``event`` is not measurable.

        References:
            [EQ-MEAS-001], [REF-BILLINGSLEY-1995, Section 2].

        """
        members = self._subset(event, name=name)
        if not all(atom <= members or atom.isdisjoint(members) for atom in self._atoms):
            raise ValueError(f"{name} is not measurable: it splits an atom")
        return members

    def events(self) -> Iterator[frozenset[OutcomeT]]:
        """Iterate over all ``2^k`` events as unions of atoms.

        The count grows exponentially with the number of atoms; this is meant
        for small teaching examples and exhaustive checks.

        Returns:
            An iterator over every measurable subset, the empty set first.

        Equation:
            [EQ-MEAS-001].

        References:
            [REF-BILLINGSLEY-1995, Section 2].

        """
        for code in range(self.event_count):
            members: set[OutcomeT] = set()
            for position, atom in enumerate(self._atoms):
                if code >> position & 1:
                    members.update(atom)
            yield frozenset(members)

    def _require_same_outcomes(self, other: object, *, name: str) -> None:
        """Require another measurable space on the same outcome set.

        Args:
            other: Candidate space.
            name: Argument name used in error messages.

        Raises:
            TypeError: If ``other`` is not a ``FiniteMeasurableSpace``.
            ValueError: If the outcome sets differ.

        References:
            [REF-BILLINGSLEY-1995, Section 2]. No equation is evaluated.

        """
        if not isinstance(other, FiniteMeasurableSpace):
            raise TypeError(f"{name} must be a FiniteMeasurableSpace")
        if frozenset(other._outcomes) != frozenset(self._outcomes):
            raise ValueError(f"{name} must have the same outcomes")

    def is_sub_sigma_algebra_of(self, other: FiniteMeasurableSpace[OutcomeT]) -> bool:
        """Return whether this sigma-algebra is contained in ``other``'s.

        Containment holds exactly when every atom of this space is a union of
        atoms of ``other``, that is, ``other``'s partition refines this one.

        Args:
            other: Space on the same outcomes.

        Returns:
            Whether every event of this space is an event of ``other``.

        Raises:
            TypeError: If ``other`` is not a ``FiniteMeasurableSpace``.
            ValueError: If the outcome sets differ.

        Equation:
            [EQ-MEAS-001].

        References:
            [REF-BILLINGSLEY-1995, Section 2], [REF-DURRETT-2019, Section 4.1].

        """
        self._require_same_outcomes(other, name="other")
        return all(other.is_measurable(atom) for atom in self._atoms)

    def preimage(
        self,
        mapping: Callable[[OutcomeT], TargetT] | Mapping[OutcomeT, TargetT],
        target_event: Iterable[TargetT],
    ) -> frozenset[OutcomeT]:
        """Return ``f^-1(B)`` for a map ``f`` and a target subset ``B``.

        Args:
            mapping: Callable or complete mapping on the outcomes.
            target_event: Subset of the codomain.

        Returns:
            The outcomes mapped into ``target_event``.

        Raises:
            TypeError: If ``target_event`` is not an iterable of hashables.

        Equation:
            [EQ-MEAS-003].

        References:
            [REF-BILLINGSLEY-1995, Section 13].

        """
        wanted = _members(target_event, name="target_event")
        values = _values(mapping, self._outcomes, name="mapping")
        return frozenset(
            outcome for outcome, value in values.items() if value in wanted
        )

    def is_measurable_map(
        self,
        mapping: Callable[[OutcomeT], TargetT] | Mapping[OutcomeT, TargetT],
        target: FiniteMeasurableSpace[TargetT],
    ) -> bool:
        """Return whether ``mapping`` is measurable into ``target``.

        Because the target sigma-algebra is generated by its atoms, it is
        enough that every atom has a measurable preimage.

        Args:
            mapping: Callable or complete mapping from outcomes to target
                outcomes.
            target: Codomain measurable space.

        Returns:
            Whether ``f^-1(B)`` is an event for every target event ``B``.

        Raises:
            TypeError: If ``target`` is not a ``FiniteMeasurableSpace``.
            ValueError: If a value lies outside the target outcomes.

        Equation:
            [EQ-MEAS-003].

        References:
            [REF-BILLINGSLEY-1995, Section 13], [REF-DURRETT-2019, Section 1.3].

        """
        if not isinstance(target, FiniteMeasurableSpace):
            raise TypeError("target must be a FiniteMeasurableSpace")
        values = _values(mapping, self._outcomes, name="mapping")
        allowed = frozenset(target.outcomes)
        for outcome, value in values.items():
            if value not in allowed:
                raise ValueError(f"mapping({outcome!r}) is not a target outcome")
        for atom in target.atoms:
            inverse = frozenset(o for o, value in values.items() if value in atom)
            if not self.is_measurable(inverse):
                return False
        return True

    def is_measurable_function(
        self, function: Callable[[OutcomeT], Hashable] | Mapping[OutcomeT, Hashable]
    ) -> bool:
        """Return whether a finite-valued function is measurable.

        With the power set on its (finite) range, which for real values
        coincides with the Borel trace, a function is measurable exactly when
        it is constant on every atom.

        Args:
            function: Callable or complete mapping with hashable values.

        Returns:
            Whether every level set is an event.

        Equation:
            [EQ-MEAS-003].

        References:
            [REF-BILLINGSLEY-1995, Section 13].

        """
        values = _values(function, self._outcomes, name="function")
        for atom in self._atoms:
            first = next(iter(atom))
            if any(values[outcome] != values[first] for outcome in atom):
                return False
        return True

    def product(
        self, other: FiniteMeasurableSpace[OtherT]
    ) -> FiniteMeasurableSpace[tuple[OutcomeT, OtherT]]:
        """Return the product space with the sigma-algebra of rectangles.

        The product sigma-algebra is generated by measurable rectangles
        ``A x B``; on finite spaces its atoms are the products of atoms.

        Args:
            other: Second factor.

        Returns:
            Space on outcome pairs ``(x, y)``.

        Raises:
            TypeError: If ``other`` is not a ``FiniteMeasurableSpace``.

        Equation:
            [EQ-MEAS-005].

        References:
            [REF-BILLINGSLEY-1995, Section 18], [REF-DURRETT-2019, Section 1.7].

        """
        if not isinstance(other, FiniteMeasurableSpace):
            raise TypeError("other must be a FiniteMeasurableSpace")
        pairs = tuple((x, y) for x in self._outcomes for y in other.outcomes)
        cells = [
            [(x, y) for x in first for y in second]
            for first in self._atoms
            for second in other.atoms
        ]
        space: FiniteMeasurableSpace[tuple[OutcomeT, OtherT]] = (
            FiniteMeasurableSpace.__new__(FiniteMeasurableSpace)
        )
        space._store(pairs, cells)
        return space


@dataclass(frozen=True, slots=True)
class FubiniCheck:
    """Product integral and both iterated integrals of one function.

    Args:
        product_integral: ``integral f d(mu x nu)``.
        outer_first: ``integral [integral f(x, y) nu(dy)] mu(dx)``.
        outer_second: ``integral [integral f(x, y) mu(dx)] nu(dy)``.
        agree: Whether the three values coincide (exactly for fractions).

    References:
        [EQ-MEAS-005], [REF-BILLINGSLEY-1995, Section 18].

    """

    product_integral: Scalar
    outer_first: Scalar
    outer_second: Scalar
    agree: bool


@dataclass(frozen=True, slots=True, init=False, eq=False)
class FiniteMeasure(Generic[OutcomeT]):
    """A non-negative measure on a finite measurable space.

    The measure is specified by one non-negative mass per atom; the measure
    of an event is the sum of the masses of the atoms it contains, so finite
    and countable additivity hold by construction ([EQ-MEAS-002]). Subsets
    that split an atom are not events and have no measure.

    Args:
        space: Finite measurable space.
        atom_masses: Mapping from each atom (any iterable of its outcomes,
            such as a ``frozenset``) to a non-negative number.

    Raises:
        TypeError: If ``space`` has the wrong type or a mass is not real.
        ValueError: If the keys are not exactly the atoms or a mass is
            negative or non-finite.

    Equation:
        [EQ-MEAS-002].

    References:
        [REF-BILLINGSLEY-1995, Section 10], [REF-DURRETT-2019, Section 1.1].

    """

    space: FiniteMeasurableSpace[OutcomeT]
    _masses: Mapping[frozenset[OutcomeT], Scalar] = field(repr=False)

    def __init__(
        self,
        space: FiniteMeasurableSpace[OutcomeT],
        atom_masses: Mapping[frozenset[OutcomeT], NumberLike],
    ) -> None:
        """Validate one non-negative mass per atom.

        Args:
            space: Finite measurable space.
            atom_masses: Atom-to-mass mapping.

        Raises:
            TypeError: If an argument has the wrong type.
            ValueError: If keys or masses violate the measure contract.

        Equation:
            [EQ-MEAS-002].

        References:
            [REF-BILLINGSLEY-1995, Section 10].

        """
        if not isinstance(space, FiniteMeasurableSpace):
            raise TypeError("space must be a FiniteMeasurableSpace")
        if not isinstance(atom_masses, Mapping):
            raise TypeError("atom_masses must be a mapping from atoms to masses")
        supplied: dict[frozenset[Hashable], object] = {}
        for key, value in atom_masses.items():
            members = _members(key, name="atom key")
            if members in supplied:
                raise ValueError(f"atom {set(members)!r} is given twice")
            supplied[members] = value
        if frozenset(supplied) != frozenset(space.atoms):
            raise ValueError("atom_masses keys must be exactly the atoms of the space")
        masses: dict[frozenset[OutcomeT], Scalar] = {}
        for atom in space.atoms:
            mass = _scalar(supplied[atom], name=f"mass of atom {set(atom)!r}")
            if mass < 0:
                raise ValueError(f"mass of atom {set(atom)!r} must be non-negative")
            masses[atom] = mass
        object.__setattr__(self, "space", space)
        object.__setattr__(self, "_masses", MappingProxyType(masses))

    @classmethod
    def from_point_masses(
        cls,
        masses: Mapping[OutcomeT, NumberLike],
        space: FiniteMeasurableSpace[OutcomeT] | None = None,
    ) -> FiniteMeasure[OutcomeT]:
        """Build a measure from outcome masses, optionally on a coarser space.

        Without ``space`` the power set on the mapping's keys is used. With a
        coarser ``space`` the result is the restriction of the point-mass
        measure: each atom receives the total mass of its outcomes.

        Args:
            masses: One non-negative number per outcome.
            space: Optional measurable space on exactly these outcomes.

        Returns:
            The measure ``mu(A) = sum_(omega in A) m(omega)`` on ``space``.

        Raises:
            ValueError: If keys and outcomes differ or a mass is negative.

        Equation:
            [EQ-MEAS-002].

        References:
            [REF-BILLINGSLEY-1995, Section 10].

        """
        target = FiniteMeasurableSpace(masses) if space is None else space
        values = _real_values(masses, target.outcomes, name="masses")
        for outcome, value in values.items():
            if value < 0:
                raise ValueError(f"masses[{outcome!r}] must be non-negative")
        atom_masses = {
            atom: _sum(values[outcome] for outcome in atom) for atom in target.atoms
        }
        return cls(target, atom_masses)

    @classmethod
    def counting(cls, outcomes: Iterable[OutcomeT]) -> FiniteMeasure[OutcomeT]:
        """Return the counting measure on the power set.

        Args:
            outcomes: Distinct hashable outcomes.

        Returns:
            The measure ``mu(A) = |A|``.

        Equation:
            [EQ-MEAS-002].

        References:
            [REF-BILLINGSLEY-1995, Section 10].

        """
        space = FiniteMeasurableSpace(outcomes)
        return cls(space, {atom: _ONE for atom in space.atoms})

    @classmethod
    def from_probability_measure(
        cls, measure: FiniteProbabilityMeasure[OutcomeT]
    ) -> FiniteMeasure[OutcomeT]:
        """Convert a ``FiniteProbabilityMeasure`` on the power set.

        Args:
            measure: Probability measure of the finite layer.

        Returns:
            The same probability measure with its weights as floats.

        Raises:
            TypeError: If ``measure`` has the wrong type.

        Equation:
            [EQ-MEAS-002], [EQ-PROB-002].

        References:
            [REF-BILLINGSLEY-1995, Section 2], [REF-KOLMOGOROV-1956, Chapter I].

        """
        if not isinstance(measure, FiniteProbabilityMeasure):
            raise TypeError("measure must be a FiniteProbabilityMeasure")
        return cls.from_point_masses(dict(measure.weights))

    @property
    def atom_masses(self) -> Mapping[frozenset[OutcomeT], Scalar]:
        """Return the read-only atom-to-mass mapping.

        References:
            [EQ-MEAS-002], [REF-BILLINGSLEY-1995, Section 10].

        """
        return self._masses

    @property
    def total_mass(self) -> Scalar:
        """Return ``mu(Omega)``.

        References:
            [EQ-MEAS-002], [REF-BILLINGSLEY-1995, Section 10].

        """
        return _sum(self._masses.values())

    @property
    def is_probability(self) -> bool:
        """Return whether the total mass is one (exactly, or within 1e-12).

        References:
            [EQ-MEAS-002], [REF-DURRETT-2019, Section 1.1].

        """
        return _equal(self.total_mass, _ONE, _TOLERANCE)

    @property
    def support(self) -> frozenset[OutcomeT]:
        """Return the union of the atoms with positive mass.

        References:
            [EQ-MEAS-002], [REF-BILLINGSLEY-1995, Section 10].

        """
        return frozenset(
            outcome
            for atom, mass in self._masses.items()
            if not _is_zero(mass)
            for outcome in atom
        )

    def measure_of(self, event: EventLike[OutcomeT]) -> Scalar:
        """Return ``mu(A)`` for a measurable event ``A``.

        Args:
            event: Measurable subset of the outcomes.

        Returns:
            The total mass of the atoms contained in ``event``.

        Raises:
            ValueError: If ``event`` is not measurable or leaves the space.

        Equation:
            [EQ-MEAS-002].

        References:
            [REF-BILLINGSLEY-1995, Section 10].

        """
        members = self.space._require_measurable(event, name="event")
        return _sum(mass for atom, mass in self._masses.items() if atom <= members)

    def _measurable_values(
        self,
        function: Callable[[OutcomeT], NumberLike] | Mapping[OutcomeT, NumberLike],
        *,
        name: str,
        space: FiniteMeasurableSpace[OutcomeT] | None = None,
    ) -> dict[OutcomeT, Scalar]:
        """Evaluate a real function and require it to be measurable.

        Args:
            function: Callable or complete mapping with real values.
            name: Argument name used in error messages.
            space: Sigma-algebra to check against (default: this space).

        Returns:
            Outcome-to-number dictionary.

        Raises:
            ValueError: If the function is not constant on every atom.

        Equation:
            [EQ-MEAS-003].

        References:
            [REF-BILLINGSLEY-1995, Section 13].

        """
        reference = self.space if space is None else space
        values = _real_values(function, reference.outcomes, name=name)
        if not reference.is_measurable_function(values):
            raise ValueError(f"{name} is not measurable: it varies within an atom")
        return values

    def simple_integral(
        self, terms: Iterable[tuple[NumberLike, EventLike[OutcomeT]]]
    ) -> Scalar:
        """Integrate the simple function ``sum_i c_i 1_(A_i)``.

        Args:
            terms: Pairs ``(c_i, A_i)`` with real ``c_i`` and measurable
                ``A_i``; the sets need not be disjoint.

        Returns:
            ``sum_i c_i mu(A_i)``.

        Raises:
            ValueError: If a set is not measurable.

        Equation:
            [EQ-MEAS-004].

        References:
            [REF-BILLINGSLEY-1995, Section 15], [REF-DURRETT-2019, Section 1.4].

        """
        products: list[Scalar] = []
        for index, (coefficient, event) in enumerate(terms):
            value = _scalar(coefficient, name=f"terms[{index}] coefficient")
            products.append(value * self.measure_of(event))
        return _sum(products)

    def integrate(
        self,
        function: Callable[[OutcomeT], NumberLike] | Mapping[OutcomeT, NumberLike],
    ) -> Scalar:
        """Return the Lebesgue integral of a measurable real function.

        A measurable function on a finite space is simple with the atoms as
        its level partition, so ``integral f dmu = sum_a f(a) mu(a)``.

        Args:
            function: Callable or complete mapping with real values.

        Returns:
            The integral.

        Raises:
            ValueError: If ``function`` is not measurable.

        Equation:
            [EQ-MEAS-004].

        References:
            [REF-BILLINGSLEY-1995, Sections 15-16], [REF-DURRETT-2019,
            Sections 1.4-1.6].

        """
        values = self._measurable_values(function, name="function")
        return _sum(
            values[next(iter(atom))] * mass for atom, mass in self._masses.items()
        )

    def integrate_over(
        self,
        function: Callable[[OutcomeT], NumberLike] | Mapping[OutcomeT, NumberLike],
        event: EventLike[OutcomeT],
    ) -> Scalar:
        """Return ``integral_A f dmu = integral f 1_A dmu``.

        Args:
            function: Measurable real function.
            event: Measurable set ``A``.

        Returns:
            The integral of ``f`` over ``A``.

        Raises:
            ValueError: If ``function`` or ``event`` is not measurable.

        Equation:
            [EQ-MEAS-004].

        References:
            [REF-BILLINGSLEY-1995, Section 16].

        """
        values = self._measurable_values(function, name="function")
        members = self.space._require_measurable(event, name="event")
        return _sum(
            values[next(iter(atom))] * mass
            for atom, mass in self._masses.items()
            if atom <= members
        )

    def restrict(
        self, sub_space: FiniteMeasurableSpace[OutcomeT]
    ) -> FiniteMeasure[OutcomeT]:
        """Restrict the measure to a sub-sigma-algebra.

        Args:
            sub_space: Space on the same outcomes whose sigma-algebra is
                contained in this one.

        Returns:
            The measure ``A -> mu(A)`` for ``A`` in the sub-sigma-algebra.

        Raises:
            ValueError: If ``sub_space`` is not a sub-sigma-algebra.

        Equation:
            [EQ-MEAS-002].

        References:
            [REF-BILLINGSLEY-1995, Section 10].

        """
        self._require_sub(sub_space, name="sub_space")
        return FiniteMeasure(
            sub_space, {atom: self.measure_of(atom) for atom in sub_space.atoms}
        )

    def _require_sub(self, sub_space: object, *, name: str) -> None:
        """Require a sub-sigma-algebra of this measure's sigma-algebra.

        Args:
            sub_space: Candidate space.
            name: Argument name used in error messages.

        Raises:
            TypeError: If ``sub_space`` has the wrong type.
            ValueError: If the outcomes differ or containment fails.

        References:
            [EQ-MEAS-001], [REF-DURRETT-2019, Section 4.1].

        """
        if not isinstance(sub_space, FiniteMeasurableSpace):
            raise TypeError(f"{name} must be a FiniteMeasurableSpace")
        self.space._require_same_outcomes(sub_space, name=name)
        if not sub_space.is_sub_sigma_algebra_of(self.space):
            raise ValueError(f"{name} is not a sub-sigma-algebra of the space")

    def pushforward(
        self,
        mapping: Callable[[OutcomeT], TargetT] | Mapping[OutcomeT, TargetT],
        target: FiniteMeasurableSpace[TargetT],
    ) -> FiniteMeasure[TargetT]:
        """Return the image measure ``mu o f^-1`` on ``target``.

        Args:
            mapping: Measurable map from outcomes to target outcomes.
            target: Codomain measurable space.

        Returns:
            The measure ``B -> mu(f^-1(B))``.

        Raises:
            ValueError: If ``mapping`` is not measurable into ``target``.

        Equation:
            [EQ-MEAS-003].

        References:
            [REF-BILLINGSLEY-1995, Section 13], [REF-DURRETT-2019, Section 1.2].

        """
        if not self.space.is_measurable_map(mapping, target):
            raise ValueError("mapping is not measurable into the target space")
        values = _values(mapping, self.space.outcomes, name="mapping")
        masses = {
            atom: self.measure_of(o for o, value in values.items() if value in atom)
            for atom in target.atoms
        }
        return FiniteMeasure(target, masses)

    def product(
        self, other: FiniteMeasure[OtherT]
    ) -> FiniteMeasure[tuple[OutcomeT, OtherT]]:
        """Return the product measure ``mu x nu`` on the product space.

        It is the unique measure with ``(mu x nu)(A x B) = mu(A) nu(B)``.

        Args:
            other: Second factor measure.

        Returns:
            Product measure on outcome pairs.

        Raises:
            TypeError: If ``other`` is not a ``FiniteMeasure``.

        Equation:
            [EQ-MEAS-005].

        References:
            [REF-BILLINGSLEY-1995, Section 18], [REF-DURRETT-2019, Section 1.7].

        """
        if not isinstance(other, FiniteMeasure):
            raise TypeError("other must be a FiniteMeasure")
        space = self.space.product(other.space)
        masses = {
            frozenset((x, y) for x in first for y in second): first_mass * second_mass
            for first, first_mass in self._masses.items()
            for second, second_mass in other.atom_masses.items()
        }
        return FiniteMeasure(space, masses)

    def fubini_check(
        self,
        function: Callable[[tuple[OutcomeT, OtherT]], NumberLike],
        other: FiniteMeasure[OtherT],
    ) -> FubiniCheck:
        """Compare the product integral with both iterated integrals.

        Every product-measurable function on a finite product is integrable,
        so Fubini-Tonelli asserts that the three values coincide.

        Args:
            function: Real function of a pair ``(x, y)``, measurable for the
                product sigma-algebra.
            other: Second factor measure ``nu``.

        Returns:
            The three integrals and whether they agree.

        Raises:
            ValueError: If ``function`` is not product-measurable.

        Equation:
            [EQ-MEAS-005].

        References:
            [REF-BILLINGSLEY-1995, Section 18], [REF-DURRETT-2019, Section 1.7].

        """
        joint = self.product(other)
        values = joint._measurable_values(function, name="function")
        total = joint.integrate(values)
        inner_y = {
            first: _sum(
                values[(next(iter(first)), next(iter(second)))] * mass
                for second, mass in other.atom_masses.items()
            )
            for first in self.space.atoms
        }
        outer_first = _sum(inner_y[atom] * mass for atom, mass in self._masses.items())
        inner_x = {
            second: _sum(
                values[(next(iter(first)), next(iter(second)))] * mass
                for first, mass in self._masses.items()
            )
            for second in other.space.atoms
        }
        outer_second = _sum(
            inner_x[atom] * mass for atom, mass in other.atom_masses.items()
        )
        agree = _equal(total, outer_first, _TOLERANCE) and _equal(
            total, outer_second, _TOLERANCE
        )
        return FubiniCheck(total, outer_first, outer_second, agree)

    def _require_same_space(
        self, other: object, *, name: str
    ) -> FiniteMeasure[OutcomeT]:
        """Require another measure on the same measurable space.

        Args:
            other: Candidate measure.
            name: Argument name used in error messages.

        Returns:
            ``other`` typed as a measure on this space.

        Raises:
            TypeError: If ``other`` is not a ``FiniteMeasure``.
            ValueError: If the measurable spaces differ.

        References:
            [REF-BILLINGSLEY-1995, Section 32]. No equation is evaluated.

        """
        if not isinstance(other, FiniteMeasure):
            raise TypeError(f"{name} must be a FiniteMeasure")
        if other.space != self.space:
            raise ValueError(f"{name} must live on the same measurable space")
        return other

    def is_absolutely_continuous_wrt(self, reference: FiniteMeasure[OutcomeT]) -> bool:
        """Return whether this measure ``nu`` satisfies ``nu << mu``.

        On a finite space it is enough that every ``mu``-null atom is
        ``nu``-null.

        Args:
            reference: Dominating candidate ``mu`` on the same space.

        Returns:
            Whether ``mu(A) = 0`` implies ``nu(A) = 0``.

        Raises:
            ValueError: If the spaces differ.

        Equation:
            [EQ-MEAS-006].

        References:
            [REF-BILLINGSLEY-1995, Section 32].

        """
        checked = self._require_same_space(reference, name="reference")
        return all(
            _is_zero(self._masses[atom])
            for atom, mass in checked.atom_masses.items()
            if _is_zero(mass)
        )

    def radon_nikodym_derivative(
        self, reference: FiniteMeasure[OutcomeT]
    ) -> Mapping[OutcomeT, Scalar]:
        """Return the density ``d nu / d mu`` of this measure ``nu``.

        On an atom with ``mu(a) > 0`` the density is ``nu(a) / mu(a)``. It is
        defined only ``mu``-almost everywhere; on ``mu``-null atoms the
        value ``0`` is returned by convention. Derivatives obtained this way
        obey the chain rule ``d lambda / d mu = (d lambda / d nu)(d nu / d mu)``
        ``mu``-almost everywhere ([EQ-MEAS-007]).

        Args:
            reference: Dominating measure ``mu`` on the same space.

        Returns:
            Read-only outcome-to-density mapping, constant on atoms.

        Raises:
            ValueError: If the spaces differ or ``nu`` is not absolutely
                continuous with respect to ``mu``.

        Equation:
            [EQ-MEAS-006], [EQ-MEAS-007].

        References:
            [REF-BILLINGSLEY-1995, Section 32].

        """
        checked = self._require_same_space(reference, name="reference")
        if not self.is_absolutely_continuous_wrt(checked):
            raise ValueError(
                "the measure is not absolutely continuous w.r.t. reference"
            )
        density: dict[OutcomeT, Scalar] = {}
        for atom, mass in checked.atom_masses.items():
            value: Scalar = _ZERO if _is_zero(mass) else self._masses[atom] / mass
            for outcome in atom:
                density[outcome] = value
        return MappingProxyType(
            {outcome: density[outcome] for outcome in self.space.outcomes}
        )

    def with_density(
        self,
        density: Callable[[OutcomeT], NumberLike] | Mapping[OutcomeT, NumberLike],
    ) -> FiniteMeasure[OutcomeT]:
        """Return the measure ``nu(A) = integral_A g dmu`` for a density ``g``.

        Args:
            density: Non-negative measurable function ``g``.

        Returns:
            The measure with density ``g`` with respect to this measure.

        Raises:
            ValueError: If ``density`` is negative or not measurable.

        Equation:
            [EQ-MEAS-006].

        References:
            [REF-BILLINGSLEY-1995, Section 16].

        """
        values = self._measurable_values(density, name="density")
        for outcome, value in values.items():
            if value < 0:
                raise ValueError(f"density({outcome!r}) must be non-negative")
        return FiniteMeasure(
            self.space,
            {
                atom: values[next(iter(atom))] * mass
                for atom, mass in self._masses.items()
            },
        )

    def conditional_expectation(
        self,
        function: Callable[[OutcomeT], NumberLike] | Mapping[OutcomeT, NumberLike],
        sub_space: FiniteMeasurableSpace[OutcomeT],
    ) -> Mapping[OutcomeT, Scalar]:
        """Return ``E[X | G]`` for a sub-sigma-algebra ``G``.

        On each atom ``A`` of ``G`` with ``mu(A) > 0`` the value is the
        average ``integral_A X dmu / mu(A)``. The result is ``G``-measurable
        and satisfies ``integral_A E[X | G] dmu = integral_A X dmu`` for every
        ``A`` in ``G``. It is unique only ``mu``-almost everywhere; on null
        atoms the value ``0`` is returned by convention.

        Args:
            function: Measurable real function ``X``.
            sub_space: Sub-sigma-algebra ``G`` of this space.

        Returns:
            Read-only outcome-to-value mapping, constant on atoms of ``G``.

        Raises:
            ValueError: If ``function`` is not measurable or ``sub_space`` is
                not a sub-sigma-algebra.

        Equation:
            [EQ-MEAS-008].

        References:
            [REF-BILLINGSLEY-1995, Section 34], [REF-DURRETT-2019, Section 4.1].

        """
        self._require_sub(sub_space, name="sub_space")
        values = self._measurable_values(function, name="function")
        result: dict[OutcomeT, Scalar] = {}
        for atom in sub_space.atoms:
            mass = self.measure_of(atom)
            value: Scalar = (
                _ZERO if _is_zero(mass) else self.integrate_over(values, atom) / mass
            )
            for outcome in atom:
                result[outcome] = value
        return MappingProxyType(
            {outcome: result[outcome] for outcome in self.space.outcomes}
        )

    def _agree_almost_everywhere(
        self,
        first: Mapping[OutcomeT, Scalar],
        second: Mapping[OutcomeT, Scalar],
        tolerance: float,
    ) -> bool:
        """Return whether two functions agree on every positive-mass atom.

        Args:
            first: First function.
            second: Second function.
            tolerance: Float comparison tolerance.

        Returns:
            Whether the functions are equal ``mu``-almost everywhere.

        References:
            [EQ-MEAS-008], [REF-BILLINGSLEY-1995, Section 34].

        """
        return all(
            _equal(first[outcome], second[outcome], tolerance)
            for atom, mass in self._masses.items()
            if not _is_zero(mass)
            for outcome in atom
        )

    def verify_tower_property(
        self,
        function: Callable[[OutcomeT], NumberLike] | Mapping[OutcomeT, NumberLike],
        finer: FiniteMeasurableSpace[OutcomeT],
        coarser: FiniteMeasurableSpace[OutcomeT],
        *,
        tolerance: float = _TOLERANCE,
    ) -> bool:
        """Check ``E[E[X | G] | H] = E[X | H]`` and ``E[E[X | G]] = E[X]``.

        Args:
            function: Measurable real function ``X``.
            finer: Sub-sigma-algebra ``G`` of this space.
            coarser: Sub-sigma-algebra ``H`` of ``G``.
            tolerance: Comparison tolerance for floats (fractions compare
                exactly).

        Returns:
            Whether both identities hold ``mu``-almost everywhere.

        Raises:
            ValueError: If ``coarser`` is not contained in ``finer`` or
                ``finer`` is not contained in this space.

        Equation:
            [EQ-MEAS-008].

        References:
            [REF-BILLINGSLEY-1995, Section 34], [REF-DURRETT-2019, Section 4.1].

        """
        checked = _check_tolerance(tolerance)
        self._require_sub(finer, name="finer")
        finer._require_same_outcomes(coarser, name="coarser")
        if not coarser.is_sub_sigma_algebra_of(finer):
            raise ValueError("coarser is not a sub-sigma-algebra of finer")
        inner = self.conditional_expectation(function, finer)
        nested = self.conditional_expectation(inner, coarser)
        direct = self.conditional_expectation(function, coarser)
        means_agree = _equal(self.integrate(inner), self.integrate(function), checked)
        return means_agree and self._agree_almost_everywhere(nested, direct, checked)

    def verify_taking_out_what_is_known(
        self,
        function: Callable[[OutcomeT], NumberLike] | Mapping[OutcomeT, NumberLike],
        known: Callable[[OutcomeT], NumberLike] | Mapping[OutcomeT, NumberLike],
        sub_space: FiniteMeasurableSpace[OutcomeT],
        *,
        tolerance: float = _TOLERANCE,
    ) -> bool:
        """Check ``E[Z X | G] = Z E[X | G]`` for a ``G``-measurable ``Z``.

        Args:
            function: Measurable real function ``X``.
            known: Real function ``Z`` measurable with respect to ``G``.
            sub_space: Sub-sigma-algebra ``G``.
            tolerance: Comparison tolerance for floats.

        Returns:
            Whether the identity holds ``mu``-almost everywhere.

        Raises:
            ValueError: If ``known`` is not ``G``-measurable.

        Equation:
            [EQ-MEAS-008].

        References:
            [REF-BILLINGSLEY-1995, Section 34], [REF-DURRETT-2019, Section 4.1].

        """
        checked = _check_tolerance(tolerance)
        self._require_sub(sub_space, name="sub_space")
        values = self._measurable_values(function, name="function")
        factor = self._measurable_values(known, name="known", space=sub_space)
        product = {outcome: factor[outcome] * values[outcome] for outcome in values}
        left = self.conditional_expectation(product, sub_space)
        right_inner = self.conditional_expectation(values, sub_space)
        right = {outcome: factor[outcome] * right_inner[outcome] for outcome in values}
        return self._agree_almost_everywhere(left, right, checked)

    def total_variation_distance(self, other: FiniteMeasure[OutcomeT]) -> Scalar:
        """Return ``sup_A |P(A) - Q(A)| = (1/2) sum_a |P(a) - Q(a)|``.

        Args:
            other: Probability measure on the same space.

        Returns:
            The total-variation distance in ``[0, 1]``.

        Raises:
            ValueError: If the spaces differ or either measure is not a
                probability measure.

        Equation:
            [EQ-MEAS-009].

        References:
            [REF-TSYBAKOV-2009, Chapter 2].

        """
        checked = self._require_same_space(other, name="other")
        if not (self.is_probability and checked.is_probability):
            raise ValueError("total variation is defined here for probability measures")
        differences: list[Scalar] = []
        for atom, mass in self._masses.items():
            difference: Scalar = mass - checked.atom_masses[atom]
            differences.append(-difference if difference < 0 else difference)
        return _sum(differences) / 2


@dataclass(frozen=True, slots=True)
class CompletenessCheck:
    """Result of the finite-family completeness check of a statistic.

    Args:
        statistic_values: Values ``t`` of ``T`` with positive probability
            under at least one family member, in first-appearance order.
        parameter_count: Number of family members ``m``.
        rank: Rank of the ``m x k`` matrix ``P_theta(T = t)``.
        is_complete: Whether ``rank`` equals the number of statistic values.
        witness: A non-zero ``g`` with ``E_theta[g(T)] = 0`` for every
            ``theta`` when the statistic is not complete, otherwise ``None``.
        exact: Whether the computation used exact fractions.

    References:
        [EQ-MEAS-010], [REF-LEHMANN-CASELLA-1998, Section 1.6].

    """

    statistic_values: tuple[Hashable, ...]
    parameter_count: int
    rank: int
    is_complete: bool
    witness: Mapping[Hashable, Scalar] | None
    exact: bool


def _reduced_row_echelon(
    rows: list[list[Scalar]], tolerance: float
) -> tuple[list[list[Scalar]], list[int]]:
    """Reduce a matrix to row-echelon form and record its pivot columns.

    Fractions are eliminated exactly. With floats, partial pivoting is used
    and entries below ``tolerance`` times the largest entry count as zero.

    Args:
        rows: Matrix rows (copied, not modified).
        tolerance: Relative zero threshold for floats.

    Returns:
        The reduced rows and the pivot column indices.

    Equation:
        [EQ-MEAS-010].

    References:
        [REF-GOLUB-VANLOAN-2013, Section 3.2].

    """
    matrix = [list(row) for row in rows]
    exact = all(isinstance(entry, Fraction) for row in matrix for entry in row)
    largest = max((abs(float(entry)) for row in matrix for entry in row), default=0.0)
    threshold = 0.0 if exact else tolerance * max(largest, 1.0)
    columns = len(matrix[0]) if matrix else 0
    pivots: list[int] = []
    pivot_row = 0
    for column in range(columns):
        if pivot_row == len(matrix):
            break
        candidates = range(pivot_row, len(matrix))
        best = max(candidates, key=lambda r: abs(float(matrix[r][column])))
        if exact:
            nonzero = [r for r in candidates if matrix[r][column] != 0]
            if not nonzero:
                continue
            best = nonzero[0]
        elif abs(float(matrix[best][column])) <= threshold:
            continue
        matrix[pivot_row], matrix[best] = matrix[best], matrix[pivot_row]
        pivot = matrix[pivot_row][column]
        matrix[pivot_row] = [entry / pivot for entry in matrix[pivot_row]]
        for other in range(len(matrix)):
            if other != pivot_row:
                factor = matrix[other][column]
                if factor != 0:
                    matrix[other] = [
                        entry - factor * lead
                        for entry, lead in zip(
                            matrix[other], matrix[pivot_row], strict=True
                        )
                    ]
        pivots.append(column)
        pivot_row += 1
    return matrix, pivots


def check_completeness(
    family: Mapping[Hashable, Mapping[OutcomeT, NumberLike]]
    | Sequence[Mapping[OutcomeT, NumberLike]],
    statistic: Callable[[OutcomeT], Hashable] | Mapping[OutcomeT, Hashable],
    *,
    tolerance: float = _TOLERANCE,
) -> CompletenessCheck:
    """Check completeness of a statistic for a finite parametric family.

    ``T`` is complete for ``{P_theta}`` when ``E_theta[g(T)] = 0`` for every
    ``theta`` forces ``g(T) = 0`` almost surely under every ``P_theta``.
    With finitely many parameters and statistic values this is a linear
    system: with ``A[theta, t] = P_theta(T = t)`` over the values ``t`` that
    some ``P_theta`` charges, ``T`` is complete exactly when ``A`` has full
    column rank ([EQ-MEAS-010]). The answer depends on the parameter set: a
    statistic complete for a rich family can fail to be complete for a
    smaller one.

    Args:
        family: Distributions over one finite sample space, as a mapping from
            parameter labels or a sequence. Each is an outcome-to-probability
            mapping with the same keys, non-negative entries summing to one.
        statistic: Callable or complete mapping from outcomes to hashable
            statistic values.
        tolerance: Float tolerance for the total-probability check and the
            rank decision; exact fractions use no tolerance.

    Returns:
        Statistic values, rank, verdict, and a null-space witness ``g`` when
        the statistic is not complete.

    Raises:
        TypeError: If the family or a probability has the wrong type.
        ValueError: If the family is empty, sample spaces differ, or a
            distribution is negative or does not sum to one.

    Equation:
        [EQ-MEAS-010].

    References:
        [REF-LEHMANN-CASELLA-1998, Section 1.6], [REF-CASELLA-BERGER-2002,
        Section 6.2.4].

    """
    checked_tolerance = _check_tolerance(tolerance)
    if isinstance(family, Mapping):
        members = list(family.values())
    elif isinstance(family, Sequence) and not isinstance(family, str | bytes):
        members = list(family)
    else:
        raise TypeError("family must be a mapping or a sequence of distributions")
    if not members:
        raise ValueError("family must contain at least one distribution")
    if not all(isinstance(member, Mapping) for member in members):
        raise TypeError("every family member must be an outcome-to-probability mapping")
    outcomes = _ordered_outcomes(members[0])
    universe = frozenset(outcomes)
    statistic_of = _values(statistic, outcomes, name="statistic")
    distributions: list[dict[OutcomeT, Scalar]] = []
    for index, member in enumerate(members):
        if frozenset(member) != universe:
            raise ValueError(f"family member {index} has a different sample space")
        probabilities = _real_values(member, outcomes, name=f"family[{index}]")
        if any(value < 0 for value in probabilities.values()):
            raise ValueError(f"family member {index} has a negative probability")
        if not _equal(_sum(probabilities.values()), _ONE, checked_tolerance):
            raise ValueError(f"family member {index} does not sum to one")
        distributions.append(probabilities)
    values: list[Hashable] = []
    for outcome in outcomes:
        value = statistic_of[outcome]
        try:
            known = value in values
        except TypeError as error:
            raise TypeError(f"statistic({outcome!r}) must be hashable") from error
        if not known:
            values.append(value)
    rows: list[list[Scalar]] = [
        [_sum(p[o] for o in outcomes if statistic_of[o] == value) for value in values]
        for p in distributions
    ]
    charged = [
        column
        for column in range(len(values))
        if any(not _is_zero(row[column]) for row in rows)
    ]
    support = tuple(values[column] for column in charged)
    matrix = [[row[column] for column in charged] for row in rows]
    exact = all(isinstance(entry, Fraction) for row in matrix for entry in row)
    reduced, pivots = _reduced_row_echelon(matrix, checked_tolerance)
    rank = len(pivots)
    complete = rank == len(support)
    witness: Mapping[Hashable, Scalar] | None = None
    if not complete:
        free = next(column for column in range(len(support)) if column not in pivots)
        unit: Scalar = _ONE if exact else 1.0
        solution: list[Scalar] = [_ZERO if exact else 0.0] * len(support)
        solution[free] = unit
        for row_index, pivot in enumerate(pivots):
            solution[pivot] = -reduced[row_index][free]
        witness = MappingProxyType(dict(zip(support, solution, strict=True)))
    return CompletenessCheck(support, len(members), rank, complete, witness, exact)


def is_complete_statistic(
    family: Mapping[Hashable, Mapping[OutcomeT, NumberLike]]
    | Sequence[Mapping[OutcomeT, NumberLike]],
    statistic: Callable[[OutcomeT], Hashable] | Mapping[OutcomeT, Hashable],
    *,
    tolerance: float = _TOLERANCE,
) -> bool:
    """Return whether a statistic is complete for a finite family.

    Args:
        family: Distributions over one finite sample space.
        statistic: Callable or complete mapping from outcomes to values.
        tolerance: Float tolerance; exact fractions use none.

    Returns:
        The verdict of :func:`check_completeness`.

    Raises:
        TypeError: If an input has the wrong type.
        ValueError: If the family is invalid.

    Equation:
        [EQ-MEAS-010].

    References:
        [REF-LEHMANN-CASELLA-1998, Section 1.6].

    """
    return check_completeness(family, statistic, tolerance=tolerance).is_complete
