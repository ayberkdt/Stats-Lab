@dataclass(frozen=True, slots=True)
class ColumnEncoding:
    """How one input variable is encoded into design-matrix columns.

    Attributes:
        name: Variable name in the input mapping.
        levels: Sorted category labels for a categorical variable, ``None`` for
            a numeric variable.
        reference: The level absorbed into the intercept (no column), or
            ``None`` when every level receives an indicator column.

    References:
        [REF-MONTGOMERY-PECK-VINING-2021, Chapter 8].

    """

    name: str
    levels: tuple[str, ...] | None
    reference: str | None

    @property
    def column_names(self) -> tuple[str, ...]:
        """Return the design-column names generated by this variable.

        Returns:
            ``(name,)`` for numeric variables, ``name[level]`` for every
            non-reference level of a categorical variable.

        Equation:
            [EQ-LM-DESIGN-001].

        References:
            [REF-MONTGOMERY-PECK-VINING-2021, Chapter 8].

        """
        if self.levels is None:
            return (self.name,)
        return tuple(
            f"{self.name}[{level}]" for level in self.levels if level != self.reference
        )


@dataclass(frozen=True, slots=True)
class DesignMatrix:
    """A model matrix together with the encoding needed to rebuild it.

    Attributes:
        rows: ``n x p`` design rows.
        column_names: Names of the ``p`` columns.
        intercept: Whether the first column is the constant ``1``.
        encodings: Per-variable encodings used by :meth:`transform`.

    References:
        [REF-MONTGOMERY-PECK-VINING-2021, Chapters 3 and 8].

    """

    rows: Matrix
    column_names: tuple[str, ...]
    intercept: bool
    encodings: tuple[ColumnEncoding, ...]

    def transform(self, data: Mapping[str, Sequence[object]]) -> Matrix:
        """Encode new observations with the stored levels and references.

        Args:
            data: Mapping from every encoded variable name to equally long
                value sequences.

        Returns:
            Design rows aligned with :attr:`column_names`.

        Raises:
            KeyError: If a variable is missing.
            ValueError: If a categorical value was not seen when fitting or the
                sequences have unequal lengths.

        Equation:
            [EQ-LM-DESIGN-001].

        References:
            [REF-MONTGOMERY-PECK-VINING-2021, Chapter 8].

        """
        return _encode_rows(self.encodings, data, self.intercept)


def _column_length(data: Mapping[str, Sequence[object]], names: Iterable[str]) -> int:
    """Return the common length of the named columns.

    References:
        Project validation policy. No equation is evaluated.

    """
    lengths = {len(data[name]) for name in names}
    if len(lengths) != 1:
        raise ValueError("all data columns must have the same length")
    (length,) = lengths
    if length == 0:
        raise ValueError("data columns must be non-empty")
    return length


def _encode_rows(
    encodings: tuple[ColumnEncoding, ...],
    data: Mapping[str, Sequence[object]],
    intercept: bool,
) -> Matrix:
    """Build design rows from stored encodings.

    References:
        [EQ-LM-DESIGN-001], [REF-MONTGOMERY-PECK-VINING-2021, Chapter 8].

    """
    for encoding in encodings:
        if encoding.name not in data:
            raise KeyError(f"missing data column {encoding.name!r}")
    length = (
        _column_length(data, (encoding.name for encoding in encodings))
        if encodings
        else 0
    )
    if length == 0:
        raise ValueError("at least one encoded variable is required")
    columns: list[Vector] = []
    if intercept:
        columns.append(tuple(1.0 for _ in range(length)))
    for encoding in encodings:
        values = data[encoding.name]
        if encoding.levels is None:
            columns.append(as_vector(values, name=encoding.name))
            continue
        labels = tuple(str(value) for value in values)
        unknown = sorted(set(labels) - set(encoding.levels))
        if unknown:
            raise ValueError(
                f"column {encoding.name!r} has levels not seen when fitting: {unknown}"
            )
        for level in encoding.levels:
            if level == encoding.reference:
                continue
            columns.append(tuple(1.0 if label == level else 0.0 for label in labels))
    return tuple(tuple(column[i] for column in columns) for i in range(length))


def design_matrix(
    data: Mapping[str, Sequence[object]],
    *,
    intercept: bool = True,
    categorical: Iterable[str] = (),
    reference: Mapping[str, object] | None = None,
) -> DesignMatrix:
    """Build a model matrix with an optional intercept and one-hot factors.

    Numeric variables become one column each. A categorical variable with
    levels ``L_1 < ... < L_m`` (sorted as text) becomes indicator columns
    ``1{x_i = L_k}`` for every level except the reference (treatment
    coding), so the intercept is the reference-level mean and each indicator
    coefficient is a contrast against it. Without an intercept, the first
    categorical variable keeps all ``m`` indicators (cell-means coding) and
    later ones drop their reference, which keeps the columns independent.

    Args:
        data: Ordered mapping from variable name to equally long sequences.
            Column order follows the mapping order.
        intercept: Prepend a constant ``1`` column named ``"(Intercept)"``.
        categorical: Names of variables to one-hot encode; values are compared
            through ``str``.
        reference: Optional reference level per categorical variable; the
            default is the first level in sorted order.

    Returns:
        :class:`DesignMatrix` with rows, column names, and encodings.

    Raises:
        KeyError: If a categorical or reference name is not a data column.
        ValueError: If columns are empty or ragged, a numeric value is not
            finite, a reference level does not occur, or a reference is given
            for a numeric variable.
        TypeError: If a numeric value is not real.

    Equation:
        [EQ-LM-DESIGN-001].

    References:
        [REF-MONTGOMERY-PECK-VINING-2021, Chapter 8].

    """
    if not data:
        raise ValueError("data must contain at least one column")
    categorical_names = tuple(categorical)
    for name in categorical_names:
        if name not in data:
            raise KeyError(f"categorical column {name!r} is not in data")
    references = dict(reference or {})
    for name in references:
        if name not in categorical_names:
            raise ValueError(f"reference given for non-categorical column {name!r}")
    _column_length(data, data.keys())
    encodings: list[ColumnEncoding] = []
    first_categorical = True
    for name, values in data.items():
        if name not in categorical_names:
            encodings.append(ColumnEncoding(name=name, levels=None, reference=None))
            continue
        levels = tuple(sorted({str(value) for value in values}))
        chosen = str(references[name]) if name in references else levels[0]
        if chosen not in levels:
            raise ValueError(f"reference level {chosen!r} does not occur in {name!r}")
        keep_all = not intercept and first_categorical
        first_categorical = False
        encodings.append(
            ColumnEncoding(
                name=name, levels=levels, reference=None if keep_all else chosen
            )
        )
    frozen = tuple(encodings)
    rows = _encode_rows(frozen, data, intercept)
    names: list[str] = ["(Intercept)"] if intercept else []
    for encoding in frozen:
        names.extend(encoding.column_names)
    return DesignMatrix(
        rows=rows, column_names=tuple(names), intercept=intercept, encodings=frozen
    )


def _coerce_design(
    design: DesignMatrix | Iterable[Iterable[object]],
    column_names: Sequence[str] | None,
) -> tuple[Matrix, tuple[str, ...], bool]:
    """Return validated rows, column names, and whether a ones column exists.

    References:
        Project validation policy. No equation is evaluated.

    """
    if isinstance(design, DesignMatrix):
        rows = design.rows
        names = design.column_names
        has_intercept = design.intercept or _has_ones_column(rows)
    else:
        rows = as_matrix(design, name="design")
        width = len(rows[0])
        names = (
            tuple(column_names)
            if column_names is not None
            else tuple(f"x{j}" for j in range(width))
        )
        has_intercept = _has_ones_column(rows)
    if len(names) != len(rows[0]):
        raise ValueError("column_names must match the number of design columns")
    if len(set(names)) != len(names):
        raise ValueError("column names must be unique")
    return rows, names, has_intercept


def _has_ones_column(rows: Matrix) -> bool:
    """Return whether some design column is identically one.

    References:
        [REF-MONTGOMERY-PECK-VINING-2021, Chapter 3]. No equation is evaluated.

    """
    return any(all(row[j] == 1.0 for row in rows) for j in range(len(rows[0])))


def _spans_constant(
    factor: HouseholderQR, weighted_rows: Matrix, root_w: Vector
) -> bool:
    """Return whether the design's column space contains the constant vector.

    An intercept can be carried implicitly, e.g. by a full set of dummy
    columns or a constant column of twos; R^2 and the overall F test must
    then be centred. With weights the test is ``sqrt(w) in span(W^1/2 X)``,
    which is equivalent to ``1 in span(X)``.

    References:
        [REF-MONTGOMERY-PECK-VINING-2021, Chapter 3],
        [REF-GOLUB-VANLOAN-2013, Section 5.3]. No new equation is evaluated.

    """
    coefficients = factor.solve(root_w)
    residual = math.fsum(
        (target - math.fsum(c * x for c, x in zip(coefficients, row, strict=True))) ** 2
        for target, row in zip(root_w, weighted_rows, strict=True)
    )
    return math.sqrt(residual) <= 1e-8 * math.sqrt(math.fsum(r * r for r in root_w))


def _positive_weights(weights: Iterable[object] | None, size: int) -> Vector:
    """Validate strictly positive finite case weights.

    References:
        [REF-MONTGOMERY-PECK-VINING-2021, Chapter 5]. No equation is evaluated.

    """
    if weights is None:
        return tuple(1.0 for _ in range(size))
    checked = as_vector(weights, name="weights")
    if len(checked) != size:
        raise ValueError("weights must have one entry per observation")
    if any(value <= 0.0 for value in checked):
        raise ValueError("weights must be strictly positive")
    return checked


def _factorize(
    rows: Matrix, names: tuple[str, ...], rank_tolerance: float
) -> HouseholderQR:
    """Factor a (weighted) design and reject numerically dependent columns.

    References:
        [EQ-LINALG-009], [REF-GOLUB-VANLOAN-2013, Section 5.4].

    """
    factor = householder_qr(rows, rank_tolerance=rank_tolerance)
    if factor.rank_deficient:
        culprits = ", ".join(names[j] for j in factor.rank_deficient)
        raise RankDeficientDesignError(
            "design matrix is rank deficient; column(s) "
            f"{culprits} are linear combinations of earlier columns"
        )
    return factor


def _validate_level(level: object) -> float:
    """Validate a two-sided confidence level in ``(0, 1)``.

    References:
        Project validation policy. No equation is evaluated.

    """
    checked = require_finite_real(level, name="level")
    if not 0.0 < checked < 1.0:
        raise ValueError("level must lie strictly between zero and one")
    return checked


def _quadratic(gram_inverse: Matrix, row: Vector) -> float:
    """Return ``x' G x`` for a symmetric matrix ``G``.

    References:
        [REF-GOLUB-VANLOAN-2013, Section 1.1]. No named equation is needed.

    """
    size = len(row)
    return math.fsum(
        row[i] * gram_inverse[i][j] * row[j] for i in range(size) for j in range(size)
    )


