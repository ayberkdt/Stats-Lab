@dataclass(frozen=True, slots=True)
class LinearPrediction:
    """Point predictions with confidence or prediction intervals.

    Attributes:
        mean: Fitted conditional means ``x0' beta``.
        standard_error: Standard error of the mean (confidence) or of a new
            observation (prediction).
        lower: Lower interval bounds.
        upper: Upper interval bounds.
        level: Two-sided coverage level.
        kind: ``"confidence"`` or ``"prediction"``.
        degrees_of_freedom: Student-t degrees of freedom ``n - p``.

    References:
        [REF-MONTGOMERY-PECK-VINING-2021, Chapter 3].

    """

    mean: Vector
    standard_error: Vector
    lower: Vector
    upper: Vector
    level: float
    kind: str
    degrees_of_freedom: int


@dataclass(frozen=True, slots=True)
class LinearModelResult:
    """Immutable OLS/WLS fit with classical inference and case diagnostics.

    Residual-based quantities use the weighted residuals
    ``e*_i = sqrt(w_i) (y_i - x_i' beta)``; with unit weights they are the
    ordinary residuals.

    Attributes:
        coefficients: Least-squares estimate ``beta``.
        standard_errors: ``sqrt(diag(sigma^2 (X'WX)^-1))``.
        t_values: ``beta_j / se_j``.
        p_values: Two-sided Student-t p-values on ``n - p`` df.
        column_names: Design-column names.
        covariance: ``sigma^2 (X'WX)^-1``.
        unscaled_covariance: ``(X'WX)^-1``.
        fitted_values: ``X beta``.
        residuals: Raw residuals ``y - X beta``.
        weights: Case weights ``w_i``.
        design: Unweighted design rows.
        has_intercept: Whether the column space contains the constant vector
            (an explicit ones column, a constant column, or full dummy coding);
            ``R^2`` and the overall ``F`` test are then centred.
        n_observations: ``n``.
        n_parameters: ``p``.
        df_residual: ``n - p``.
        residual_sum_squares: ``sum w_i e_i^2``.
        total_sum_squares: Weighted centered (with intercept) or uncentered
            (without intercept) total sum of squares.
        residual_variance: ``sigma^2 = RSS / (n - p)``.
        residual_standard_error: ``sigma``.
        r_squared: ``1 - RSS / TSS``.
        adjusted_r_squared: ``1 - (1 - R^2)(n - k0)/(n - p)``.
        f_statistic: Overall F statistic against the intercept-only (or empty)
            model; ``nan`` for an intercept-only fit.
        f_df: Numerator and denominator degrees of freedom.
        f_p_value: Upper-tail F probability.
        leverage: Diagonal of the hat matrix of the weighted design.
        standardized_residuals: Internally studentized residuals.
        studentized_residuals: Externally studentized (deleted) residuals.
        cooks_distance: Cook's distances.
        log_likelihood: Gaussian log-likelihood at the MLE ``RSS / n``.
        aic: Akaike information criterion with ``p + 1`` parameters.
        bic: Bayesian information criterion with ``p + 1`` parameters.

    References:
        [REF-MONTGOMERY-PECK-VINING-2021, Chapters 3-6], [REF-COOK-1977],
        [REF-WHITE-1980].

    """

    coefficients: Vector
    standard_errors: Vector
    t_values: Vector
    p_values: Vector
    column_names: tuple[str, ...]
    covariance: Matrix
    unscaled_covariance: Matrix
    fitted_values: Vector
    residuals: Vector
    weights: Vector
    design: Matrix
    has_intercept: bool
    n_observations: int
    n_parameters: int
    df_residual: int
    residual_sum_squares: float
    total_sum_squares: float
    residual_variance: float
    residual_standard_error: float
    r_squared: float
    adjusted_r_squared: float
    f_statistic: float
    f_df: tuple[int, int]
    f_p_value: float
    leverage: Vector
    standardized_residuals: Vector
    studentized_residuals: Vector
    cooks_distance: Vector
    log_likelihood: float
    aic: float
    bic: float

    def coefficient(self, name: str) -> float:
        """Return one coefficient by column name.

        Args:
            name: Design-column name.

        Returns:
            The estimate for that column.

        Raises:
            KeyError: If no column has that name.

        References:
            [REF-MONTGOMERY-PECK-VINING-2021, Chapter 3]. No equation is
            evaluated.

        """
        if name not in self.column_names:
            raise KeyError(f"no design column named {name!r}")
        return self.coefficients[self.column_names.index(name)]

    def coefficient_intervals(
        self, level: float = 0.95
    ) -> tuple[tuple[float, float], ...]:
        """Return Student-t confidence intervals ``beta_j +- t se_j``.

        Args:
            level: Two-sided confidence level in ``(0, 1)``.

        Returns:
            One ``(lower, upper)`` pair per coefficient.

        Raises:
            ValueError: If ``level`` is invalid.

        Equation:
            [EQ-LM-INF-001].

        References:
            [REF-MONTGOMERY-PECK-VINING-2021, Chapter 3].

        """
        checked = _validate_level(level)
        quantile = student_t_quantile(0.5 * (1.0 + checked), self.df_residual)
        return tuple(
            (beta - quantile * se, beta + quantile * se)
            for beta, se in zip(self.coefficients, self.standard_errors, strict=True)
        )

    def _new_rows(self, rows: Iterable[Iterable[object]]) -> Matrix:
        """Validate new design rows against the fitted column count.

        References:
            Project validation policy. No equation is evaluated.

        """
        checked = as_matrix(rows, name="rows")
        if len(checked[0]) != self.n_parameters:
            raise ValueError("new rows must have one entry per design column")
        return checked

    def predict(self, rows: Iterable[Iterable[object]]) -> Vector:
        """Return fitted means ``x0' beta`` at new design rows.

        Args:
            rows: Design rows encoded like the fitting design (for a
                :class:`DesignMatrix`, use its ``transform``).

        Returns:
            Predicted conditional means.

        Raises:
            ValueError: If a row has the wrong length or is not finite.

        Equation:
            [EQ-LM-PRED-001].

        References:
            [REF-MONTGOMERY-PECK-VINING-2021, Chapter 3].

        """
        checked = self._new_rows(rows)
        return tuple(
            math.fsum(b * x for b, x in zip(self.coefficients, row, strict=True))
            for row in checked
        )

    def interval(
        self,
        rows: Iterable[Iterable[object]],
        *,
        level: float = 0.95,
        kind: IntervalKind = "confidence",
        weights: Iterable[object] | None = None,
    ) -> LinearPrediction:
        """Return confidence intervals for means or prediction intervals.

        The mean at ``x0`` has variance ``sigma^2 x0'(X'WX)^-1 x0``; a new
        observation with weight ``w0`` adds independent noise of variance
        ``sigma^2 / w0``. Both pivots are Student-t on ``n - p`` df under
        normal errors.

        Args:
            rows: New design rows.
            level: Two-sided level in ``(0, 1)``.
            kind: ``"confidence"`` for the mean, ``"prediction"`` for a new
                observation.
            weights: Optional positive weights of the new observations
                (prediction intervals only); default one.

        Returns:
            :class:`LinearPrediction`.

        Raises:
            ValueError: If inputs are invalid.

        Equation:
            [EQ-LM-PRED-001].

        References:
            [REF-MONTGOMERY-PECK-VINING-2021, Chapter 3].

        """
        if kind not in ("confidence", "prediction"):
            raise ValueError("kind must be 'confidence' or 'prediction'")
        checked_level = _validate_level(level)
        checked = self._new_rows(rows)
        new_weights = _positive_weights(weights, len(checked))
        quantile = student_t_quantile(0.5 * (1.0 + checked_level), self.df_residual)
        means = self.predict(checked)
        errors: list[float] = []
        for row, weight in zip(checked, new_weights, strict=True):
            variance = self.residual_variance * _quadratic(
                self.unscaled_covariance, row
            )
            if kind == "prediction":
                variance += self.residual_variance / weight
            errors.append(math.sqrt(max(variance, 0.0)))
        return LinearPrediction(
            mean=means,
            standard_error=tuple(errors),
            lower=tuple(m - quantile * e for m, e in zip(means, errors, strict=True)),
            upper=tuple(m + quantile * e for m, e in zip(means, errors, strict=True)),
            level=checked_level,
            kind=kind,
            degrees_of_freedom=self.df_residual,
        )

    def robust_covariance(self, kind: RobustKind = "HC3") -> Matrix:
        """Return a heteroskedasticity-consistent sandwich covariance.

        With ``X* = W^(1/2) X``, weighted residuals ``e*`` and leverages
        ``h``, the estimator is ``(X*'X*)^-1 X*' diag(omega) X* (X*'X*)^-1``
        with ``omega_i = e*_i^2`` (HC0), ``n/(n-p) e*_i^2`` (HC1),
        ``e*_i^2/(1-h_i)`` (HC2), or ``e*_i^2/(1-h_i)^2`` (HC3).

        Args:
            kind: ``"HC0"``, ``"HC1"``, ``"HC2"``, or ``"HC3"``.

        Returns:
            Symmetric ``p x p`` covariance estimate.

        Raises:
            ValueError: If ``kind`` is unknown or a leverage equals one for
                HC2/HC3.

        Equation:
            [EQ-LM-HC-001].

        References:
            [REF-WHITE-1980], [REF-MACKINNON-WHITE-1985].

        """
        if kind not in ("HC0", "HC1", "HC2", "HC3"):
            raise ValueError("kind must be one of HC0, HC1, HC2, HC3")
        size = self.n_parameters
        meat = [[0.0] * size for _ in range(size)]
        n, p = self.n_observations, self.n_parameters
        terms: list[list[list[float]]] = [
            [[] for _ in range(size)] for _ in range(size)
        ]
        for row, residual, weight, leverage in zip(
            self.design, self.residuals, self.weights, self.leverage, strict=True
        ):
            squared = weight * residual * residual
            if kind == "HC1":
                omega = squared * n / (n - p)
            elif kind == "HC2" or kind == "HC3":
                complement = 1.0 - leverage
                if complement <= 0.0:
                    raise ValueError(f"{kind} is undefined when a leverage equals one")
                omega = squared / (complement if kind == "HC2" else complement**2)
            else:
                omega = squared
            scaled = omega * weight
            for i in range(size):
                for j in range(i, size):
                    terms[i][j].append(scaled * row[i] * row[j])
        for i in range(size):
            for j in range(i, size):
                meat[i][j] = meat[j][i] = math.fsum(terms[i][j])
        bread = self.unscaled_covariance
        left = [
            [
                math.fsum(bread[i][k] * meat[k][j] for k in range(size))
                for j in range(size)
            ]
            for i in range(size)
        ]
        product = [
            [
                math.fsum(left[i][k] * bread[k][j] for k in range(size))
                for j in range(size)
            ]
            for i in range(size)
        ]
        return tuple(
            tuple(0.5 * (product[i][j] + product[j][i]) for j in range(size))
            for i in range(size)
        )

    def robust_standard_errors(self, kind: RobustKind = "HC3") -> Vector:
        """Return square roots of the diagonal of :meth:`robust_covariance`.

        Args:
            kind: ``"HC0"``, ``"HC1"``, ``"HC2"``, or ``"HC3"``.

        Returns:
            Robust standard errors in column order.

        Raises:
            ValueError: As for :meth:`robust_covariance`.

        Equation:
            [EQ-LM-HC-001].

        References:
            [REF-WHITE-1980], [REF-MACKINNON-WHITE-1985].

        """
        covariance = self.robust_covariance(kind)
        return tuple(
            math.sqrt(max(covariance[j][j], 0.0)) for j in range(len(covariance))
        )

    def variance_inflation_factors(self) -> dict[str, float]:
        """Return VIFs of the non-constant design columns.

        Returns:
            Mapping from column name to ``1 / (1 - R_j^2)``.

        Raises:
            ValueError: As for :func:`variance_inflation_factors`.

        Equation:
            [EQ-LM-VIF-001].

        References:
            [REF-MONTGOMERY-PECK-VINING-2021, Chapter 9].

        """
        return variance_inflation_factors(self.design, column_names=self.column_names)


