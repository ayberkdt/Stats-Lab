def _safe_ratio_p(estimate: float, error: float, df: int) -> tuple[float, float]:
    """Return ``(t, p)`` handling a zero standard error explicitly.

    References:
        [EQ-LM-INF-001], [REF-CASELLA-BERGER-2002, Chapter 5].

    """
    if error > 0.0:
        t_value = estimate / error
        if not math.isfinite(t_value):
            return t_value, 0.0
        return t_value, student_t_two_sided_p(t_value, df)
    if estimate == 0.0:
        return math.nan, math.nan
    return math.copysign(math.inf, estimate), 0.0


def fit_linear_model(
    design: DesignMatrix | Iterable[Iterable[object]],
    response: Iterable[object],
    *,
    weights: Iterable[object] | None = None,
    column_names: Sequence[str] | None = None,
    rank_tolerance: float = DEFAULT_RANK_TOLERANCE,
) -> LinearModelResult:
    """Fit ``y = X beta + e`` by ordinary or weighted least squares via QR.

    The weighted rows ``sqrt(w_i) x_i`` are factored as ``QR``; then
    ``beta = R^-1 Q' W^(1/2) y`` solves the normal equations
    ``X'WX beta = X'Wy`` and ``(X'WX)^-1 = R^-1 R^-T``. Inference assumes
    independent normal errors with variance ``sigma^2 / w_i``.

    Args:
        design: :class:`DesignMatrix` or ``n x p`` rows. An intercept is
            recognized as any column identically equal to one.
        response: ``n`` finite responses.
        weights: Optional strictly positive case weights (inverse relative
            variances); default unweighted.
        column_names: Names for a raw design; defaults to ``x0, x1, ...``.
        rank_tolerance: Relative threshold for declaring a column dependent.

    Returns:
        :class:`LinearModelResult` with coefficients, inference, fit measures,
        and case diagnostics.

    Raises:
        RankDeficientDesignError: If columns are numerically dependent.
        TypeError: If an entry is not real.
        ValueError: If shapes disagree, ``n <= p``, or weights are invalid.

    Equation:
        [EQ-LINALG-009], [EQ-LM-OLS-001], [EQ-LM-INF-001], [EQ-LM-FIT-001],
        [EQ-LM-DIAG-001], [EQ-LM-DIAG-002], [EQ-LM-DIAG-003], [EQ-LM-LL-001].

    References:
        [REF-MONTGOMERY-PECK-VINING-2021, Chapters 3-6],
        [REF-GOLUB-VANLOAN-2013, Section 5.3], [REF-COOK-1977].

    """
    rows, names, has_intercept = _coerce_design(design, column_names)
    y = as_vector(response, name="response")
    n, p = len(rows), len(rows[0])
    if len(y) != n:
        raise ValueError("response length must equal the number of design rows")
    if n <= p:
        raise ValueError("linear model needs more observations than coefficients")
    w = _positive_weights(weights, n)
    root_w = tuple(math.sqrt(value) for value in w)
    weighted_rows = tuple(
        tuple(r * value for value in row) for r, row in zip(root_w, rows, strict=True)
    )
    weighted_y = tuple(r * value for r, value in zip(root_w, y, strict=True))
    factor = _factorize(weighted_rows, names, rank_tolerance)
    beta = factor.solve(weighted_y)
    if not has_intercept:
        has_intercept = _spans_constant(factor, weighted_rows, root_w)
    fitted = tuple(
        math.fsum(b * x for b, x in zip(beta, row, strict=True)) for row in rows
    )
    residuals = tuple(value - fit for value, fit in zip(y, fitted, strict=True))
    weighted_residuals = tuple(r * e for r, e in zip(root_w, residuals, strict=True))
    rss = math.fsum(e * e for e in weighted_residuals)
    df = n - p
    sigma2 = rss / df
    gram_inverse = factor.gram_inverse()
    covariance = tuple(tuple(sigma2 * value for value in row) for row in gram_inverse)
    errors = tuple(math.sqrt(max(covariance[j][j], 0.0)) for j in range(p))
    ratios = [_safe_ratio_p(b, e, df) for b, e in zip(beta, errors, strict=True)]
    k0 = 1 if has_intercept else 0
    if has_intercept:
        total_weight = math.fsum(w)
        center = math.fsum(wi * yi for wi, yi in zip(w, y, strict=True)) / total_weight
        tss = math.fsum(wi * (yi - center) ** 2 for wi, yi in zip(w, y, strict=True))
    else:
        tss = math.fsum(wi * yi * yi for wi, yi in zip(w, y, strict=True))
    r_squared = 1.0 - rss / tss if tss > 0.0 else math.nan
    adjusted = 1.0 - (1.0 - r_squared) * (n - k0) / df if tss > 0.0 else math.nan
    df_model = p - k0
    if df_model == 0 or tss <= 0.0:
        f_statistic, f_p = math.nan, math.nan
    elif rss == 0.0:
        f_statistic, f_p = math.inf, 0.0
    else:
        f_statistic = ((tss - rss) / df_model) / sigma2
        f_p = f_sf(max(f_statistic, 0.0), df_model, df)
    leverage = factor.hat_diagonal()
    standardized: list[float] = []
    studentized: list[float] = []
    cooks: list[float] = []
    for e, h in zip(weighted_residuals, leverage, strict=True):
        complement = 1.0 - h
        if complement <= 1e-12 or sigma2 == 0.0:
            standardized.append(math.nan)
            studentized.append(math.nan)
            cooks.append(math.nan)
            continue
        r_value = e / math.sqrt(sigma2 * complement)
        standardized.append(r_value)
        deleted = (rss - e * e / complement) / (df - 1) if df > 1 else math.nan
        studentized.append(
            e / math.sqrt(deleted * complement)
            if deleted > 0.0 and math.isfinite(deleted)
            else math.nan
        )
        cooks.append(r_value * r_value * h / (p * complement))
    if rss > 0.0:
        log_likelihood = -0.5 * n * (math.log(2.0 * math.pi * rss / n) + 1.0)
        log_likelihood += 0.5 * math.fsum(math.log(value) for value in w)
    else:
        log_likelihood = math.inf
    aic, _, bic = information_criteria(log_likelihood, p + 1, n)
    return LinearModelResult(
        coefficients=beta,
        standard_errors=errors,
        t_values=tuple(t for t, _ in ratios),
        p_values=tuple(pv for _, pv in ratios),
        column_names=names,
        covariance=covariance,
        unscaled_covariance=gram_inverse,
        fitted_values=fitted,
        residuals=residuals,
        weights=w,
        design=rows,
        has_intercept=has_intercept,
        n_observations=n,
        n_parameters=p,
        df_residual=df,
        residual_sum_squares=rss,
        total_sum_squares=tss,
        residual_variance=sigma2,
        residual_standard_error=math.sqrt(sigma2),
        r_squared=r_squared,
        adjusted_r_squared=adjusted,
        f_statistic=f_statistic,
        f_df=(df_model, df),
        f_p_value=f_p,
        leverage=leverage,
        standardized_residuals=tuple(standardized),
        studentized_residuals=tuple(studentized),
        cooks_distance=tuple(cooks),
        log_likelihood=log_likelihood,
        aic=aic,
        bic=bic,
    )


def variance_inflation_factors(
    design: DesignMatrix | Iterable[Iterable[object]],
    *,
    column_names: Sequence[str] | None = None,
) -> dict[str, float]:
    """Return variance inflation factors ``VIF_j = 1 / (1 - R_j^2)``.

    ``R_j^2`` is the centered coefficient of determination from regressing
    column ``j`` on an intercept and every other non-constant column. A
    column exactly explained by the others receives ``inf``. Constant
    columns (the intercept) are skipped.

    Args:
        design: :class:`DesignMatrix` or raw rows.
        column_names: Names for a raw design.

    Returns:
        Mapping from non-constant column name to its VIF.

    Raises:
        ValueError: If there are fewer than two non-constant columns' worth of
            rows (``n <= number of predictors``) or no non-constant column.

    Equation:
        [EQ-LM-VIF-001].

    References:
        [REF-MONTGOMERY-PECK-VINING-2021, Chapter 9].

    """
    rows, names, _ = _coerce_design(design, column_names)
    n, p = len(rows), len(rows[0])
    predictors = [j for j in range(p) if any(row[j] != rows[0][j] for row in rows)]
    if not predictors:
        raise ValueError("design has no non-constant columns")
    if n <= len(predictors):
        raise ValueError("VIF needs more observations than predictors")
    result: dict[str, float] = {}
    for j in predictors:
        target = tuple(row[j] for row in rows)
        others = [k for k in predictors if k != j]
        regressors = tuple((1.0,) + tuple(row[k] for k in others) for row in rows)
        mean = math.fsum(target) / n
        tss = math.fsum((value - mean) ** 2 for value in target)
        factor = householder_qr(regressors)
        if not factor.full_rank:
            result[names[j]] = math.inf
            continue
        beta = factor.solve(target)
        rss = math.fsum(
            (value - math.fsum(b * x for b, x in zip(beta, row, strict=True))) ** 2
            for value, row in zip(target, regressors, strict=True)
        )
        r_squared = 1.0 - rss / tss
        threshold = DEFAULT_RANK_TOLERANCE**2
        result[names[j]] = (
            math.inf if 1.0 - r_squared <= threshold else 1.0 / (1.0 - r_squared)
        )
    return result
