"""Multiple linear regression by Householder QR: OLS, WLS, inference, diagnostics.

The model is ``y = X beta + e`` with independent errors of variance
``sigma^2 / w_i``. Weighted least squares is ordinary least squares on the
rows scaled by ``sqrt(w_i)``, so a single QR code path serves both. The normal
equations ``X'WX beta = X'Wy`` are never formed explicitly; ``(X'WX)^-1`` is
obtained as ``R^-1 R^-T`` from the triangular factor.

A design whose columns are numerically dependent raises
:class:`RankDeficientDesignError` naming the offending columns. No ridge or
pseudo-inverse is applied silently; explicit ridge penalties live in
:mod:`probstat.inference.regularization`.
"""

from __future__ import annotations

import math
from collections.abc import Iterable, Mapping, Sequence
from dataclasses import dataclass
from typing import Literal

from probstat.foundations.validation import require_finite_real
from probstat.linalg import (
    DEFAULT_RANK_TOLERANCE,
    HouseholderQR,
    Matrix,
    Vector,
    as_matrix,
    as_vector,
    householder_qr,
)

from .bayesian import student_t_quantile
from .fitting import information_criteria
from .sampling_distributions import f_sf, student_t_two_sided_p

RobustKind = Literal["HC0", "HC1", "HC2", "HC3"]
IntervalKind = Literal["confidence", "prediction"]


class RankDeficientDesignError(ValueError):
    """Raised when design columns are linearly dependent to working precision.

    References:
        [REF-GOLUB-VANLOAN-2013, Section 5.4],
        [REF-MONTGOMERY-PECK-VINING-2021, Chapter 9].

    """


