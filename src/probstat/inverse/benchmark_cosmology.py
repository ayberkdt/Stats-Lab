def bao_degeneracy_report(
    *,
    sn_redshifts: Sequence[float] | None = None,
    bao_redshifts: Sequence[float] = (0.15, 0.38, 0.51, 0.7, 0.85, 1.0, 1.2),
    hubble_redshifts: Sequence[float] = (0.3, 0.6, 0.9, 1.2),
    bins: int = 4,
    sigma_mu: float = 0.1,
    bao_relative_sd: float = 0.01,
    hubble_relative_sd: float = 0.03,
    omega_m: float = 0.3,
    h0: float = 70.0,
    rs: float = _DEFAULT_RS,
    panels: int = 4,
) -> BaoDegeneracyReport:
    """Measure which nuisance degeneracies BAO breaks and which it does not.

    For four synthetic samples (supernova distance moduli with a free
    magnitude offset, BAO ``D_V / r_s`` with a free ``r_s``, both, and both
    plus Hubble-rate data) the whitened Jacobian of the nuisance block is
    decomposed at the LCDM baseline [EQ-INV-APP-COSMO-004]. Expected and
    measured in the tests: SN alone leaves ``(log10 H0, M)`` collinear; BAO
    alone leaves ``(log10 H0, log10 r_s)`` collinear; SN plus BAO still leave
    one combination ``(H0, M, r_s)`` free (two combinations, three
    parameters); only a datum that fixes ``H0`` (the Hubble rate) breaks
    it. All numbers are SYNTHETIC and say nothing about the real universe.

    Args:
        sn_redshifts: Supernova redshifts (default 20 points in ``[0.05, 1.5]``).
        bao_redshifts: BAO redshifts.
        hubble_redshifts: Hubble-rate redshifts.
        bins: Number of uniform equation-of-state bins on ``[0, 1.5]``.
        sigma_mu: Supernova noise (mag).
        bao_relative_sd: BAO noise relative to the value.
        hubble_relative_sd: Hubble noise relative to the value.
        omega_m: Nominal matter density.
        h0: Nominal ``H0``.
        rs: Nominal sound horizon (Mpc).
        panels: Quadrature panels.

    Returns:
        :class:`BaoDegeneracyReport`.

    Raises:
        TypeError: If an argument has the wrong type.
        ValueError: If an argument is out of range.

    References:
        [EQ-INV-APP-COSMO-004], [REF-EISENSTEIN-2005].

    """
    n_bins = _positive_int(bins, "bins")
    edges = tuple(1.5 * j / n_bins for j in range(n_bins + 1))
    sn_z = (
        tuple(0.05 + 1.45 * i / 19 for i in range(20))
        if sn_redshifts is None
        else _real_sequence(sn_redshifts, "sn_redshifts")
    )
    common = {"omega_m": omega_m, "h0": h0, "panels": panels}
    sn = ExpansionHistoryModel(
        sn_z,
        "piecewise_constant",
        edges,
        nuisance=("omega_m", "log10_h0", "offset"),
        **common,  # type: ignore[arg-type]
    )
    bao = BaoDistanceModel(
        _real_sequence(bao_redshifts, "bao_redshifts"),
        "piecewise_constant",
        edges,
        rs=rs,
        nuisance=("omega_m", "log10_h0", "log10_rs"),
        **common,  # type: ignore[arg-type]
    )
    hub = ExpansionHistoryModel(
        _real_sequence(hubble_redshifts, "hubble_redshifts"),
        "piecewise_constant",
        edges,
        observable="hubble",
        nuisance=("omega_m", "log10_h0"),
        **common,  # type: ignore[arg-type]
    )
    sd_mu = _real_positive(sigma_mu, "sigma_mu")
    rel_bao = _real_positive(bao_relative_sd, "bao_relative_sd")
    rel_hub = _real_positive(hubble_relative_sd, "hubble_relative_sd")
    samples = (
        ("sn", (sn,)),
        ("bao", (bao,)),
        ("sn+bao", (sn, bao)),
        ("sn+bao+hubble", (sn, bao, hub)),
    )
    block = ("omega_m", "log10_h0", "offset", "log10_rs")
    spectra = []
    fixed = []
    for _, members in samples:
        joint = JointExpansionModel(members)
        x0 = nominal_expansion_point(
            joint.parameter_names, omega_m=omega_m, h0=h0, rs=rs
        )
        variances: list[float] = []
        for member in members:
            base = member.value(
                tuple(
                    x0[joint.parameter_names.index(n)] for n in member.parameter_names
                )
            )
            if isinstance(member, ExpansionHistoryModel) and (
                member.observable == "distance_modulus"
            ):
                variances.extend(sd_mu * sd_mu for _ in base)
            else:
                rel = rel_bao if isinstance(member, BaoDistanceModel) else rel_hub
                variances.extend((rel * v) ** 2 for v in base)
        noise = DiagonalCovariance(variances)
        present = tuple(n for n in block if n in joint.parameter_names)
        spectra.append(whitened_spectrum(joint, x0, noise, parameters=present))
        fixed.append(
            whitened_spectrum(
                joint,
                x0,
                noise,
                parameters=tuple(n for n in present if n != "omega_m"),
            )
        )
    return BaoDegeneracyReport(
        labels=tuple(label for label, _ in samples),
        spectra=tuple(spectra),
        omega_m_fixed_spectra=tuple(fixed),
    )


def linear_gaussian_eig(
    columns: Sequence[Sequence[float]], noise: Any, prior_sd: Sequence[float]
) -> float:
    """Return the linear-Gaussian expected information gain.

    ``EIG = 1/2 log det(I + P^(1/2) J' Gamma^-1 J P^(1/2))`` with ``P`` the
    diagonal prior covariance (``prior_sd``), ``J`` the Jacobian given by its
    columns and ``Gamma`` the noise covariance (a covariance factor, possibly
    correlated). It equals the expected Kullback-Leibler divergence from the
    prior to the posterior and, equivalently,
    ``1/2 [log det(P^-1 + J' Gamma^-1 J) - log det(P^-1)]``
    [EQ-INV-APP-COSMO-007]. The linearization point is the caller's choice; for
    a nonlinear model this is a LOCAL value.

    Args:
        columns: ``n`` Jacobian columns of length ``m``.
        noise: Covariance factor of dimension ``m``.
        prior_sd: ``n`` positive prior standard deviations.

    Returns:
        The EIG in nats (``0`` for an all-zero Jacobian).

    Raises:
        TypeError: If an argument has the wrong type.
        ValueError: If the dimensions do not match or a prior sd is not
            positive.

    References:
        [EQ-INV-APP-COSMO-007], [REF-CHALONER-VERDINELLI-1995].

    """
    cols = [_real_sequence(c, "columns") for c in columns]
    sds = _real_sequence(prior_sd, "prior_sd")
    if len(cols) != len(sds) or any(s <= 0.0 for s in sds):
        raise ValueError("prior_sd must be positive, one per column")
    if noise.dimension != len(cols[0]):
        raise ValueError("noise dimension must equal the column length")
    scaled = [
        tuple(s * v for v in noise.whiten(c)) for c, s in zip(cols, sds, strict=True)
    ]
    n = len(scaled)
    gram = [
        [
            math.fsum(a * b for a, b in zip(scaled[i], scaled[j], strict=True))
            + (1.0 if i == j else 0.0)
            for j in range(n)
        ]
        for i in range(n)
    ]
    return 0.5 * log_det_spd(_mat(gram))


@dataclass(frozen=True, slots=True)
class GreedyDesign:
    """Greedy choice of additional redshifts by expected information gain.

    Attributes:
        selected: The chosen candidate redshifts in order.
        marginal_gains: Dense EIG increase obtained by each choice.
        cumulative_eig: Dense EIG of ``base + selected[:k]`` for each ``k``.
        base_eig: Dense EIG of the base sample alone.
        first_step_gains: Dense EIG increase of every candidate (in the input
            order) when added to the base alone: information gain versus
            redshift.
        dense_eig: Dense EIG of the final design recomputed from scratch.
        telescoping_error: ``|base_eig + sum(marginal_gains) - dense_eig|``.
        rank_one_eig: EIG of the final design from the rank-one
            (Sherman-Morrison) recursion, an independent formula valid for
            independent noise; ``nan`` when the noise is correlated.
        rank_one_error: ``|rank_one_eig - dense_eig|`` (``nan`` if
            correlated).

    References:
        [EQ-INV-APP-COSMO-007], [EQ-INV-APP-COSMO-008].

    """

    selected: tuple[float, ...]
    marginal_gains: Vector
    cumulative_eig: Vector
    base_eig: float
    first_step_gains: Vector
    dense_eig: float
    telescoping_error: float
    rank_one_eig: float
    rank_one_error: float


def _rank_one_eig(
    rows: Sequence[Sequence[float]],
    variances: Sequence[float],
    prior_sd: Sequence[float],
) -> float:
    """Return the EIG of independent data by sequential rank-one updates.

    ``Delta_k = 1/2 log(1 + j' S j / s^2)`` with ``S`` the running posterior
    covariance, updated by Sherman-Morrison.

    References:
        [EQ-INV-APP-COSMO-008].

    """
    n = len(prior_sd)
    cov = [[prior_sd[i] ** 2 if i == j else 0.0 for j in range(n)] for i in range(n)]
    total = 0.0
    for row, var in zip(rows, variances, strict=True):
        v = [math.fsum(cov[i][k] * row[k] for k in range(n)) for i in range(n)]
        denom = var + math.fsum(row[i] * v[i] for i in range(n))
        total += 0.5 * math.log(denom / var)
        for i in range(n):
            for j in range(n):
                cov[i][j] -= v[i] * v[j] / denom
    return total


def greedy_redshift_design(
    base_redshifts: Sequence[float],
    candidates: Sequence[float],
    count: int,
    *,
    bin_edges: Sequence[float],
    calibration: CalibrationNoise,
    nuisance: Sequence[str] = (),
    prior_sd: Sequence[float] | None = None,
    x0: Sequence[float] | None = None,
    omega_m: float = 0.3,
    h0: float = 70.0,
    panels: int = 4,
) -> GreedyDesign:
    """Choose ``count`` candidate redshifts greedily by expected information gain.

    The Jacobian rows of the distance-modulus model at the baseline ``x0``
    (default LCDM) are computed once for the base and candidate redshifts; for
    every trial design the dense EIG
    :func:`linear_gaussian_eig` is evaluated with the covariance
    ``calibration.matrix`` of exactly the redshifts in the trial design, so a
    correlated calibration (a common offset or a smooth drift) changes which
    redshifts add information [EQ-INV-APP-COSMO-007]. The greedy rule adds the
    candidate with the largest dense EIG increase at each step
    [EQ-INV-APP-COSMO-008]. The result also carries the EIG recomputed from
    scratch for the final design (``telescoping_error`` must vanish to
    roundoff) and, when the noise is independent, the rank-one recursion as an
    independent check. LOCAL (linearized) and SYNTHETIC: the numbers are not
    forecasts for any survey.

    Args:
        base_redshifts: Existing redshifts (may be empty).
        candidates: Distinct candidate redshifts ``> 0`` (non-empty).
        count: Number of candidates to select (``1 <= count <= len(candidates)``).
        bin_edges: Edges of the equation-of-state bins.
        calibration: Noise model for all data (white, offset, smooth).
        nuisance: Nuisance names of the supernova model.
        prior_sd: Prior standard deviations of all parameters (default
            :func:`default_prior_sd`).
        x0: Linearization point (default the LCDM baseline).
        omega_m: Nominal matter density.
        h0: Nominal ``H0``.
        panels: Quadrature panels.

    Returns:
        :class:`GreedyDesign`.

    Raises:
        TypeError: If an argument has the wrong type.
        ValueError: If a redshift or count is invalid.

    References:
        [EQ-INV-APP-COSMO-007], [EQ-INV-APP-COSMO-008],
        [REF-CHALONER-VERDINELLI-1995].

    """
    if not isinstance(calibration, CalibrationNoise):
        raise TypeError("calibration must be a CalibrationNoise")
    if isinstance(base_redshifts, (str, bytes)) or not isinstance(
        base_redshifts, Sequence
    ):
        raise TypeError("base_redshifts must be a sequence of reals")
    base = tuple(_finite_real(v, "base_redshifts") for v in base_redshifts)
    cands = _real_sequence(candidates, "candidates")
    if len(set(cands)) != len(cands):
        raise ValueError("candidates must be distinct")
    picks = _positive_int(count, "count")
    if picks > len(cands):
        raise ValueError("count must not exceed the number of candidates")
    all_z = base + cands
    model = ExpansionHistoryModel(
        all_z,
        "piecewise_constant",
        bin_edges,
        omega_m=omega_m,
        h0=h0,
        panels=panels,
        nuisance=nuisance,
    )
    point = (
        nominal_expansion_point(model.parameter_names, omega_m=omega_m, h0=h0)
        if x0 is None
        else _real_sequence(x0, "x0")
    )
    sds = default_prior_sd(model.parameter_names) if prior_sd is None else prior_sd
    cols = jacobian_columns(model, point)
    n = len(cols)

    def dense(index: Sequence[int]) -> float:
        """Return the dense EIG of the rows in ``index``.

        References:
            [EQ-INV-APP-COSMO-007].

        """
        if not index:
            return 0.0
        sub = [tuple(c[i] for i in index) for c in cols]
        gamma = calibration.covariance([all_z[i] for i in index])
        return linear_gaussian_eig(sub, gamma, sds)

    chosen: list[int] = []
    base_idx = list(range(len(base)))
    base_eig = dense(base_idx)
    first = tuple(
        dense([*base_idx, len(base) + j]) - base_eig for j in range(len(cands))
    )
    current = base_eig
    gains: list[float] = []
    cumulative: list[float] = []
    remaining = list(range(len(cands)))
    for _ in range(picks):
        held = [*base_idx, *(len(base) + c for c in chosen)]
        scores = {j: dense([*held, len(base) + j]) for j in remaining}
        best = max(remaining, key=lambda j: scores[j])
        gains.append(scores[best] - current)
        current = scores[best]
        cumulative.append(current)
        chosen.append(best)
        remaining.remove(best)
    final_idx = [*base_idx, *(len(base) + c for c in chosen)]
    final = dense(final_idx)
    independent = calibration.offset_sd == 0.0 and calibration.smooth_sd == 0.0
    if independent:
        rows = [[cols[j][i] for j in range(n)] for i in final_idx]
        rank_one = _rank_one_eig(rows, [calibration.white_sd**2] * len(rows), sds)
        rank_one_error = abs(rank_one - final)
    else:
        rank_one = rank_one_error = math.nan
    return GreedyDesign(
        selected=tuple(cands[j] for j in chosen),
        marginal_gains=tuple(gains),
        cumulative_eig=tuple(cumulative),
        base_eig=base_eig,
        first_step_gains=first,
        dense_eig=final,
        telescoping_error=abs(base_eig + math.fsum(gains) - final),
        rank_one_eig=rank_one,
        rank_one_error=rank_one_error,
    )


@dataclass(frozen=True, slots=True)
class IntervalCalibration:
    """Nominal versus actual linear-Gaussian posterior spread.

    Attributes:
        parameters: Parameter names.
        nominal_sd: Posterior standard deviations the ``assumed`` noise
            reports, ``sqrt(diag(P^-1 + J' G_a^-1 J)^-1)``.
        actual_sd: Root-mean-square estimator error when the TRUE noise acts
            and the truth is a prior draw,
            ``sqrt(diag((I - K J) P (I - K J)' + K G_t K'))`` with
            ``K = (P^-1 + J' G_a^-1 J)^-1 J' G_a^-1``.
        ratio: ``actual_sd / nominal_sd``; ``> 1`` means the nominal intervals
            are too narrow.

    References:
        [EQ-INV-APP-COSMO-009].

    """

    parameters: tuple[str, ...]
    nominal_sd: Vector
    actual_sd: Vector
    ratio: Vector


def interval_calibration(
    model: Any,
    x: Sequence[float],
    true_noise: Any,
    assumed_noise: Any,
    prior_sd: Sequence[float],
) -> IntervalCalibration:
    """Compare the spread an assumed noise model reports with the true spread.

    The estimator is the linearized MAP with the ASSUMED noise (for example
    the diagonal surrogate that ignores the correlation). When the truth is a
    draw of the prior ``N(0, P)`` and the data errors have the TRUE
    covariance, its mean-square error matrix is
    ``(I - K J) P (I - K J)' + K G_t K'`` with
    ``K = (P^-1 + J' G_a^-1 J)^-1 J' G_a^-1``; for ``G_t = G_a`` it equals the
    nominal posterior covariance. The ratio ``actual / nominal`` is the factor
    by which nominal intervals are too narrow (``> 1``) or too wide
    [EQ-INV-APP-COSMO-009]. Local and SYNTHETIC.

    Args:
        model: Differentiable model with ``parameter_names``.
        x: Linearization point.
        true_noise: True covariance factor (dimension ``m``).
        assumed_noise: Assumed covariance factor (dimension ``m``).
        prior_sd: Positive prior standard deviations (one per parameter).

    Returns:
        :class:`IntervalCalibration`.

    Raises:
        TypeError: If an argument has the wrong type.
        ValueError: If dimensions or standard deviations are invalid.

    References:
        [EQ-INV-APP-COSMO-009].

    """
    cols = jacobian_columns(model, x)
    n, m = len(cols), len(cols[0])
    sds = _real_sequence(prior_sd, "prior_sd")
    if len(sds) != n or any(s <= 0.0 for s in sds):
        raise ValueError("prior_sd must be positive, one per parameter")
    if true_noise.dimension != m or assumed_noise.dimension != m:
        raise ValueError("noise dimensions must equal the number of observations")
    ga = [assumed_noise.solve(c) for c in cols]
    info = [
        [
            math.fsum(cols[a][i] * ga[b][i] for i in range(m))
            + (1.0 / sds[a] ** 2 if a == b else 0.0)
            for b in range(n)
        ]
        for a in range(n)
    ]
    cov = inverse_spd(_mat(info))
    a_mat = matmul(cov, _mat(ga))
    gt_at = [true_noise.apply(row) for row in a_mat]
    jac = tuple(tuple(cols[j][i] for j in range(n)) for i in range(m))
    kj = matmul(a_mat, jac)
    actual = [
        math.fsum(
            (((1.0 if i == k else 0.0) - kj[i][k]) * sds[k]) ** 2 for k in range(n)
        )
        + math.fsum(a_mat[i][k] * gt_at[i][k] for k in range(m))
        for i in range(n)
    ]
    nominal = tuple(math.sqrt(cov[i][i]) for i in range(n))
    actual_sd = tuple(math.sqrt(v) for v in actual)
    return IntervalCalibration(
        parameters=tuple(model.parameter_names),
        nominal_sd=nominal,
        actual_sd=actual_sd,
        ratio=tuple(a / b for a, b in zip(actual_sd, nominal, strict=True)),
    )
