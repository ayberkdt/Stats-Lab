def correlated_calibration_benchmark(
    calibration: CalibrationNoise,
    *,
    truth: str = "lcdm",
    nuisance: Sequence[str] = (),
    seed: int = 11,
    **design: object,
) -> CorrelatedExpansionBenchmark:
    """Return A02c: A02 data with correlated calibration noise (SYNTHETIC).

    The noise-free data, the model, the truth and the prior are those of
    :func:`synthetic_expansion_history_benchmark` (every keyword of its design
    is forwarded through ``design``: ``redshifts``, ``bins``, ``omega_m``,
    ``h0``, ``offset``, ``count``, ``z_max``, ``panels``, ``prior_sd``); only
    the noise differs: ``e = F z`` with ``F F' = Gamma`` of ``calibration``
    and ``z ~ N(0, I)`` from the stream ``A02c/noise``
    [EQ-INV-APP-COSMO-002]. Pass ``noise`` of the result to a solver for the
    correct generalized least squares and ``naive_noise`` to see the effect of
    ignoring the correlation. A common-offset noise component is exactly
    confounded with the ``"offset"`` nuisance when that is free. No survey,
    covariance or real-universe claim is made.

    Args:
        calibration: The correlated noise specification.
        truth: ``"lcdm"``, ``"cpl"`` or ``"oscillating"``.
        nuisance: Nuisance names of the model.
        seed: Root seed (only the noise is random).
        **design: Further keywords of the A02 benchmark (not ``sigma_mu`` or
            ``relative_noise``).

    Returns:
        :class:`CorrelatedExpansionBenchmark`.

    Raises:
        TypeError: If an argument has the wrong type.
        ValueError: If ``design`` contains a noise option or any value is
            invalid.

    References:
        [EQ-INV-APP-COSMO-002], [REF-HOGG-1999].

    """
    if not isinstance(calibration, CalibrationNoise):
        raise TypeError("calibration must be a CalibrationNoise")
    if "sigma_mu" in design or "relative_noise" in design:
        raise ValueError("the noise comes from calibration, not sigma_mu")
    base = synthetic_expansion_history_benchmark(
        truth=truth,
        nuisance=nuisance,
        sigma_mu=calibration.white_sd,
        seed=seed,
        **design,  # type: ignore[arg-type]
    )
    model = base.model
    if (
        not isinstance(model, ExpansionHistoryModel)
        or base.prior_mean is None
        or base.prior_covariance is None
    ):
        raise ValueError("the A02 benchmark did not return its model and prior")
    zs = model.redshifts
    gamma = calibration.covariance(zs)
    gen = resolve_stream(seed).child("A02c").child("noise").generator()
    draws = [gen.gauss(0.0, 1.0) for _ in zs]
    error = gamma.unwhiten(draws)
    matrix = calibration.matrix(zs)
    return CorrelatedExpansionBenchmark(
        identifier="A02c",
        name=f"{base.name}, correlated calibration noise",
        model=model,
        data=tuple(b + e for b, e in zip(base.exact_data, error, strict=True)),
        noise=gamma,
        naive_noise=DiagonalCovariance([matrix[i][i] for i in range(len(zs))]),
        calibration=calibration,
        realized_error_norm=math.hypot(*error),
        truth=base.truth,
        exact_data=base.exact_data,
        same_discretization=base.same_discretization,
        prior_mean=base.prior_mean,
        prior_covariance=base.prior_covariance,
        pathologies=(*base.pathologies, "correlated_noise"),
        seeds=MappingProxyType({"noise": "A02c/noise"}),
    )


class BaoDistanceModel:
    """Simplified BAO observable ``D_V(z) / r_s`` with ``r_s`` a nuisance.

    The angle-averaged distance of a flat model is
    ``D_V(z) = [ z D_M(z)^2 (c / H(z)) ]^(1/3)`` with the transverse comoving
    distance ``D_M = D_C``; the observable is the dimensionless ratio
    ``y = D_V / r_s`` [EQ-INV-APP-COSMO-003]. SIMPLIFICATIONS, all declared:
    the sound horizon ``r_s`` is NOT computed from physics (no baryon density,
    no radiation, no drag epoch) but treated as a free parameter
    ``log10 r_s`` (Mpc, nominal ``147``), so the model is a toy for the
    degeneracy structure only; there is no reconstruction, no anisotropic
    ``D_M / r_s`` and ``D_H / r_s`` split, no survey covariance, and no
    statement about the real universe. Because ``y`` depends on ``H0`` and
    ``r_s`` only through ``H0 r_s``, ``log10 H0`` and ``log10 r_s`` have
    EXACTLY collinear Jacobian columns [EQ-INV-APP-COSMO-004].

    The model composes two :class:`ExpansionHistoryModel` instances (the
    distance modulus gives ``D_M``, the Hubble rate gives ``H``), so its
    derivatives are the exact derivatives of the same discrete quadrature.
    Unknowns: ``x1..xK`` followed by the requested subset of
    ``omega_m``, ``log10_h0``, ``log10_rs`` (in this order).

    References:
        [EQ-INV-APP-COSMO-003], [EQ-INV-APP-COSMO-004], [REF-EISENSTEIN-2005],
        [REF-HOGG-1999].

    """

    __slots__ = ("_h", "_mu", "_nuisance", "_rs", "_slot_rs", "_z")

    def __init__(
        self,
        redshifts: Sequence[float],
        basis: str = "piecewise_constant",
        bin_edges: Sequence[float] | None = None,
        *,
        omega_m: float = 0.3,
        h0: float = 70.0,
        rs: float = _DEFAULT_RS,
        panels: int = 4,
        nuisance: Sequence[str] = (),
    ) -> None:
        """Validate the design and build the two inner models.

        Args:
            redshifts: Observation redshifts ``> 0``.
            basis: Only ``"piecewise_constant"``.
            bin_edges: Strictly increasing edges from ``0``.
            omega_m: Nominal matter density in ``(0, 1)``.
            h0: Nominal ``H0`` (km/s/Mpc).
            rs: Nominal sound horizon ``> 0`` (Mpc).
            panels: Gauss-Legendre panels per smooth segment.
            nuisance: Subset of ``("omega_m", "log10_h0", "log10_rs")``.

        Raises:
            TypeError: If an argument has the wrong type.
            ValueError: If a value is out of range or a nuisance name is
                unknown or duplicated.

        References:
            [EQ-INV-APP-COSMO-003].

        """
        if isinstance(nuisance, (str, bytes)) or not isinstance(nuisance, Sequence):
            raise TypeError("nuisance must be a sequence of names")
        names = tuple(nuisance)
        if len(set(names)) != len(names) or any(n not in _BAO_NUISANCE for n in names):
            raise ValueError(
                "nuisance must be distinct names from 'omega_m', 'log10_h0', 'log10_rs'"
            )
        self._nuisance = tuple(n for n in _BAO_NUISANCE if n in names)
        inner = tuple(n for n in self._nuisance if n != "log10_rs")
        self._mu = ExpansionHistoryModel(
            redshifts,
            basis,
            bin_edges,
            omega_m=omega_m,
            h0=h0,
            panels=panels,
            nuisance=inner,
        )
        self._h = ExpansionHistoryModel(
            redshifts,
            basis,
            bin_edges,
            omega_m=omega_m,
            h0=h0,
            observable="hubble",
            panels=panels,
            nuisance=inner,
        )
        self._rs = _real_positive(rs, "rs")
        self._slot_rs = (
            self._mu.input_dimension if "log10_rs" in self._nuisance else None
        )
        self._z = self._mu.redshifts

    @property
    def input_dimension(self) -> int:
        """Return ``n = K + len(nuisance)``.

        References:
            [EQ-INV-APP-COSMO-003].

        """
        return self._mu.input_dimension + (1 if self._slot_rs is not None else 0)

    @property
    def output_dimension(self) -> int:
        """Return the number of redshifts.

        References:
            [EQ-INV-APP-COSMO-003].

        """
        return len(self._z)

    @property
    def redshifts(self) -> tuple[float, ...]:
        """Return the observation redshifts.

        References:
            [EQ-INV-APP-COSMO-003].

        """
        return self._z

    @property
    def parameter_names(self) -> tuple[str, ...]:
        """Return ``x1..xK`` followed by the nuisance names.

        References:
            [EQ-INV-APP-COSMO-003].

        """
        k = len(self._mu.bin_edges) - 1
        return tuple(f"x{j + 1}" for j in range(k)) + self._nuisance

    def _split(self, x: Sequence[float]) -> tuple[Vector, float]:
        """Return the inner parameter vector and the sound horizon ``r_s``.

        References:
            [EQ-INV-APP-COSMO-003].

        """
        if isinstance(x, (str, bytes)) or not isinstance(x, Sequence):
            raise TypeError("x must be a sequence of reals")
        if len(x) != self.input_dimension:
            raise ValueError(f"x must have length {self.input_dimension}")
        point = tuple(x[: self._mu.input_dimension])
        if self._slot_rs is None:
            return point, self._rs
        return point, 10.0 ** _finite_real(x[self._slot_rs], "x")

    def value(self, x: Sequence[float]) -> Vector:
        """Return ``D_V(z_i) / r_s`` (an all-``nan`` vector on a failed point).

        Args:
            x: Parameters (length ``n``).

        Returns:
            The dimensionless ratios.

        Raises:
            TypeError: If ``x`` is not a sequence of reals.
            ValueError: If ``x`` has the wrong length.

        References:
            [EQ-INV-APP-COSMO-003].

        """
        point, rs = self._split(x)
        mu = self._mu.value(point)
        hub = self._h.value(point)
        out = []
        for z, m, h in zip(self._z, mu, hub, strict=True):
            d_m = 10.0 ** ((m - 25.0) / 5.0) / (1.0 + z)
            out.append((z * d_m * d_m * _C_KM_S / h) ** (1.0 / 3.0) / rs)
        return tuple(out)

    def volume_distance(self, x: Sequence[float]) -> Vector:
        """Return ``D_V(z_i)`` in Mpc (``r_s`` times the observable).

        Args:
            x: Parameters (length ``n``).

        Returns:
            The volume-averaged distances.

        Raises:
            TypeError: If ``x`` is not a sequence of reals.
            ValueError: If ``x`` has the wrong length.

        References:
            [EQ-INV-APP-COSMO-003].

        """
        rs = self._split(x)[1]
        return tuple(v * rs for v in self.value(x))

    def jvp(self, x: Sequence[float], v: Sequence[float]) -> Vector:
        """Return the exact derivative of ``value`` along ``v``.

        ``d y = y [ (2 ln10 / 15) d mu - (1/3) dH / H - ln10 d log10 r_s ]``.

        Args:
            x: Base point.
            v: Direction (length ``n``).

        Returns:
            ``J(x) v``.

        Raises:
            TypeError: If an argument is not a sequence of reals.
            ValueError: On a wrong length or an invalid base point.

        References:
            [EQ-INV-APP-COSMO-004].

        """
        point, _ = self._split(x)
        if len(v) != self.input_dimension:
            raise ValueError(f"v must have length {self.input_dimension}")
        direction = self._mu._check_x(v[: self._mu.input_dimension])
        d_rs = 0.0 if self._slot_rs is None else _finite_real(v[self._slot_rs], "v")
        y = self.value(x)
        d_mu = self._mu.jvp(point, direction)
        d_h = self._h.jvp(point, direction)
        hub = self._h.value(point)
        return tuple(
            yi * (2.0 * _LN10 / 15.0 * a - b / (3.0 * h) - _LN10 * d_rs)
            for yi, a, b, h in zip(y, d_mu, d_h, hub, strict=True)
        )

    def vjp(self, x: Sequence[float], w: Sequence[float]) -> Vector:
        """Return the exact adjoint action ``J(x)' w``.

        Args:
            x: Base point.
            w: Weights (length ``m``).

        Returns:
            ``J(x)' w``.

        Raises:
            TypeError: If an argument is not a sequence of reals.
            ValueError: On a wrong length or an invalid base point.

        References:
            [EQ-INV-APP-COSMO-004].

        """
        point, _ = self._split(x)
        weights = [_finite_real(a, "w") for a in w]
        if len(weights) != self.output_dimension:
            raise ValueError(f"w must have length {self.output_dimension}")
        y = self.value(x)
        hub = self._h.value(point)
        u = [yi * wi for yi, wi in zip(y, weights, strict=True)]
        g_mu = self._mu.vjp(point, [2.0 * _LN10 / 15.0 * a for a in u])
        g_h = self._h.vjp(point, [-a / (3.0 * h) for a, h in zip(u, hub, strict=True)])
        grad = [a + b for a, b in zip(g_mu, g_h, strict=True)]
        if self._slot_rs is not None:
            grad.append(-_LN10 * math.fsum(u))
        return tuple(grad)


class JointExpansionModel:
    """Several expansion-history observables sharing one parameter vector.

    The unknowns are the shared bins ``x1..xK`` and the UNION of the member
    models' nuisance names in the fixed order ``omega_m``, ``log10_h0``,
    ``offset``, ``log10_rs``. Observations are concatenated in member order.
    A member that lacks a nuisance of the union uses its own nominal value
    for it (the caller keeps the nominal values consistent) and has a zero
    Jacobian column there [EQ-INV-APP-COSMO-005]. The point of the class is to
    show degeneracies that one observable has and another breaks.

    References:
        [EQ-INV-APP-COSMO-005].

    """

    __slots__ = ("_maps", "_models", "_names", "_nbins")

    def __init__(self, models: Sequence[Any]) -> None:
        """Validate the members and build the index maps.

        Args:
            models: Objects with ``parameter_names``, ``value``, ``jvp``,
                ``vjp`` and ``output_dimension`` (the cosmology models of this
                module), at least one, sharing the same bin names.

        Raises:
            TypeError: If ``models`` is not a sequence.
            ValueError: If it is empty, the bins differ or a nuisance name is
                unknown.

        References:
            [EQ-INV-APP-COSMO-005].

        """
        if isinstance(models, (str, bytes)) or not isinstance(models, Sequence):
            raise TypeError("models must be a sequence of models")
        members = tuple(models)
        if not members:
            raise ValueError("at least one model is required")
        bins = [n for n in members[0].parameter_names if n.startswith("x")]
        union: set[str] = set()
        for model in members:
            names = tuple(model.parameter_names)
            if [n for n in names if n.startswith("x")] != bins:
                raise ValueError("all models must share the same bin parameters")
            extra = {n for n in names if not n.startswith("x")}
            if not extra <= set(_JOINT_ORDER):
                raise ValueError("unknown nuisance name in a member model")
            union |= extra
        nuisance = tuple(n for n in _JOINT_ORDER if n in union)
        self._names = tuple(bins) + nuisance
        self._nbins = len(bins)
        self._models = members
        index = {n: i for i, n in enumerate(self._names)}
        self._maps = tuple(
            tuple(index[n] for n in model.parameter_names) for model in members
        )

    @property
    def input_dimension(self) -> int:
        """Return the number of shared parameters.

        References:
            [EQ-INV-APP-COSMO-005].

        """
        return len(self._names)

    @property
    def output_dimension(self) -> int:
        """Return the total number of observations.

        References:
            [EQ-INV-APP-COSMO-005].

        """
        return sum(int(m.output_dimension) for m in self._models)

    @property
    def parameter_names(self) -> tuple[str, ...]:
        """Return the shared parameter names.

        References:
            [EQ-INV-APP-COSMO-005].

        """
        return self._names

    def _sub(self, vector: Sequence[float], member: int) -> Vector:
        """Return the member's coordinates of a joint vector.

        References:
            [EQ-INV-APP-COSMO-005].

        """
        if len(vector) != len(self._names):
            raise ValueError(f"vector must have length {len(self._names)}")
        return tuple(float(vector[i]) for i in self._maps[member])

    def value(self, x: Sequence[float]) -> Vector:
        """Return the concatenated observables.

        Args:
            x: Joint parameters.

        Returns:
            The member values in order.

        Raises:
            ValueError: On a wrong length.

        References:
            [EQ-INV-APP-COSMO-005].

        """
        out: list[float] = []
        for k, model in enumerate(self._models):
            out.extend(model.value(self._sub(x, k)))
        return tuple(out)

    def jvp(self, x: Sequence[float], v: Sequence[float]) -> Vector:
        """Return the concatenated Jacobian actions.

        Args:
            x: Joint base point.
            v: Joint direction.

        Returns:
            ``J(x) v``.

        Raises:
            ValueError: On a wrong length or an invalid base point.

        References:
            [EQ-INV-APP-COSMO-005].

        """
        out: list[float] = []
        for k, model in enumerate(self._models):
            out.extend(model.jvp(self._sub(x, k), self._sub(v, k)))
        return tuple(out)

    def vjp(self, x: Sequence[float], w: Sequence[float]) -> Vector:
        """Return the summed adjoint actions.

        Args:
            x: Joint base point.
            w: Weights of the concatenated observations.

        Returns:
            ``J(x)' w``.

        Raises:
            ValueError: On a wrong length or an invalid base point.

        References:
            [EQ-INV-APP-COSMO-005].

        """
        if len(w) != self.output_dimension:
            raise ValueError(f"w must have length {self.output_dimension}")
        grad = [0.0] * len(self._names)
        start = 0
        for k, model in enumerate(self._models):
            stop = start + int(model.output_dimension)
            part = model.vjp(self._sub(x, k), tuple(w[start:stop]))
            for slot, g in zip(self._maps[k], part, strict=True):
                grad[slot] += g
            start = stop
        return tuple(grad)


def nominal_expansion_point(
    parameter_names: Sequence[str],
    *,
    omega_m: float = 0.3,
    h0: float = 70.0,
    rs: float = _DEFAULT_RS,
) -> Vector:
    """Return the LCDM base point of a parameter-name list.

    Bins are ``0`` (``w = -1``), ``omega_m`` is the given value, ``log10_h0``
    and ``log10_rs`` are the logarithms of the nominal values and the offset
    is ``0``.

    Args:
        parameter_names: Names as in the models' ``parameter_names``.
        omega_m: Nominal matter density.
        h0: Nominal ``H0``.
        rs: Nominal sound horizon (Mpc).

    Returns:
        The point.

    Raises:
        ValueError: If a name is unknown or a nominal value is not positive.

    References:
        [EQ-INV-APP-COSMO-005].

    """
    values = {
        "omega_m": _real_positive(omega_m, "omega_m"),
        "log10_h0": math.log10(_real_positive(h0, "h0")),
        "offset": 0.0,
        "log10_rs": math.log10(_real_positive(rs, "rs")),
    }
    out = []
    for name in parameter_names:
        if name.startswith("x"):
            out.append(0.0)
        elif name in values:
            out.append(values[name])
        else:
            raise ValueError(f"unknown parameter name {name!r}")
    return tuple(out)


def default_prior_sd(parameter_names: Sequence[str], *, bin_sd: float = 0.5) -> Vector:
    """Return the prior standard deviations used by the A02 benchmark.

    Bins get ``bin_sd``; nuisance parameters ``0.05`` (``omega_m``,
    ``log10_h0``, ``log10_rs``) and ``0.5`` (``offset``) as declared in
    :func:`synthetic_expansion_history_benchmark`.

    Args:
        parameter_names: Names of the parameters.
        bin_sd: Standard deviation of the bin values (``> 0``).

    Returns:
        One standard deviation per name.

    Raises:
        ValueError: If a name is unknown or ``bin_sd`` is not positive.

    References:
        [EQ-INV-COSMO-008].

    """
    sd = _real_positive(bin_sd, "bin_sd")
    out = []
    for name in parameter_names:
        if name.startswith("x"):
            out.append(sd)
        elif name in _PRIOR_NUISANCE_SD:
            out.append(_PRIOR_NUISANCE_SD[name])
        else:
            raise ValueError(f"unknown parameter name {name!r}")
    return tuple(out)


def jacobian_columns(model: Any, x: Sequence[float]) -> list[Vector]:
    """Return the Jacobian of a differentiable model as ``n`` columns.

    Args:
        model: Object with ``input_dimension`` and ``jvp``.
        x: Base point.

    Returns:
        Columns ``J e_j`` assembled from unit-vector ``jvp`` calls.

    Raises:
        ValueError: If ``x`` is invalid for the model.

    References:
        [EQ-INV-COSMO-005].

    """
    n = int(model.input_dimension)
    return [
        model.jvp(x, tuple(1.0 if k == j else 0.0 for k in range(n))) for j in range(n)
    ]


@dataclass(frozen=True, slots=True)
class WhitenedSpectrum:
    """Singular spectrum of a noise-whitened Jacobian block.

    Attributes:
        parameters: Names of the columns used.
        singular_values: Descending singular values of ``W J`` restricted to
            those columns (zero rows appended when ``m < n``).
        condition_number: ``s_1 / s_n`` (``inf`` when ``s_n = 0``).
        numerical_rank: Count above ``rank_tolerance * s_1``.
        rank_tolerance: The relative threshold.
        weakest_direction: Unit right singular vector of the smallest singular
            value (a null direction when the rank is deficient).

    References:
        [EQ-INV-APP-COSMO-006].

    """

    parameters: tuple[str, ...]
    singular_values: Vector
    condition_number: float
    numerical_rank: int
    rank_tolerance: float
    weakest_direction: Vector


def whitened_spectrum(
    model: Any,
    x: Sequence[float],
    noise: Any,
    *,
    parameters: Sequence[str] | None = None,
    rank_tolerance: float = 1e-8,
) -> WhitenedSpectrum:
    """Return the whitened singular spectrum of (a block of) the Jacobian.

    ``W J_S`` for the columns ``S`` named in ``parameters`` (default all), with
    ``W' W = Gamma^-1`` from the covariance factor ``noise``, so the correlated
    noise enters through its factor and not through a diagonal surrogate
    [EQ-INV-APP-COSMO-006]. Fixing the other parameters at ``x`` is what a
    restriction to ``S`` means.

    Args:
        model: Differentiable model with ``parameter_names``.
        x: Base point.
        noise: Covariance factor of dimension ``m`` (``whiten`` method).
        parameters: Subset of ``model.parameter_names``.
        rank_tolerance: Relative singular-value threshold (``> 0``).

    Returns:
        :class:`WhitenedSpectrum`.

    Raises:
        TypeError: If an argument has the wrong type.
        ValueError: If a name is unknown or the dimensions do not match.

    References:
        [EQ-INV-APP-COSMO-006].

    """
    tol = _real_positive(rank_tolerance, "rank_tolerance")
    names = tuple(model.parameter_names)
    chosen = names if parameters is None else tuple(parameters)
    if not chosen or any(n not in names for n in chosen):
        raise ValueError("parameters must be a non-empty subset of the model's names")
    cols = jacobian_columns(model, x)
    if noise.dimension != model.output_dimension:
        raise ValueError("noise dimension must equal the number of observations")
    use = [noise.whiten(cols[names.index(n)]) for n in chosen]
    n, m = len(use), len(use[0])
    rows = [[use[j][i] for j in range(n)] for i in range(m)]
    rows.extend([0.0] * n for _ in range(max(0, n - m)))
    svd = singular_value_decomposition(_mat(rows))
    sv = svd.singular_values
    return WhitenedSpectrum(
        parameters=chosen,
        singular_values=tuple(sv),
        condition_number=sv[0] / sv[-1] if sv[-1] > 0.0 else math.inf,
        numerical_rank=sum(1 for v in sv if v > tol * sv[0]),
        rank_tolerance=tol,
        weakest_direction=tuple(svd.v[i][n - 1] for i in range(n)),
    )


