@dataclass(frozen=True, slots=True)
class CalibrationNoise:
    """Correlated calibration noise of a distance-modulus sample (SYNTHETIC).

    The covariance of the data errors at redshifts ``z_i`` is

    ``Gamma = s_w^2 I + s_o^2 1 1' + s_s^2 K`` with
    ``K_ij = exp(-(z_i - z_j)^2 / (2 l^2))``,

    a white part, a COMMON OFFSET shared by every datum (a magnitude
    zero-point error) and a SMOOTH component correlated across redshift
    (a slowly varying calibration drift) [EQ-INV-APP-COSMO-001]. With
    ``white_sd > 0`` the matrix is symmetric positive definite and is handled
    through its Cholesky covariance factor. Nothing here is a real survey
    covariance.

    Attributes:
        white_sd: ``s_w > 0`` (magnitudes).
        offset_sd: ``s_o >= 0``, the common-offset standard deviation.
        smooth_sd: ``s_s >= 0``, the smooth-component standard deviation.
        length_scale: ``l > 0``, the redshift correlation length of the smooth
            component.

    References:
        [EQ-INV-APP-COSMO-001].

    """

    white_sd: float
    offset_sd: float = 0.0
    smooth_sd: float = 0.0
    length_scale: float = 0.5

    def __post_init__(self) -> None:
        """Validate the four scales.

        Raises:
            TypeError: If a value is not a real number.
            ValueError: If ``white_sd`` or ``length_scale`` is not positive or
                a standard deviation is negative.

        References:
            [EQ-INV-APP-COSMO-001].

        """
        _real_positive(self.white_sd, "white_sd")
        _nonneg(self.offset_sd, "offset_sd")
        _nonneg(self.smooth_sd, "smooth_sd")
        _real_positive(self.length_scale, "length_scale")

    def matrix(self, redshifts: Sequence[float]) -> list[list[float]]:
        """Return the dense covariance matrix at the given redshifts.

        Args:
            redshifts: Finite redshifts (non-empty).

        Returns:
            The ``m x m`` matrix ``Gamma``.

        Raises:
            TypeError: If ``redshifts`` is not a real sequence.
            ValueError: If it is empty.

        References:
            [EQ-INV-APP-COSMO-001].

        """
        zs = _real_sequence(redshifts, "redshifts")
        two_l2 = 2.0 * self.length_scale**2
        out = [
            [
                self.offset_sd**2
                + self.smooth_sd**2 * math.exp(-((a - b) ** 2) / two_l2)
                for b in zs
            ]
            for a in zs
        ]
        for i in range(len(zs)):
            out[i][i] += self.white_sd**2
        return out

    def covariance(self, redshifts: Sequence[float]) -> DenseCovariance:
        """Return the covariance as a factorized ``DenseCovariance``.

        Args:
            redshifts: Finite redshifts (non-empty).

        Returns:
            The covariance factor used by the solvers.

        Raises:
            TypeError: If ``redshifts`` is not a real sequence.
            ValueError: If it is empty.

        References:
            [EQ-INV-APP-COSMO-001].

        """
        return DenseCovariance(self.matrix(redshifts))


