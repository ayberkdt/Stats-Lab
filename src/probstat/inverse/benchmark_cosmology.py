"""Synthetic dark-energy expansion-history inversion benchmark (A02).

Experimental (added in 0.28).

This module is a SYNTHETIC TEST BED for inverse-problem methods. It makes no
statement about the real universe: every redshift, covariance and datum it
produces is generated locally from a stated model and seed, and nothing here
may be read as a constraint on dark energy.

Physical model. A spatially flat FLRW background with pressureless matter and
one dark-energy component of equation of state ``w(z)``; radiation is NEGLECTED
(low-redshift regime, ``z <~ 2``; no high-redshift or CMB physics is claimed)
[EQ-INV-COSMO-001]::

    E^2(z) = Om (1 + z)^3 + (1 - Om) X(z),
    X(z)   = exp(3 int_0^z (1 + w(t)) / (1 + t) dt).

With ``w(z) = -1 + sum_j x_j phi_j(z)`` and piecewise-constant ``phi_j`` (the
indicator of the redshift bin ``[e_j, e_{j+1})``) the exponent integral is
exact per bin, ``3 x_j ln((1 + b) / (1 + a))`` [EQ-INV-COSMO-002]. Observables
are the distance modulus ``mu = 5 log10(D_L / Mpc) + 25`` with
``D_L = (1 + z) (c / H0) int_0^z dt / E(t)`` (a fixed 5-point Gauss-Legendre
composite rule whose panels are aligned with the bin edges, so the discrete
model is differentiated exactly) [EQ-INV-COSMO-003], or the Hubble rate
``H(z) = H0 E(z)`` [EQ-INV-COSMO-009]. The nuisance parameters ``Om``,
``log10 H0`` and an additive magnitude offset ``M`` may be appended to the
unknowns; an uncalibrated supernova sample cannot separate ``log10 H0`` from
``M`` (exactly collinear Jacobian columns) [EQ-INV-COSMO-007].

Two exact checks anchor the implementation: for constant ``w`` the factor is
``X(z) = (1 + z)^(3 (1 + w))``, and at low redshift ``D_L ~ c z / H0``
[EQ-INV-COSMO-006].

Classes and functions:

- :class:`ExpansionHistoryModel`: the differentiable forward map
  (``DifferentiableForward``) with analytic ``jvp``/``vjp``
  [EQ-INV-COSMO-004, EQ-INV-COSMO-005];
- :func:`synthetic_expansion_history_benchmark`: catalog case A02 with data
  from a FINER, independent representation of the truth (closed forms are used
  only in the tests as independent oracles) [EQ-INV-COSMO-008].

The coarse-bin truth ``x`` is the projection that preserves the exponent
integral of each bin. Data of the ``cpl`` and ``oscillating`` truths come from
a different quadrature on a 300-panel grid, so they are NOT generated by the
inverted model (``same_discretization=False``).

References:
    [REF-HOGG-1999], [REF-CHEVALLIER-POLARSKI-2001], [REF-LINDER-2003],
    [REF-STUART-2010], [REF-HANSEN-2008].

"""

