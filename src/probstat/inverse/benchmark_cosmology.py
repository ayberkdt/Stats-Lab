def _gauss_legendre_5() -> tuple[tuple[float, ...], tuple[float, ...]]:
    """Return the 5-point Gauss-Legendre nodes and weights on ``[-1, 1]``.

    The closed forms ``(1/3) sqrt(5 -+ 2 sqrt(10/7))`` and
    ``(322 +- 13 sqrt(70)) / 900`` are used; the rule is exact for
    polynomials up to degree 9.

    References:
        [EQ-INV-COSMO-003].

    """
    a = math.sqrt(10.0 / 7.0)
    inner = math.sqrt(5.0 - 2.0 * a) / 3.0
    outer = math.sqrt(5.0 + 2.0 * a) / 3.0
    w_in = (322.0 + 13.0 * math.sqrt(70.0)) / 900.0
    w_out = (322.0 - 13.0 * math.sqrt(70.0)) / 900.0
    return (
        (-outer, -inner, 0.0, inner, outer),
        (w_out, w_in, 128.0 / 225.0, w_in, w_out),
    )


_GL_NODES, _GL_WEIGHTS = _gauss_legendre_5()


def _gl_integrate(f: Callable[[float], float], a: float, b: float) -> float:
    """Integrate ``f`` over ``[a, b]`` with one 5-point Gauss-Legendre panel.

    References:
        [EQ-INV-COSMO-003].

    """
    half = 0.5 * (b - a)
    mid = 0.5 * (a + b)
    return half * math.fsum(
        w * f(mid + half * s) for s, w in zip(_GL_NODES, _GL_WEIGHTS, strict=True)
    )


def _real_sequence(values: object, name: str) -> tuple[float, ...]:
    """Validate a non-empty sequence of finite reals.

    References:
        Project validation policy [REF-PROBSTAT-VALIDATION].

    """
    if isinstance(values, (str, bytes)) or not isinstance(values, Sequence):
        raise TypeError(f"{name} must be a sequence of reals")
    out = tuple(_finite_real(v, name) for v in values)
    if not out:
        raise ValueError(f"{name} must not be empty")
    return out


class ExpansionHistoryModel:
    """Flat-FLRW expansion-history forward map with analytic derivatives.

    Unknowns ``x = (x_1..x_K, [Om], [log10 H0], [M])``: ``x_j = 1 + w`` in
    redshift bin ``j`` (so ``x = 0`` is LCDM; ``w = -1`` beyond the last
    edge) followed by the requested nuisance parameters in the fixed order
    ``omega_m``, ``log10_h0``, ``offset``. Observations are the distance
    moduli ``mu(z_i) + M`` or the Hubble rates ``H0 E(z_i)``. Radiation is
    neglected (low-redshift regime). Synthetic test bed only: nothing here is
    a statement about the real universe [EQ-INV-COSMO-001].

    The distance integral uses ``panels`` 5-point Gauss-Legendre panels in each
    smooth segment (segments are cut at the bin edges), and ``jvp``/``vjp``
    differentiate that very discrete sum, so they are exact derivatives of
    ``value`` up to roundoff [EQ-INV-COSMO-005].

    References:
        [EQ-INV-COSMO-001], [EQ-INV-COSMO-004], [EQ-INV-COSMO-005],
        [REF-HOGG-1999], [REF-CHEVALLIER-POLARSKI-2001], [REF-LINDER-2003].

    """

    __slots__ = (
        "_bin_edges",
        "_h0",
        "_lam",
        "_nuisance",
        "_obs",
        "_observable",
        "_omega_m",
        "_panels",
        "_redshifts",
        "_slot",
    )

    def __init__(
        self,
        redshifts: Sequence[float],
        basis: str = "piecewise_constant",
        bin_edges: Sequence[float] | None = None,
        *,
        omega_m: float = 0.3,
        h0: float = 70.0,
        observable: str = "distance_modulus",
        panels: int = 4,
        nuisance: Sequence[str] = (),
    ) -> None:
        """Validate the design and precompute the quadrature nodes.

        Args:
            redshifts: Observation redshifts ``z_i > 0`` (finite).
            basis: Only ``"piecewise_constant"`` is implemented.
            bin_edges: Strictly increasing edges ``0 = e_0 < ... < e_K`` of the
                ``K >= 1`` bins.
            omega_m: Matter density ``Om`` in ``(0, 1)`` (fixed value, or the
                nominal value when ``"omega_m"`` is a nuisance).
            h0: ``H0`` in km/s/Mpc (``> 0``; nominal when ``"log10_h0"`` is a
                nuisance).
            observable: ``"distance_modulus"`` or ``"hubble"``.
            panels: Gauss-Legendre panels (5 nodes each) per smooth segment.
            nuisance: Subset of ``("omega_m", "log10_h0", "offset")``;
                ``"offset"`` needs ``"distance_modulus"``.

        Raises:
            TypeError: If an argument has the wrong type.
            ValueError: If a value is out of range (``z <= 0``, ``Om`` outside
                ``(0, 1)``, edges not increasing from 0, unknown basis,
                observable or nuisance name, duplicate nuisance, ``offset``
                with the Hubble observable).

        References:
            [EQ-INV-COSMO-001], [EQ-INV-COSMO-002].

        """
        if basis != "piecewise_constant":
            raise ValueError("basis must be 'piecewise_constant'")
        if observable not in ("distance_modulus", "hubble"):
            raise ValueError("observable must be 'distance_modulus' or 'hubble'")
        zs = _real_sequence(redshifts, "redshifts")
        if min(zs) <= 0.0:
            raise ValueError("redshifts must be positive")
        if bin_edges is None:
            raise ValueError("bin_edges is required")
        edges = _real_sequence(bin_edges, "bin_edges")
        if len(edges) < 2 or edges[0] != 0.0:
            raise ValueError("bin_edges need at least two values starting at 0")
        if any(b <= a for a, b in zip(edges, edges[1:], strict=False)):
            raise ValueError("bin_edges must be strictly increasing")
        om = _finite_real(omega_m, "omega_m")
        if not 0.0 < om < 1.0:
            raise ValueError("omega_m must lie in (0, 1)")
        hubble0 = _real_positive(h0, "h0")
        count = _positive_int(panels, "panels")
        if isinstance(nuisance, (str, bytes)) or not isinstance(nuisance, Sequence):
            raise TypeError("nuisance must be a sequence of names")
        names = tuple(nuisance)
        if len(set(names)) != len(names) or any(
            n not in _NUISANCE_ORDER for n in names
        ):
            raise ValueError(
                "nuisance must be distinct names from 'omega_m', 'log10_h0', 'offset'"
            )
        if "offset" in names and observable != "distance_modulus":
            raise ValueError("the offset nuisance needs observable='distance_modulus'")
        self._redshifts = zs
        self._bin_edges = edges
        self._omega_m = om
        self._h0 = hubble0
        self._observable = observable
        self._panels = count
        self._nuisance = tuple(n for n in _NUISANCE_ORDER if n in names)
        k = len(edges) - 1
        self._slot = {n: k + i for i, n in enumerate(self._nuisance)}
        self._lam = tuple(
            math.log((1.0 + edges[j + 1]) / (1.0 + edges[j])) for j in range(k)
        )
        self._obs = tuple(self._build_nodes(z, observable == "hubble") for z in zs)

    def _zone(self, t: float) -> int:
        """Return the bin index of ``t`` (``K`` beyond the last edge).

        References:
            [EQ-INV-COSMO-002].

        """
        k = len(self._bin_edges) - 1
        if t > self._bin_edges[-1]:
            return k
        return min(bisect.bisect_right(self._bin_edges, t) - 1, k - 1)

    def _u(self, zone: int, t: float) -> float:
        """Return ``ln((1 + t) / (1 + e_zone))`` (``0`` beyond the last edge).

        References:
            [EQ-INV-COSMO-002].

        """
        if zone >= len(self._bin_edges) - 1:
            return 0.0
        return math.log((1.0 + t) / (1.0 + self._bin_edges[zone]))

    def _build_nodes(
        self, z: float, endpoint: bool
    ) -> tuple[tuple[int, float, float, float], ...]:
        """Return the quadrature nodes ``(zone, t, weight, u)`` of ``[0, z]``.

        With ``endpoint`` the single node is the endpoint ``z`` with
        weight one.

        References:
            [EQ-INV-COSMO-003].

        """
        if endpoint:
            zone = self._zone(z)
            return ((zone, z, 1.0, self._u(zone, z)),)
        cuts = [0.0] + [e for e in self._bin_edges[1:] if e < z] + [z]
        nodes: list[tuple[int, float, float, float]] = []
        for a, b in zip(cuts, cuts[1:], strict=False):
            zone = self._zone(0.5 * (a + b))
            width = (b - a) / self._panels
            for p in range(self._panels):
                lo = a + p * width
                half = 0.5 * width
                for s, w in zip(_GL_NODES, _GL_WEIGHTS, strict=True):
                    t = lo + half + half * s
                    nodes.append((zone, t, half * w, self._u(zone, t)))
        return tuple(nodes)

    @property
    def input_dimension(self) -> int:
        """Return ``n = K + len(nuisance)``.

        References:
            [EQ-INV-COSMO-001].

        """
        return len(self._bin_edges) - 1 + len(self._nuisance)

    @property
    def output_dimension(self) -> int:
        """Return the number of observations ``m``.

        References:
            [EQ-INV-COSMO-001].

        """
        return len(self._redshifts)

    @property
    def redshifts(self) -> tuple[float, ...]:
        """Return the observation redshifts.

        References:
            [EQ-INV-COSMO-001].

        """
        return self._redshifts

    @property
    def bin_edges(self) -> tuple[float, ...]:
        """Return the bin edges ``e_0 = 0 < ... < e_K``.

        References:
            [EQ-INV-COSMO-002].

        """
        return self._bin_edges

    @property
    def nuisance(self) -> tuple[str, ...]:
        """Return the nuisance names in coordinate order.

        References:
            [EQ-INV-COSMO-007].

        """
        return self._nuisance

    @property
    def observable(self) -> str:
        """Return ``"distance_modulus"`` or ``"hubble"``.

        References:
            [EQ-INV-COSMO-003].

        """
        return self._observable

    @property
    def parameter_names(self) -> tuple[str, ...]:
        """Return coordinate names ``x1..xK`` followed by the nuisance names.

        References:
            [EQ-INV-COSMO-001].

        """
        k = len(self._bin_edges) - 1
        return tuple(f"x{j + 1}" for j in range(k)) + self._nuisance

    def _check_x(self, x: Sequence[float]) -> tuple[float, ...]:
        """Validate the length and real type of ``x`` (non-finite allowed).

        References:
            Project validation policy [REF-PROBSTAT-VALIDATION].

        """
        if isinstance(x, (str, bytes)) or not isinstance(x, Sequence):
            raise TypeError("x must be a sequence of reals")
        values = tuple(x)
        for v in values:
            if isinstance(v, bool) or not isinstance(v, (int, float)):
                raise TypeError("x must contain real numbers")
        if len(values) != self.input_dimension:
            raise ValueError(f"x must have length {self.input_dimension}")
        return tuple(float(v) for v in values)

    def _split(
        self, x: tuple[float, ...]
    ) -> tuple[tuple[float, ...], float, float, float]:
        """Return ``(bins, Om, H0, offset)`` of a parameter vector.

        References:
            [EQ-INV-COSMO-001].

        """
        k = len(self._bin_edges) - 1
        om = x[self._slot["omega_m"]] if "omega_m" in self._slot else self._omega_m
        h0 = 10.0 ** x[self._slot["log10_h0"]] if "log10_h0" in self._slot else self._h0
        off = x[self._slot["offset"]] if "offset" in self._slot else 0.0
        return x[:k], om, h0, off

    def _prefix(self, bins: tuple[float, ...]) -> list[float]:
        """Return ``P_j = sum_{i<j} x_i Lambda_i`` for ``j = 0..K``.

        References:
            [EQ-INV-COSMO-002].

        """
        out = [0.0]
        for xi, lam in zip(bins, self._lam, strict=True):
            out.append(out[-1] + xi * lam)
        return out

    @staticmethod
    def _valid(x: tuple[float, ...], om: float) -> bool:
        """Return whether ``x`` is finite with ``Om`` in ``(0, 1)``.

        References:
            [EQ-INV-COSMO-001].

        """
        return all(math.isfinite(v) for v in x) and 0.0 < om < 1.0

    def _assemble(
        self, x: tuple[float, ...], derivatives: bool
    ) -> tuple[
        Vector, list[tuple[tuple[tuple[int, float, float], ...], float, float, float]]
    ]:
        """Return values and (optionally) the sparse Jacobian rows.

        Each row is ``(entries, d_om, d_log10h0, d_offset)`` with
        ``entries = ((zone, u, coef), ...)`` such that
        ``dvalue = sum coef (P'_zone + v_zone u) + ...`` (``P'`` the prefix of
        the direction).

        References:
            [EQ-INV-COSMO-004], [EQ-INV-COSMO-005].

        """
        bins, om, h0, off = self._split(x)
        prefix = self._prefix(bins)
        k = len(bins)

        def s_of(zone: int, u: float) -> float:
            """Return the exponent integral ``S = int (1+w)/(1+t)``.

            References:
                [EQ-INV-COSMO-002].

            """
            return prefix[zone] + (bins[zone] * u if zone < k else 0.0)

        values: list[float] = []
        rows: list[
            tuple[tuple[tuple[int, float, float], ...], float, float, float]
        ] = []
        for z, nodes in zip(self._redshifts, self._obs, strict=True):
            if self._observable == "hubble":
                zone, _, _, u = nodes[0]
                xx = math.exp(3.0 * s_of(zone, u))
                e = math.sqrt(om * (1.0 + z) ** 3 + (1.0 - om) * xx)
                values.append(h0 * e)
                if derivatives:
                    ds = h0 * 3.0 * (1.0 - om) * xx / (2.0 * e)
                    dom = h0 * ((1.0 + z) ** 3 - xx) / (2.0 * e)
                    rows.append((((zone, u, ds),), dom, _LN10 * h0 * e, 0.0))
                continue
            integral = 0.0
            entries: list[tuple[int, float, float]] = []
            dom_sum = 0.0
            for zone, t, wt, u in nodes:
                xx = math.exp(3.0 * s_of(zone, u))
                cube = (1.0 + t) ** 3
                e = math.sqrt(om * cube + (1.0 - om) * xx)
                integral += wt / e
                if derivatives:
                    inv3 = 1.0 / (e * e * e)
                    entries.append((zone, u, -1.5 * (1.0 - om) * xx * inv3 * wt))
                    dom_sum += -0.5 * inv3 * (cube - xx) * wt
            values.append(
                5.0 * math.log10((1.0 + z) * _C_KM_S / h0 * integral) + 25.0 + off
            )
            if derivatives:
                scale = 5.0 / (_LN10 * integral)
                rows.append(
                    (
                        tuple((zn, u, c * scale) for zn, u, c in entries),
                        dom_sum * scale,
                        -5.0,
                        1.0,
                    )
                )
        return tuple(values), rows

    def value(self, x: Sequence[float]) -> Vector:
        """Return the observables ``G(x)``.

        A parameter vector with a non-finite entry, ``Om`` outside ``(0, 1)``
        or an overflowing exponent returns an all-``nan`` vector (a failed
        forward evaluation that solvers treat as a rejected trial).

        Args:
            x: Parameters (length ``n``).

        Returns:
            Distance moduli (mag) or Hubble rates (km/s/Mpc).

        Raises:
            TypeError: If ``x`` is not a sequence of reals.
            ValueError: If ``x`` has the wrong length.

        References:
            [EQ-INV-COSMO-003], [EQ-INV-COSMO-009].

        """
        point = self._check_x(x)
        if not self._valid(point, self._split(point)[1]):
            return (math.nan,) * self.output_dimension
        try:
            return self._assemble(point, False)[0]
        except OverflowError:
            return (math.nan,) * self.output_dimension

    def _linearize(
        self, x: Sequence[float]
    ) -> list[tuple[tuple[tuple[int, float, float], ...], float, float, float]]:
        """Return the Jacobian rows at ``x`` or raise on an invalid point.

        References:
            [EQ-INV-COSMO-005].

        """
        point = self._check_x(x)
        if not self._valid(point, self._split(point)[1]):
            raise ValueError("x must be finite with omega_m in (0, 1)")
        try:
            return self._assemble(point, True)[1]
        except OverflowError as error:
            raise ValueError("the dark-energy exponent overflows at x") from error

    def jvp(self, x: Sequence[float], v: Sequence[float]) -> Vector:
        """Return the exact derivative of ``value`` along ``v``.

        Args:
            x: Base point (finite, ``Om`` in ``(0, 1)``).
            v: Direction (length ``n``).

        Returns:
            ``J(x) v``.

        Raises:
            TypeError: If an argument is not a sequence of reals.
            ValueError: On a wrong length or an invalid base point.

        References:
            [EQ-INV-COSMO-004], [EQ-INV-COSMO-005].

        """
        rows = self._linearize(x)
        direction = self._check_x(v)
        k = len(self._bin_edges) - 1
        pv = self._prefix(direction[:k])
        v_om = direction[self._slot["omega_m"]] if "omega_m" in self._slot else 0.0
        v_h = direction[self._slot["log10_h0"]] if "log10_h0" in self._slot else 0.0
        v_off = direction[self._slot["offset"]] if "offset" in self._slot else 0.0
        out: list[float] = []
        for entries, d_om, d_h, d_off in rows:
            total = d_om * v_om + d_h * v_h + d_off * v_off
            for zone, u, coef in entries:
                ds = pv[zone] + (direction[zone] * u if zone < k else 0.0)
                total += coef * ds
            out.append(total)
        return tuple(out)

    def vjp(self, x: Sequence[float], w: Sequence[float]) -> Vector:
        """Return the exact adjoint action ``J(x)' w``.

        Args:
            x: Base point (finite, ``Om`` in ``(0, 1)``).
            w: Weights (length ``m``).

        Returns:
            ``J(x)' w``.

        Raises:
            TypeError: If an argument is not a sequence of reals.
            ValueError: On a wrong length or an invalid base point.

        References:
            [EQ-INV-COSMO-004], [EQ-INV-COSMO-005].

        """
        rows = self._linearize(x)
        if isinstance(w, (str, bytes)) or not isinstance(w, Sequence):
            raise TypeError("w must be a sequence of reals")
        weights = [_finite_real(a, "w") for a in w]
        if len(weights) != self.output_dimension:
            raise ValueError(f"w must have length {self.output_dimension}")
        k = len(self._bin_edges) - 1
        full = [0.0] * (k + 1)
        part = [0.0] * k
        grad = [0.0] * self.input_dimension
        for wi, (entries, d_om, d_h, d_off) in zip(weights, rows, strict=True):
            for zone, u, coef in entries:
                full[zone] += wi * coef
                if zone < k:
                    part[zone] += wi * coef * u
            if "omega_m" in self._slot:
                grad[self._slot["omega_m"]] += wi * d_om
            if "log10_h0" in self._slot:
                grad[self._slot["log10_h0"]] += wi * d_h
            if "offset" in self._slot:
                grad[self._slot["offset"]] += wi * d_off
        tail = 0.0
        for i in range(k - 1, -1, -1):
            tail += full[i + 1]
            grad[i] = part[i] + self._lam[i] * tail
        return tuple(grad)

    def equation_of_state(
        self, x: Sequence[float], redshifts: Sequence[float]
    ) -> Vector:
        """Return ``w(z) = -1 + x_j`` in bin ``j`` (``-1`` beyond the edges).

        Args:
            x: Parameters (length ``n``).
            redshifts: Evaluation redshifts ``>= 0``.

        Returns:
            ``w`` at the requested redshifts.

        Raises:
            ValueError: If a redshift is negative or ``x`` has a wrong length.

        References:
            [EQ-INV-COSMO-002].

        """
        point = self._check_x(x)
        k = len(self._bin_edges) - 1
        out = []
        for z in _real_sequence(redshifts, "redshifts"):
            if z < 0.0:
                raise ValueError("redshifts must be non-negative")
            zone = self._zone(z)
            out.append(-1.0 + (point[zone] if zone < k else 0.0))
        return tuple(out)

    def dark_energy_factor(
        self, x: Sequence[float], redshifts: Sequence[float]
    ) -> Vector:
        """Return ``X(z) = exp(3 int_0^z (1 + w)/(1 + t) dt)`` exactly.

        Args:
            x: Parameters (length ``n``).
            redshifts: Evaluation redshifts ``>= 0``.

        Returns:
            ``X`` at the requested redshifts.

        Raises:
            ValueError: If a redshift is negative or ``x`` has a wrong length.

        References:
            [EQ-INV-COSMO-002].

        """
        point = self._check_x(x)
        bins = self._split(point)[0]
        prefix = self._prefix(bins)
        k = len(bins)
        out = []
        for z in _real_sequence(redshifts, "redshifts"):
            if z < 0.0:
                raise ValueError("redshifts must be non-negative")
            zone = self._zone(z)
            s = prefix[zone] + (bins[zone] * self._u(zone, z) if zone < k else 0.0)
            out.append(math.exp(3.0 * s))
        return tuple(out)

    def expansion_rate(self, x: Sequence[float], redshifts: Sequence[float]) -> Vector:
        """Return ``E(z) = sqrt(Om (1+z)^3 + (1-Om) X(z))``.

        Args:
            x: Parameters (length ``n``; ``Om`` from ``x`` if free).
            redshifts: Evaluation redshifts ``>= 0``.

        Returns:
            ``E`` at the requested redshifts.

        Raises:
            ValueError: If a redshift is negative, ``x`` has a wrong length or
                ``Om`` lies outside ``(0, 1)``.

        References:
            [EQ-INV-COSMO-001].

        """
        point = self._check_x(x)
        om = self._split(point)[1]
        if not 0.0 < om < 1.0:
            raise ValueError("omega_m must lie in (0, 1)")
        zs = _real_sequence(redshifts, "redshifts")
        factors = self.dark_energy_factor(point, zs)
        return tuple(
            math.sqrt(om * (1.0 + z) ** 3 + (1.0 - om) * f)
            for z, f in zip(zs, factors, strict=True)
        )

    def comoving_distance(self, x: Sequence[float]) -> Vector:
        """Return the discrete comoving distance ``D_C(z_i)`` in Mpc.

        Args:
            x: Parameters (length ``n``).

        Returns:
            ``(c / H0) sum_q w_q / E(t_q)`` at the model redshifts (with the
            model's quadrature).

        Raises:
            ValueError: On a wrong length or ``Om`` outside ``(0, 1)``.

        References:
            [EQ-INV-COSMO-003].

        """
        point = self._check_x(x)
        bins, om, h0, _ = self._split(point)
        if not 0.0 < om < 1.0:
            raise ValueError("omega_m must lie in (0, 1)")
        prefix = self._prefix(bins)
        k = len(bins)
        out = []
        for z in self._redshifts:
            total = 0.0
            for zone, t, wt, u in self._build_nodes(z, False):
                s = prefix[zone] + (bins[zone] * u if zone < k else 0.0)
                total += wt / math.sqrt(
                    om * (1.0 + t) ** 3 + (1.0 - om) * math.exp(3.0 * s)
                )
            out.append(_C_KM_S / h0 * total)
        return tuple(out)


