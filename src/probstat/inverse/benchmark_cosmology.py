_CPL_W0 = -0.9
_CPL_WA = -0.4
_OSC_AMPLITUDE = 0.2
_OSC_PERIOD = 0.5


def _one_plus_w(truth: str) -> Callable[[float], float]:
    """Return the function ``1 + w(z)`` of a named truth.

    References:
        [EQ-INV-COSMO-008].

    """
    if truth == "lcdm":
        return lambda z: 0.0
    if truth == "cpl":
        return lambda z: (1.0 + _CPL_W0) + _CPL_WA * z / (1.0 + z)
    return lambda z: _OSC_AMPLITUDE * math.sin(2.0 * math.pi * z / _OSC_PERIOD)


def _fine_distance_moduli(
    one_plus_w: Callable[[float], float],
    redshifts: Sequence[float],
    omega_m: float,
    h0: float,
) -> Vector:
    """Return ``mu(z_i)`` from a fine quadrature of the truth ``w`` itself.

    The exponent integral is accumulated by 5-point Gauss-Legendre panels of
    width ``z_max / 300`` (cumulative at panel edges, a partial panel inside
    each outer node) and the distance by the same panel grid, so no closed form
    and no coarse bin is involved [EQ-INV-COSMO-008].

    References:
        [EQ-INV-COSMO-008], [EQ-INV-COSMO-003].

    """
    zmax = max(redshifts)
    h = zmax / _FINE_PANELS

    def g(t: float) -> float:
        """Return the exponent integrand ``(1 + w)/(1 + t)``.

        References:
            [EQ-INV-COSMO-001].

        """
        return one_plus_w(t) / (1.0 + t)

    cumulative = [0.0]
    for p in range(_FINE_PANELS):
        cumulative.append(cumulative[-1] + _gl_integrate(g, p * h, (p + 1) * h))

    def inv_e(t: float) -> float:
        """Return ``1 / E(t)`` with the cumulative exponent integral.

        References:
            [EQ-INV-COSMO-001].

        """
        p = min(int(t / h), _FINE_PANELS - 1)
        s = cumulative[p] + _gl_integrate(g, p * h, t)
        return 1.0 / math.sqrt(
            omega_m * (1.0 + t) ** 3 + (1.0 - omega_m) * math.exp(3.0 * s)
        )

    out = []
    for z in redshifts:
        full = min(int(z / h), _FINE_PANELS)
        total = math.fsum(_gl_integrate(inv_e, p * h, (p + 1) * h) for p in range(full))
        if z > full * h:
            total += _gl_integrate(inv_e, full * h, z)
        out.append(5.0 * math.log10((1.0 + z) * _C_KM_S / h0 * total) + 25.0)
    return tuple(out)


def _project_truth(
    one_plus_w: Callable[[float], float], edges: Sequence[float]
) -> Vector:
    """Return bin values preserving each bin's exponent integral.

    ``x_j = int_{e_j}^{e_{j+1}} (1+w)/(1+t) dt / ln((1+e_{j+1})/(1+e_j))``.

    References:
        [EQ-INV-COSMO-008].

    """

    def g(t: float) -> float:
        """Return the exponent integrand ``(1 + w)/(1 + t)``.

        References:
            [EQ-INV-COSMO-001].

        """
        return one_plus_w(t) / (1.0 + t)

    out = []
    for a, b in zip(edges, edges[1:], strict=False):
        sub = 40
        total = math.fsum(
            _gl_integrate(g, a + (b - a) * i / sub, a + (b - a) * (i + 1) / sub)
            for i in range(sub)
        )
        out.append(total / math.log((1.0 + b) / (1.0 + a)))
    return tuple(out)


def synthetic_expansion_history_benchmark(
    *,
    truth: str = "lcdm",
    redshifts: Sequence[float] | None = None,
    bins: int | Sequence[float] = 8,
    sigma_mu: float | None = None,
    relative_noise: float | None = None,
    nuisance: Sequence[str] = (),
    omega_m: float = 0.3,
    h0: float = 70.0,
    offset: float = 0.15,
    count: int = 30,
    z_max: float = 1.5,
    panels: int = 4,
    prior_sd: float = 0.5,
    seed: int = 11,
) -> NonlinearBenchmark:
    """Return A02: SYNTHETIC supernova-like distance moduli and a coarse model.

    Supernova-like distance moduli are generated from a finer, independent
    representation of the truth and inverted with the coarse piecewise-constant
    :class:`ExpansionHistoryModel`. The truths are LCDM (``w = -1``), CPL
    (``w = -0.9 - 0.4 z/(1+z)``) and an oscillation ``w = -1 + 0.2
    sin(4 pi z)`` that the coarse bins cannot represent. This is a synthetic
    test bed: no real survey, covariance or constraint on the universe is
    implied, and the prior and the noise are declared assumptions
    [EQ-INV-COSMO-008].

    Nuisance coordinates follow the bins as in the model; their truth is
    ``omega_m``, ``log10(h0)`` and ``offset``, with Gaussian prior means
    ``omega_m``, ``log10(h0)`` and ``0`` and standard deviations ``0.05``,
    ``0.05`` and ``0.5``. The bins have prior mean ``0`` (LCDM) and standard
    deviation ``prior_sd``. With the offset and ``log10_h0`` both free the
    data cannot separate them (exact degeneracy) [EQ-INV-COSMO-007].

    Args:
        truth: ``"lcdm"``, ``"cpl"`` or ``"oscillating"``.
        redshifts: Observation redshifts (default: ``count`` points evenly in
            ``[0.05, z_max]``).
        bins: Number of uniform bins on ``[0, max z]`` or explicit edges
            (strictly increasing from 0, last edge ``>= max z``).
        sigma_mu: Absolute noise standard deviation in magnitudes (default
            ``0.1`` unless ``relative_noise`` is given).
        relative_noise: Noise level relative to ``||b|| / sqrt(m)``
            (exclusive with ``sigma_mu``).
        nuisance: Nuisance names as in :class:`ExpansionHistoryModel`.
        omega_m: True and nominal matter density in ``(0, 1)``.
        h0: True and nominal ``H0`` in km/s/Mpc.
        offset: True magnitude offset used when ``"offset"`` is a nuisance.
        count: Number of default redshifts (``>= 3``).
        z_max: Largest default redshift (``> 0.05``).
        panels: Quadrature panels per segment of the inversion model.
        prior_sd: Prior standard deviation of the bin values (``> 0``).
        seed: Root seed (only the noise is random).

    Returns:
        :class:`NonlinearBenchmark` with ``same_discretization`` true only for
        ``truth="lcdm"`` (data from the inverted model itself).

    Raises:
        TypeError: If an argument has the wrong type.
        ValueError: On an unknown truth, both noise options, or an invalid
            design.

    References:
        [EQ-INV-COSMO-008], [EQ-INV-COSMO-007], [REF-HOGG-1999],
        [REF-CHEVALLIER-POLARSKI-2001], [REF-LINDER-2003], [REF-STUART-2010].

    """
    if truth not in ("lcdm", "cpl", "oscillating"):
        raise ValueError("truth must be 'lcdm', 'cpl' or 'oscillating'")
    if sigma_mu is not None and relative_noise is not None:
        raise ValueError("give sigma_mu or relative_noise, not both")
    sd = _real_positive(prior_sd, "prior_sd")
    if redshifts is None:
        n_obs = _positive_int(count, "count", 3)
        top = _real_positive(z_max, "z_max")
        if top <= 0.05:
            raise ValueError("z_max must exceed 0.05")
        zs = tuple(0.05 + (top - 0.05) * i / (n_obs - 1) for i in range(n_obs))
    else:
        zs = _real_sequence(redshifts, "redshifts")
    if isinstance(bins, int) and not isinstance(bins, bool):
        n_bins = _positive_int(bins, "bins")
        edges = tuple(max(zs) * j / n_bins for j in range(n_bins + 1))
    else:
        edges = _real_sequence(bins, "bins")
        if edges[-1] < max(zs):
            raise ValueError("the last bin edge must reach the largest redshift")
    model = ExpansionHistoryModel(
        zs,
        "piecewise_constant",
        edges,
        omega_m=omega_m,
        h0=h0,
        panels=panels,
        nuisance=nuisance,
    )
    shift = offset if "offset" in model.nuisance else 0.0
    off = _finite_real(shift, "offset")
    one_plus_w = _one_plus_w(truth)
    bins_truth = (
        (0.0,) * (len(edges) - 1)
        if truth == "lcdm"
        else _project_truth(one_plus_w, edges)
    )
    extra_truth = {
        "omega_m": omega_m,
        "log10_h0": math.log10(h0),
        "offset": off,
    }
    x_true = bins_truth + tuple(extra_truth[n] for n in model.nuisance)
    if truth == "lcdm":
        exact = model.value(x_true)
    else:
        exact = tuple(
            mu + shift for mu in _fine_distance_moduli(one_plus_w, zs, omega_m, h0)
        )
    stream = resolve_stream(seed).child("A02")
    if relative_noise is not None:
        data, level, realized = _noise(exact, relative_noise, stream)
    else:
        level = _real_positive(0.1 if sigma_mu is None else sigma_mu, "sigma_mu")
        gen = stream.child("noise").generator()
        draws = [gen.gauss(0.0, 1.0) for _ in exact]
        data = tuple(b + level * e for b, e in zip(exact, draws, strict=True))
        realized = level * math.hypot(*draws)
    prior_means = {"omega_m": omega_m, "log10_h0": math.log10(h0), "offset": 0.0}
    prior_sds = {"omega_m": 0.05, "log10_h0": 0.05, "offset": 0.5}
    mean = (0.0,) * (len(edges) - 1) + tuple(prior_means[n] for n in model.nuisance)
    sds = (sd,) * (len(edges) - 1) + tuple(prior_sds[n] for n in model.nuisance)
    n = len(mean)
    prior = DenseCovariance(
        [[sds[i] ** 2 if i == j else 0.0 for j in range(n)] for i in range(n)]
    )
    pathologies: tuple[str, ...] = ("nonlinear", "weakly_identified_high_z")
    if model.nuisance:
        pathologies += ("nuisance_degeneracy",)
    if truth != "lcdm":
        pathologies += ("model_misspecification",)
    return NonlinearBenchmark(
        identifier="A02",
        name=f"synthetic expansion history ({truth}, {len(edges) - 1} bins)",
        model=model,
        data=data,
        noise=ScaledIdentityCovariance(len(zs), level * level),
        noise_level=level,
        realized_noise_norm=realized,
        truth=x_true,
        exact_data=exact,
        same_discretization=truth == "lcdm",
        prior_mean=mean,
        prior_covariance=prior,
        pathologies=pathologies,
        seeds=MappingProxyType({"noise": "A02/noise"}),
    )
